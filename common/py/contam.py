def dirty_shelves(nuclide, E, fwhm, roi=1.0, side=1.0, guard=0.6):
    """Линии, попадающие в фоновые полки вокруг пика E.

    Полки: [E-(roi+side)*ПШПВ, E-roi*ПШПВ] и [E+roi*ПШПВ, E+(roi+side)*ПШПВ].
    Своя линия E из проверки исключается (guard — допуск в долях ПШПВ).
    """
    lo0, lo1 = E - (roi + side) * fwhm, E - roi * fwhm
    hi0, hi1 = E + roi * fwhm, E + (roi + side) * fwhm
    out = []
    for L in LINES.get(nuclide, []):
        if abs(L - E) <= guard * fwhm:
            continue
        if lo0 <= L <= lo1 or hi0 <= L <= hi1:
            out.append(L)
    return out
