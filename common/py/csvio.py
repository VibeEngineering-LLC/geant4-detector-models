# -*- coding: utf-8 -*-
"""Запись и проверка таблиц results/ — ОДНА реализация на весь репозиторий.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Файлы в results/ читает внешний потребитель, и читает
он их своим кодом. Значит у записи два требования, а не одно:

1. правильный CSV (`csv.writer`), чтобы поле с запятой было закавычено;
2. отсутствие запятых в самих значениях, чтобы файл разбирался и наивным
   `split(",")` по позициям — кавычки такому читателю не помогают, а мешают.

Проверяется и то и другое: `check` следит за длиной строк, а сама запись
отказывается писать значение с запятой внутри. Второе правило нельзя вывести
из формата CSV — закавыченная запятая совершенно законна, — но потребитель нам
не подконтролен, и правило держится тем, что нарушить его молча нельзя.

ПОЧЕМУ ЗДЕСЬ, А НЕ В КАЖДОМ СКРИПТЕ. Сторож, скопированный в два места,
разъезжается: копия в export_curves не пропускала строки-комментариев, а копия
в tools/check_csv.py пропускала, и на здоровом файле со «шапкой из решёток»
первая упала бы. Это ровно тот дефект «одно правило в двух местах», который в
этом репозитории ловится третий раз подряд. Реализация одна, пользователи —
все: скрипты выгрузки, пересчёты и tools/check_csv.py.
"""
import csv

# Символы, запрещённые внутри значения, и как они называются в отказе.
NAMES = {",": "запятая", "\"": "кавычка", "\n": "перевод строки",
         "\r": "возврат каретки"}


def check(path):
    """[(номер строки, сколько полей)] у строк, не совпавших с шапкой.

    Строки-комментарии (начинаются с #) пропускаются: ими открывается
    большинство таблиц пересчёта.
    """
    with open(path, encoding="utf-8", newline="") as fh:
        rows = [(i + 1, r) for i, r in enumerate(csv.reader(fh))
                if r and not r[0].lstrip().startswith("#")]
    if not rows:
        return []
    n = len(rows[0][1])
    return [(i, len(r)) for i, r in rows if len(r) != n]


def write(path, header, rows, comments=()):
    """Записать таблицу и тут же перечитать её штатным парсером.

    header   — список имён столбцов;
    rows     — список словарей ИЛИ список кортежей/списков в порядке header;
    comments — строки пояснений, идут первыми как «# ...».

    Падает SystemExit, если собственный файл не читается ровно: лучше
    остановить пересчёт, чем отдать потребителю таблицу со сдвинутыми полями.
    """
    out = [[r[h] for h in header] if isinstance(r, dict) else list(r)
           for r in rows]
    # Запятая, кавычка и перевод строки внутри значения запрещены НАМЕРЕННО,
    # хотя csv.writer все три экранирует. Потребитель читает выгрузку своим
    # кодом и разбирает её по позициям: закавыченное поле для него — те же два
    # куска, только теперь с кавычками.
    #
    # Первой была заперта одна дверь из трёх. Кавычка внутри значения даёт
    # 25"" см посреди поля, а перевод строки — хуже всего: запись разъезжается
    # на две ФИЗИЧЕСКИЕ строки, и читатель, идущий по строкам файла, получает
    # вместо одной записи две. Сторож check этого не увидит вовсе: csv.reader
    # соберёт запись правильно, длина совпадёт с шапкой, и всё промолчит.
    for i, r in enumerate(out):
        for j, v in enumerate(r):
            bad = [c for c in ",\"\n\r" if c in str(v)]
            if bad:
                raise SystemExit(
                    "%s: %s внутри значения — строка %d, столбец «%s»: %r.\n"
                    "Уберите их (запятую — на точку с запятой): файл должен "
                    "читаться и наивным split(\",\") по строкам."
                    % (path, NAMES[bad[0]], i + 1, header[j], v))
    with open(path, "w", encoding="utf-8", newline="") as fh:
        for c in comments:
            for ln in str(c).split("\n"):
                fh.write("# " + ln + "\n" if ln else "#\n")
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(header)
        for r in out:
            w.writerow(r)
    bad = check(path)
    if bad:
        raise SystemExit(
            "%s: %d строк не совпали с шапкой (%d полей): %s.\n"
            "Скорее всего запятая внутри значения и запись без экранирования."
            % (path, len(bad), len(header), bad[:5]))
