# -*- coding: utf-8 -*-
"""Окно съёма площади в ДЕПОЗИТНОМ спектре — ОДНА реализация на репозиторий.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Правило `gross − side/(bg0−bg1)·(2·win+1)` жило в
четырёх местах: `point_recalc.area_sim`, `kit_recalc.area_sim`,
`summing.area_var` и через импорт в проверках. Починка окна полки была применена
к ОДНОМУ экземпляру, а объёмный пересчёт (Маринелли, Дента, Петри — то есть
опубликованные кривые) остался на прежнем дефектном правиле. Это тот же дефект
«одно правило в двух местах», который в этом репозитории ловится четвёртый раз;
здесь он был найден независимым аудитом, а не мной.

ДВА ИСПРАВЛЕНИЯ ПРОТИВ ПРЕЖНЕГО ПРАВИЛА.

1. **Окно полки `[E−25, E−10]`, а не `[E−30, E−10]`.** Прежнее захватывало пик
   вылета K-рентгена иода (`E−28,6`), занимавший 42…73 % его содержимого: полка
   вычиталась плоской подложкой, а внутри неё сидела дискретная особенность.
   Вся структура вылета лежит ниже `E−25` тождественно, при любом `E`
   (`E − E_выл < E − 25`, поскольку `E_выл ≥ 28,6` для иода и `≥ 30,97` для
   цезия), поэтому окно годится и для CsI.

2. **Окно задаётся В КАНАЛАХ, а не в кэВ.** Прежний множитель `2·win+1` считал
   13 каналов, тогда как фильтр `|e−E| ≤ 6` при шаге 1 кэВ отбирает 12 — но НЕ
   ВСЕГДА. Когда дробная часть `E/шаг` равна 0,5, оба края окна ложатся ТОЧНО в
   центры каналов и их снова 13. Это 10 % энергий, и среди узлов сетки такие
   есть: **59,5 и 3552,5 кэВ** — оба края паспортного диапазона. То есть ширина
   наблюдаемой скакала на 8 % в зависимости от дробной части энергии линии.
   Прежнее утверждение «в ±6,0 кэВ ровно 12 каналов при ЛЮБОЙ энергии» неверно
   (найдено аудитом; артефакт был виден в моём же выводе — провал в столбце
   поправки на 59,5 кэВ против соседей 56,1 и 88,0).

   Поэтому окно здесь — фиксированное ЧИСЛО каналов вокруг канала, ближайшего к
   `E`: 12 в пике и 15 в полке, всегда, множитель вычитания ровно `12/15 = 0,80`.
   Дробная часть энергии больше на ширину не влияет — не «исправлено число», а
   убран сам способ ошибиться.

ОБЛАСТЬ ДЕЙСТВИЯ. Только депозитные (неразмытые) спектры: окно заведомо шире
физического разброса и на разрешение НЕ нормируется. Размытые спектры снимаются
`becqmoni.area_broadened` / `peak_area` в долях ПШПВ — другая конвенция, и
смешивать их нельзя (см. common/docs/method-rules.md §2).
"""

WIN_KEV = 6.0    # полуширина окна пика, кэВ (номинально; счёт идёт в каналах)
BG0_KEV = 25.0   # дальний край полки: E-25, а не E-30 — вылет иода снаружи
BG1_KEV = 10.0   # ближний край полки


def _centre_index(E, bin_keV):
    """Индекс канала, чей ЦЕНТР ближе всего к E.

    Каналы стоят в `(i+0.5)·шаг` (см. main.cc: индекс — floor от энергии,
    печатается центр), поэтому ближайший центр — `round(E/шаг − 0.5)`.
    """
    return int(round(E / bin_keV - 0.5))


def channels(E, bin_keV=1.0, win_keV=WIN_KEV, bg0_keV=BG0_KEV,
             bg1_keV=BG1_KEV, n_chan=None):
    """Границы окон В ИНДЕКСАХ каналов: (пик i0, i1, полка j0, j1), полуоткрыто.

    Число каналов постоянно по построению: `n_peak = round(2·win/шаг)`,
    `n_side = round((bg0−bg1)/шаг)`. Полка примыкает к окну пика слева с
    зазором `bg1`, как и прежде.

    `n_chan` — сколько каналов в гистограмме на самом деле. Если задан, окно
    обрезается сверху, и `area()` об этом СКАЖЕТ. Снизу обрезка была всегда
    (`max(0, i0)`), сверху её не было вовсе: у линии вблизи верхнего края
    гистограммы окно уезжало за её конец, отсутствующие каналы попадали в
    `n_peak`, и вычиталось больше, чем следует, — молча. Текущей сеткой такая
    линия недостижима (верхний узел 3552,5 при гистограмме до 3600), поэтому
    дефект латентный; чинится он до того, как сетку расширят, а не после.
    """
    n_peak = int(round(2 * win_keV / bin_keV))
    n_side = int(round((bg0_keV - bg1_keV) / bin_keV))
    c = _centre_index(E, bin_keV)
    i0 = c - n_peak // 2
    i1 = i0 + n_peak
    j1 = _centre_index(E - bg1_keV, bin_keV) + 1
    j0 = j1 - n_side
    if n_chan is not None:
        i1 = min(i1, n_chan)
        j1 = min(j1, n_chan)
    return i0, i1, j0, j1


def right_shelf(E, bin_keV=1.0, bg0_keV=BG0_KEV, bg1_keV=BG1_KEV):
    """Границы ПРАВОЙ полки в индексах каналов, полуоткрыто.

    Зеркало левой: левая КОНЧАЕТСЯ каналом, ближайшим к `E−bg1`
    (включительно), правая НАЧИНАЕТСЯ каналом, ближайшим к `E+bg1`, и
    тянется на те же `n_side` каналов вправо (то есть чуть дальше
    `E+bg0−шаг`, а не «до канала, ближайшего к E+bg0»). Вылета K-рентгена
    справа от пика нет (он всегда ниже `E`), поэтому у правой полки нет и
    причины для отступа 25 — но окно берётся тем же числом каналов, чтобы
    обе полки были одной ширины и однородной наблюдаемой.
    """
    n_side = int(round((bg0_keV - bg1_keV) / bin_keV))
    k0 = _centre_index(E + bg1_keV, bin_keV)
    return k0, k0 + n_side


def area(hist, E, bin_keV=1.0, win_keV=WIN_KEV, bg0_keV=BG0_KEV,
         bg1_keV=BG1_KEV, detail=None, n_chan=None, side="left"):
    """Чистая площадь пика в депозит-спектре: gross − плотность полки · n_пика.

    `hist` — {центр канала: отсчёты}, только НЕПУСТЫЕ каналы (так пишет модель),
    поэтому суммирование идёт по индексам, а не по ключам: пустой канал обязан
    входить в ЧИСЛО каналов, иначе плотность полки завышается.

    `detail` — если передан dict, туда кладутся фактические границы и суммы:
    без этого «отказ, замаскированный под норму» (полка вне сетки, нулевой
    знаменатель) выглядел бы обычным числом.

    `side` — "left" (штатно) или "both": плотность подложки как СРЕДНЯЯ по
    левой и правой полкам. Симметричный режим нужен там, где подложка слева
    и справа устроена по-разному и односторонняя полка смещает результат:
    у Co-60 левая полка каждой линии стоит на структуре от соседней линии
    (tcc_selfcheck), у сравнения shield/bare обратное рассеяние меняет
    континуум именно слева (shield_role). Это ИНАЯ наблюдаемая — смешивать
    режимы в одной таблице нельзя, объявление берётся из declare(side=...).
    """
    # Границы считаются ДВАЖДЫ одной и той же функцией: без обрезки и с ней.
    # Переписать формулу «сколько каналов было бы» рядом значило бы завести
    # вторую копию правила — тот самый дефект, против которого этот модуль.
    _, full_i1, _, _ = channels(E, bin_keV, win_keV, bg0_keV, bg1_keV)
    i0, i1, j0, j1 = channels(E, bin_keV, win_keV, bg0_keV, bg1_keV, n_chan)
    if n_chan is not None and full_i1 > n_chan:
        # Обрезка окна пика сверху МЕНЯЕТ наблюдаемую: часть пика в сумму не
        # входит, а обрезанное окно всё равно называется «+-6 кэВ». Отказ
        # громкий намеренно — с правильной гистограммой этого не бывает, а
        # если случилось, число молча использовать нельзя.
        raise SystemExit(
            "peakwin.area: окно пика для E = %.3f кэВ выходит за гистограмму"
            " (нужен канал %d при %d каналах).\n"
            "Обрезанное окно — уже другая наблюдаемая; расширьте гистограмму"
            " прогона или исключите линию." % (E, full_i1 - 1, n_chan))
    lo = max(0, i0)
    gross = sum(c for e, c in hist.items()
                if lo * bin_keV <= e - 0.5 * bin_keV < i1 * bin_keV)
    js = max(0, j0)
    sideL = sum(c for e, c in hist.items()
                if js * bin_keV <= e - 0.5 * bin_keV < j1 * bin_keV)
    n_peak, n_side = i1 - lo, j1 - js
    if detail is not None:
        detail.update(i0=lo, i1=i1, j0=js, j1=j1, n_peak=n_peak,
                      n_side=n_side, gross=gross, side=sideL)
    if n_side <= 0:
        if detail is not None:
            detail.update(mode="no_shelf")
        return gross
    if side == "both":
        k0, k1 = right_shelf(E, bin_keV, bg0_keV, bg1_keV)
        if n_chan is not None and k1 > n_chan:
            # Обрезанная правая полка — уже другая наблюдаемая (короче левой,
            # средняя плотность смещена). Отказ громкий, как у окна пика.
            raise SystemExit(
                "peakwin.area(side='both'): правая полка для E = %.3f кэВ"
                " выходит за гистограмму (нужен канал %d при %d каналах)."
                % (E, k1 - 1, n_chan))
        sideR = sum(c for e, c in hist.items()
                    if k0 * bin_keV <= e - 0.5 * bin_keV < k1 * bin_keV)
        # Плотности считаются КАЖДАЯ по своему числу каналов: при E вблизи
        # нуля левая полка обрезается снизу (js > j0) и её n_side короче
        # правой — общая нормировка на левый n_side завышала бы плотность
        # (найдено ревью задачи 151; на текущих энергиях >=45 кэВ случай
        # недостижим, чинится способ ошибиться, а не проявившийся промах).
        dens = 0.5 * (sideL / n_side + sideR / (k1 - k0))
        if detail is not None:
            detail.update(k0=k0, k1=k1, n_side_r=k1 - k0, side_r=sideR,
                          mode="shelf_both")
        return gross - dens * n_peak
    if detail is not None:
        detail.update(mode="shelf")
    return gross - sideL / n_side * n_peak


def declare(bin_keV=1.0, win_keV=WIN_KEV, bg0_keV=BG0_KEV, bg1_keV=BG1_KEV,
            side="left"):
    """Строки объявления наблюдаемой, СОБРАННЫЕ ИЗ ТЕХ ЖЕ констант.

    Объявление, набранное руками рядом с кодом, рассинхронизируется с ним при
    первой же правке — и рассинхронизировалось: правка `bg0` с 30 на 25 оставила
    в объявлении «[E−30; E−10]», то есть штамп начал ЛГАТЬ ровно там, где
    заводился против лжи (найдено аудитом). Поэтому строки строятся здесь.
    """
    i0, i1, j0, j1 = channels(1000.0, bin_keV, win_keV, bg0_keV, bg1_keV)
    if side == "both":
        # без запятых: значения штампа идут в CSV одной строкой (stamp.lines)
        shelf = ("симметричная [E-%.0f; E-%.0f] и [E+%.0f; E+%.0f] средней"
                 " плотностью; %d каналов каждая; множитель вычитания %d/%d"
                 % (bg0_keV, bg1_keV, bg1_keV, bg0_keV, j1 - j0,
                    i1 - i0, j1 - j0))
    else:
        shelf = ("односторонняя [E-%.0f; E-%.0f] = %d каналов;"
                 " множитель вычитания %d/%d"
                 % (bg0_keV, bg1_keV, j1 - j0, i1 - i0, j1 - j0))
    return {
        "window": "+-%.1f кэВ = %d каналов (счёт в каналах; ширина не зависит"
                  " от дробной части E)" % (win_keV, i1 - i0),
        "shelf": shelf,
        "blurred": "нет (депозит как есть; на ПШПВ не нормируется)",
    }
