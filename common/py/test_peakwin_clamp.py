# -*- coding: utf-8 -*-
"""Обрезка окна съёма сверху обязана быть слышной (хвост задачи 133).

Снизу окно обрезалось всегда (`max(0, i0)`), сверху — не обрезалось вовсе: у
линии вблизи верхнего края гистограммы окно пика уезжало за её конец,
отсутствующие каналы всё равно попадали в `n_peak`, и вычиталось больше, чем
следует. Число выходило меньше истинного и ничем себя не выдавало.

Тест закрепляет три вещи:
  1. без `n_chan` поведение не изменилось — иначе правка тихо переписала бы
     все опубликованные числа;
  2. `n_chan` на безопасной линии тоже ничего не меняет;
  3. на линии у края — громкий отказ, а не обрезанная сумма под прежним
     именем «±6 кэВ».

Запуск: python common/py/test_peakwin_clamp.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import peakwin  # noqa: E402

N_CHAN = 3600


def _hist(peak_at):
    """Ровная подложка плюс узкий пик — минимальный годный вход."""
    h = {i + 0.5: 10.0 for i in range(N_CHAN)}
    for i in range(int(peak_at) - 5, int(peak_at) + 6):
        h[i + 0.5] = 1000.0
    return h


def main():
    bad = []

    h = _hist(2614.5)
    a_plain = peakwin.area(h, 2614.511)
    a_clamp = peakwin.area(h, 2614.511, n_chan=N_CHAN)
    if a_plain != a_clamp:
        bad.append("безопасная линия 2614;5: %.3f без n_chan против %.3f с ним"
                   % (a_plain, a_clamp))

    # Верхний узел рабочей сетки — обрезки быть не должно.
    h = _hist(3552.5)
    if peakwin.area(h, 3552.5) != peakwin.area(h, 3552.5, n_chan=N_CHAN):
        bad.append("узел сетки 3552;5 обрезается — гистограмма мала")

    # Линия у самого края: обрезка обязана быть отказом, а не числом.
    h = _hist(3596.0)
    try:
        peakwin.area(h, 3598.0, n_chan=N_CHAN)
        bad.append("линия у края прошла МОЛЧА — окно обрезано без отказа")
    except SystemExit:
        pass

    # Без n_chan та же линия по-прежнему считается (обратная совместимость):
    # сторож включается явной передачей числа каналов, а не сам.
    try:
        peakwin.area(h, 3598.0)
    except SystemExit:
        bad.append("без n_chan линия у края стала падать — сломана"
                   " обратная совместимость")

    if bad:
        print("ПРОВАЛ:")
        for b in bad:
            print("  " + b)
        return 1
    print("peakwin: обрезка окна сверху слышна; поведение без n_chan"
          " не изменилось — 4 проверки пройдены.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
