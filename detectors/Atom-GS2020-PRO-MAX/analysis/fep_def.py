# #GS-66 (оператор 09.10 «Вычесть континуум»): отсчёты пика полного поглощения БЕЗ рассеянного континуума под пиком.
# Бины 1 кэВ, центры x.5. Пик при E лежит в бине floor(E)+0.5; при целом E делится округлением с бином ниже.
# Читают: make_dataset_marinelli1l (кривая набора), gs64_density_corr (поправка f) — определение одно.
import math


def fep_net(h, E):
    """h: {центр бина: отсчёты edep}. Возвращает (k_net, дисперсия k_net). Континуум на 1 кэВ — по бину ниже окна пика."""
    if abs(E - round(E)) < 0.02:   # целое E: пик в [E−1,E)+[E,E+1), в них 1 кэВ континуума ≈ бин [E−2,E−1)
        b = round(E) + 0.5
        return h.get(b, 0) + h.get(b - 1, 0) - h.get(b - 2, 0), h.get(b, 0) + h.get(b - 1, 0) + h.get(b - 2, 0)
    b = math.floor(E) + 0.5
    phi = E - math.floor(E)   # бин с E содержит φ кэВ континуума ниже E; бин ниже — чистый континуум
    return h.get(b, 0) - phi * h.get(b - 1, 0), h.get(b, 0) + phi * phi * h.get(b - 1, 0)
