# -*- coding: utf-8 -*-
"""Кривая эффективности по ППП из расчётных спектров сетки.

Наблюдаемая объявляется явно. Эффективность здесь — АБСОЛЮТНАЯ ПО ПИКУ ПОЛНОГО
ПОГЛОЩЕНИЯ на 4pi: доля испущенных источником квантов, дающих отсчёт в пике.
Прогон идёт конусом, поэтому счёт делится на N первичных и умножается на долю
телесного угла конуса, которую печатает сам exe (solid_angle_frac).

ПУБЛИКУЕТСЯ ОДНА величина по пику:

  eps_peak     — СТРОГАЯ: в нерасплывшемся модельном спектре события с полным
                 поглощением попадают в канал E0 (при целой E0 расщепляются на
                 два соседних из-за плавающей точки), поэтому счёт берётся
                 окном в три канала с вычетом континуума по НАБЛЮДАЕМОМУ
                 каналу ниже окна. Полок и исключений вылета здесь нет, окно
                 не подбирается — но окно есть, и континуум под линией не
                 пренебрежим: на мягком крае он даёт единицы процентов при
                 статистике около 0,25 %. Величина вычтенного пишется
                 отдельным столбцом.

ОКОННАЯ величина `eps_peak_win` СНЯТА С ПУБЛИКАЦИИ (аудит кода 06.08.2026).
Её левая полка `[E−2,5·ПШПВ; E−1,25·ПШПВ]` на жёстких узлах садится на
размытый комптоновский край: на 3000 кэВ плотность полки на порядок выше
плотности под самим пиком, вычитается примерно в 12 раз больше, чем там есть,
и смещение относительно строгой доходит до десятков процентов, меняя знак по
диапазону. Это ровно тот случай, который `method-rules.md` запрещает для любой
полочной конвенции: «в полке нет известных особенностей». Отдельно: исключение
каналов вылета съедало левую полку до одного уцелевшего канала на 100 кэВ, а
метка `left_thin` ставилась без всякого отката, тогда как общий модуль
(`becqmoni.area_broadened`, `peakwin.peak_area`) по такой же проверке
запускает реальный откат — то есть здесь был регресс относительно общего
модуля.

Пока конвенция не заменена на общий модуль, сравнивать расчёт с кривыми,
построенными по измерениям, этим файлом НЕЛЬЗЯ: величины такой конвенции в нём
нет. Строгая величина отвечает на другой вопрос и подменять её не может.

ПШПВ прибора взята из СОБСТВЕННОЙ записи Cs-137 (подгонка «гауссиана +
линейная подложка», `compare_cs137.py`): 41,60 кэВ на 661,657 кэВ, то есть
6,4 %. Закон ПШПВ(E) = ПШПВ(662)*sqrt(E/661,657) — приближение по одной
опорной точке; на краях диапазона оно даёт систематику формы пика, но не
площади, пока окно берётся в долях самой ПШПВ.

    python analysis/export_curve.py <каталог со спектрами> [<выход.csv>]
"""
import os
import sys
import math
import glob

import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.normpath(os.path.join(_HERE, "..", "..", "..",
                                                 "common", "py")))
import becqmoni as bm   # noqa: E402

FWHM_662 = 41.60           # собственная запись Cs-137, подгонка пика
ESCAPES = (28.6, 30.97)    # K-вылет иода и цезия, кэВ


def win_area(wide, e0, fwhm, roi=1.25):
    """НЕ ВЫЗЫВАЕТСЯ И НЕ ПУБЛИКУЕТСЯ — оставлено как предмет переделки.

    Конвенция признана негодной аудитом 06.08.2026 (полка садится на размытый
    комптоновский край, см. заголовок модуля). Заменять не заплаткой, а
    переводом на общий модуль `peakwin`/`becqmoni`, чтобы не плодить пятую
    реализацию съёма. До этого функция мертва намеренно: живой вызов сразу
    вернул бы смещённую величину в публикуемый файл.

    Оконная площадь по размытому МОДЕЛЬНОМУ спектру. -> (площадь, режим).

    Полка берётся ТОЛЬКО СЛЕВА. Причина не в удобстве: в моноэнергетическом
    расчётном спектре депозитов выше E0 не бывает по построению (проверено —
    верхний непустой канал ровно floor(E0)), поэтому справа от пика лежит не
    континуум, а хвост САМОЙ гауссианы размытия. Усреднение двух полок, как в
    `becqmoni.area_broadened`, делит подложку пополам независимо от того, есть
    ли справа континуум, и результат уезжает на +9…+10 % там, где обе полки
    уцелели, и на +6…−1 % там, где левой не осталось. Тот же код на ИЗМЕРЕННОМ
    спектре, где континуум справа есть, — это уже другая конвенция, а
    сравнивать модель с измеренной кривой полагалось именно этой величиной.

    Каналы пиков вылета характеристического рентгеновского излучения кристалла
    из полки исключаются: иначе на мягком крае полка садится на собственную
    особенность спектра.
    """
    w = roi * fwhm
    lo, hi = int(round(e0 - w)), int(round(e0 + w))
    lo, hi = max(0, lo), min(len(wide), hi)
    if hi <= lo:
        return 0.0, "empty"
    g = float(wide[lo:hi].sum())
    sl0, sl1 = int(round(e0 - 2.5 * fwhm)), lo
    sl0 = max(0, sl0)
    keep = []
    for i in range(sl0, sl1):
        if any(abs(i - (e0 - esc)) <= 0.5 * fwhm for esc in ESCAPES):
            continue
        keep.append(wide[i])
    if not keep:
        return g, "no_shelf"
    dens = sum(keep) / len(keep)
    n_full = sl1 - sl0
    mode = "left" if len(keep) >= 0.25 * n_full else "left_thin"
    return g - dens * (hi - lo), mode


def read_model(path):
    head, dic = {}, {}
    with open(path, encoding="utf-8") as f:
        for ln in f:
            if ln.startswith("#"):
                if "=" in ln:
                    k, v = ln[1:].split("=", 1)
                    head[k.strip()] = v.strip()
            elif "," in ln and not ln.startswith("E_keV"):
                a, b = ln.split(",")
                dic[float(a)] = dic.get(float(a), 0.0) + float(b)
    return dic, head


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        print("Нет каталога спектров. Сначала прогон:\n"
              "  asn16 curve_point_end10cm.mac\n"
              "он кладёт спектры в подкаталог spectra/ каталога сборки.")
        return 2
    src = sys.argv[1]
    files = sorted(glob.glob(os.path.join(src, "*.csv")))
    files = [f for f in files if not f.endswith("_emit.csv")]
    if not files:
        print("В %s нет спектров." % src)
        return 2

    rows, stamps = [], set()
    # Постановка прогона собирается ИЗ САМИХ СПЕКТРОВ, а не пишется в код.
    # Прежде и шапка выходного файла, и имя по умолчанию были захардкожены
    # под торцевую геометрию: кривая «на грань» подписывалась торцевой, а
    # запуск без второго аргумента молча клал её поверх торцевой. Обе ошибки
    # найдены независимым аудитом 05.08.2026, обе относятся к тому же классу,
    # что и «наблюдаемая без указания грани не определена».
    setup = {}
    for f in files:
        dic, head = read_model(f)
        e0 = float(head["E_prim_keV"])
        n = int(head["N_primaries"])
        frac = float(head["solid_angle_frac"])
        stamps.add(head.get("src_sha1", "?"))
        for k in ("run_args", "solid_angle_frac", "front_face_z_mm",
                  "work_face_y_mm"):
            setup.setdefault(k, set()).add(head.get(k, "?"))
        total = sum(dic.values())
        fwhm = FWHM_662 * math.sqrt(e0 / 661.657)
        # СТРОГАЯ площадь: канал полного поглощения нерасплывшегося спектра.
        # Гистограмма пишется как b = int(E/шаг), центр канала b + 0,5 —
        # поэтому канал ищется тем же floor, а не округлением к ближайшему:
        # при целом E0 (40, 50, 80 ...) ближайших каналов ДВА на равном
        # расстоянии, и выбор «первого попавшегося» уводил счёт в соседний
        # канал континуума. Расхождение доходило до трёх раз и выглядело как
        # физика: узлы с дробной энергией (59,541; 122,061; 661,657) давали
        # правильное значение, целые — заниженное.
        #
        # Берётся не один канал, а ±1,5 кэВ: сумма энерговыделений равна E0
        # лишь с точностью плавающей точки, и часть событий при целом E0
        # попадает в канал ниже. Континуум непосредственно под линией
        # пренебрежимо мал (рассеяние на малые углы), поэтому окно в три
        # канала конвенцией не является.
        kc = math.floor(e0) + 0.5
        fep_raw = sum(c for e, c in dic.items() if abs(e - kc) <= 1.5)
        # Континуум под линией. Без вычета строгая величина смещена
        # ОДНОСТОРОННЕ вверх: два независимых аудита намерили 3–4 % на мягком
        # краю при заявленной статистике 0,25 %, то есть смещение больше своей
        # же погрешности более чем на порядок.
        #
        # Вычитается НЕ по всем трём каналам окна, а по той их части, которая
        # физически может содержать континуум: депозита ВЫШЕ E0 не бывает,
        # поэтому канал kc+1 пуст всегда (проверено по всем 50 спектрам), в
        # канале kc континууму доступна лишь доля [floor(E0), E0), а полностью
        # континуум занимает только канал kc−1. Отсюда ширина вычета
        # 1 + дробная часть E0 канала.
        #
        # Плотность берётся ПО НАБЛЮДАЕМОМУ каналу, а не экстраполяцией.
        #
        # Прежняя версия строила линейную экстраполяцию по kc−4 .. kc−2 из
        # посылки «континуум под линией — круто растущий хвост». Посылка
        # эмпирически неверна: на 122,061 канальный ряд 1122 / 1031 / 838 / 590
        # монотонно ПАДАЕТ к линии, и падает на всех жёстких узлах. Хуже того,
        # плечо экстраполяции (2–3 канала) превышало базу (2 канала), а при
        # трёх равноотстоящих точках средний канал в наклон не входит вовсе.
        # Смещение измерено там, где истина наблюдаема (см. ниже): вычет
        # завышался на +23,0 % (59,541), +20,8 % (122,061), +166,7 % (661,657),
        # то есть строгая площадь занижалась ОДНОСТОРОННЕ и больше своей же
        # заявленной погрешности (найдено аудитом кода 06.08.2026).
        #
        # При ДРОБНОЙ E0 канал kc−1 чист от пика по построению: события полного
        # поглощения кладутся в канал, содержащий E0, а сюда попасть не могут.
        # Значит его содержимое — не оценка, а измерение, и оно берётся как
        # есть. Плотность континуума под самой линией оценивается тем же
        # каналом: он ближайший чистый, а на масштабе одного канала континуум
        # гладкий.
        #
        # При ЦЕЛОЙ E0 канал kc−1 заражён расщеплением пика по плавающей точке,
        # поэтому берётся ближайший заведомо чистый kc−2. Экстраполяции нет ни
        # в одной ветви: любая оценка вне наблюдаемых каналов возвращает
        # односторонность, ради устранения которой правка и делается.
        frac_lo = e0 - math.floor(e0)      # доля канала линии ниже E0
        # Вычитаемая область: канал kc−1 целиком плюс доля frac_lo канала kc.
        dens = (dic.get(kc - 1.0, 0.0) if frac_lo > 1e-9
                else dic.get(kc - 2.0, 0.0))
        fep_bg = dens * (1.0 + frac_lo)
        fep = fep_raw - fep_bg
        if fep <= 0:
            print("  ! %s: строгая площадь не положительна при E0 = %.1f, "
                  "узел пропущен" % (os.path.basename(f), e0))
            continue
        # Дисперсия вычтенной подложки. Вычет её не уменьшает: обе части
        # пуассоновские и независимые (kc−1 либо kc−2 в окно площади не входит
        # своим счётом дважды). Множитель (1+frac_lo) входит в квадрате.
        var_bg = dens * (1.0 + frac_lo) ** 2
        # Оконная величина (eps_peak_win) СНЯТА С ПУБЛИКАЦИИ, см. шапку файла и
        # README: её левая полка на жёстких узлах садится на размытый
        # комптоновский край, смещение доходит до десятков процентов.
        rows.append(dict(E=e0, fep=fep, fep_raw=fep_raw, fep_bg=fep_bg,
                         var_bg=var_bg, n=n, frac=frac,
                         total=total, fwhm=fwhm))

    if len(stamps) > 1:
        print("! В каталоге спектры от РАЗНЫХ сборок: %s\n"
              "  Кривая по смешанным прогонам недействительна." %
              ", ".join(sorted(stamps)))
        return 1
    for k, v in setup.items():
        if len(v) > 1:
            print("! В каталоге спектры с РАЗНОЙ постановкой: %s = %s\n"
                  "  Одной кривой они не образуют." % (k, ", ".join(sorted(v))))
            return 1

    mac = setup["run_args"].pop()
    tag = os.path.splitext(mac)[0].replace("curve_point_", "")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        _HERE, "..", "results", "eff_point_%s.csv" % tag)
    out = os.path.normpath(out)

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="") as g:
        g.write("# AtomSpectra Nano 16 PRO, точечный источник на оси кристалла\n")
        g.write("# постановка взята из шапок спектров, а не вписана здесь:\n")
        g.write("#   run_args = %s\n" % mac)
        g.write("#   solid_angle_frac = %s\n" % setup["solid_angle_frac"].pop())
        g.write("#   front_face_z_mm = %s, work_face_y_mm = %s\n"
                % (setup["front_face_z_mm"].pop(),
                   setup["work_face_y_mm"].pop()))
        g.write("# наблюдаемая: абсолютная эффективность по ППП на 4pi\n")
        g.write("# src_sha1 = %s\n" % stamps.pop())
        g.write("# fwhm_662_keV = %.2f  (собственная запись Cs-137)\n"
                % FWHM_662)
        g.write("# escapes_keV = %s\n" % ", ".join("%.2f" % e for e in ESCAPES))
        g.write("# подложка под линией: содержимое НАБЛЮДАЕМОГО канала (kc-1\n")
        g.write("#   при дробной E0, kc-2 при целой) на ширину 1+дробная часть\n")
        g.write("#   E0. Экстраполяции нет: прежняя линейная завышала вычет на\n")
        g.write("#   20-170 %% там, где истина наблюдаема (аудит 06.08.2026)\n")
        g.write("# d_eps_peak = статистика сырого окна И дисперсия подложки\n")
        g.write("# eps_peak — строгая (канал полного поглощения), ЕДИНСТВЕННАЯ\n")
        g.write("#   публикуемая величина по пику\n")
        g.write("# ОКОННАЯ величина eps_peak_win СНЯТА С ПУБЛИКАЦИИ: её левая\n")
        g.write("#   полка на жёстких узлах садится на размытый комптоновский\n")
        g.write("#   край, смещение относительно строгой доходит до десятков\n")
        g.write("#   процентов и меняет знак по диапазону. До замены конвенции\n")
        g.write("#   на общий модуль сравнивать с измеренными кривыми нечем\n")
        g.write("E_keV,eps_peak,d_eps_peak,eps_total,fep_counts,"
                "fep_raw_counts,fep_bg_counts,N_primaries,"
                "solid_angle_frac,fwhm_keV\n")
        for r in rows:
            eps = r["fep"] / r["n"] * r["frac"]
            # Погрешность — по СЫРОМУ счёту в окне ПЛЮС дисперсия вычтенной
            # подложки: вычет её не уменьшает. Прежняя версия обещала второе
            # слагаемое комментарием, а формулы не имела (аудит 06.08.2026).
            d = (eps * math.sqrt(max(r["fep_raw"], 1.0) + r["var_bg"])
                 / max(r["fep"], 1.0))
            epst = r["total"] / r["n"] * r["frac"]
            g.write("%.3f,%.6e,%.3e,%.6e,%.1f,%.0f,%.1f,%d,%.8f,%.2f\n"
                    % (r["E"], eps, d, epst, r["fep"], r["fep_raw"],
                       r["fep_bg"], r["n"], r["frac"], r["fwhm"]))
    print("записано: %s  (%d узлов, постановка %s)" % (out, len(rows), mac))
    print("%9s %12s %8s %7s %12s %7s"
          % ("E, кэВ", "eps ППП", "стат,%", "подл,%", "eps полная", "пик/пол"))
    for r in rows:
        eps = r["fep"] / r["n"] * r["frac"]
        epst = r["total"] / r["n"] * r["frac"]
        print("%9.1f %12.4e %7.2f %7.2f %12.4e %7.3f"
              % (r["E"], eps,
                 100.0 * math.sqrt(max(r["fep_raw"], 1.0) + r["var_bg"])
                 / max(r["fep"], 1.0),
                 100.0 * r["fep_bg"] / max(r["fep_raw"], 1.0),
                 epst, eps / epst))
    return 0


if __name__ == "__main__":
    sys.exit(main())
