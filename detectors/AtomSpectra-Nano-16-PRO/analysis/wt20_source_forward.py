# -*- coding: utf-8 -*-
"""Прямая задача: пачка WT-20 как источник, от состава к выходу квантов.

Обратная задача (спектр -> активность) решается в `wt20_unfold.py`. Здесь всё
наоборот и независимо от спектра: известно содержание тория по этикетке, отсюда
считаются удельная активность, число распадов в пачке, выход квантов по линиям и
доля, которая ВЫХОДИТ из вольфрама. Смысл — получить опорное число, с которым
сравнивается результат разложения, и отдельно увидеть, сколько съедает
самопоглощение на каждой линии.

Что считается и чем считается:

1. **Удельная активность Th-232** — из периода полураспада и атомной массы:
   A_уд = ln2 * N_A / (T_1/2 * M). Обе величины берутся из МАГАТЭ (NDS),
   постоянная Авогадро — определена СИ точно.

2. **Состав** — 2 % масс. ThO2 по этикетке. Доля тория в ThO2 считается по
   атомным массам, не берётся готовой.

3. **Самопоглощение** — методом Монте-Карло по геометрии стержня: точка
   розыгрыша равномерно по объёму цилиндра, направление изотропно, считается
   длина пути до боковой поверхности и вес exp(-mu*L). Средний вес и есть доля
   НЕрассеянных квантов, вышедших из стержня. Коэффициенты ослабления — NIST
   XCOM для реального состава сплава (W 0,980000 / Th 0,017576 / O 0,002424 по
   массе), колонка «с когерентным рассеянием»: когерентное рассеяние уводит
   квант с исходного направления, для выхода линии это потеря.

   Отдельно считается доля, вышедшая ВВЕРХ (в сторону прибора) через всю пачку,
   с учётом соседних стержней и воздушных промежутков между ними.

   Важно: это выход НЕрассеянных квантов. Рассеянные не исчезают, они уходят в
   подложку спектра — в пик полного поглощения своей линии они не попадают.

4. **Выходы линий** — из библиотеки МАГАТЭ, `reference/nuclide-lines/*.csv`.

Числа не сравниваются здесь с результатом разложения: сравнение делает отчёт.

    python analysis/wt20_source_forward.py [каталог вывода]
"""
import csv
import io
import math
import os
import sys

import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
_DET = os.path.dirname(_HERE)
LIB = os.path.join(_DET, "reference", "nuclide-lines")

# --- ядерные данные, МАГАТЭ NDS (nds.iaea.org/relnsd/v1/data?fields=ground_states)
TH232_T12_S = 4.41796963644288e17     # период полураспада, с (1,40e10 лет)
TH232_M_U = 232.038053606             # атомная масса, а.е.м.
N_A = 6.02214076e23                   # 1/моль, точно по определению СИ 2019
O_M_U = 15.999                        # стандартная атомная масса кислорода, ИЮПАК

# --- пачка: те же числа, что в geometry/ASN16Detector.hh
N_RODS = 10
ROD_D_CM = 0.320
ROD_L_CM = 17.50
PITCH_CM = 0.485
RHO_ALLOY = 18.925                    # г/см3, считается в ASN16Detector.cc по долям
THO2_MASS_FRAC = 0.02                 # по этикетке

# --- mu/rho сплава, NIST XCOM, колонка «с когерентным рассеянием», см2/г
#     состав по массе W 0.980000 / Th 0.017576 / O 0.002424 — печатает сам XCOM
MU_RHO = {
    59.30: 3.8690,      # Ka вольфрама (ниже K-края W 69,5 кэВ)
    77.30: 8.4200,      # Ka висмута — уже ВЫШЕ K-края вольфрама, отсюда скачок
    87.10: 6.2090,
    238.63: 0.5280,
    300.09: 0.3261,
    583.19: 0.1136,
    727.33: 0.0889,
    860.56: 0.0757,
    911.20: 0.0719,
    968.97: 0.0682,
    1620.50: 0.0482,
    2614.51: 0.0416,
}

# --- линии, по которым ведётся сверка -----------------------------------------
# Перечислены только ЭНЕРГИИ. Нуклид и выход на распад определяются из
# библиотеки МАГАТЭ при запуске (reference/nuclide-lines): набранный от руки
# список уже расходился с ней — линия 860,56 кэВ была приписана Ac-228, хотя
# принадлежит Tl-208 (выход 12,5 %), а 300,09 приписана Ra-224 вместо Pb-212.
# Ошибка стоила ×2,78 в строке CSV, поскольку для Tl-208 не применялось
# ветвление Bi-212 (находка S9 внешнего аудита от 07.08.2026).
LINE_ENERGIES = [238.63, 300.09, 583.19, 727.33, 860.56, 911.20, 968.97,
                 2614.51]

# доля распадов Bi-212, идущая по ветви на Tl-208 (МАГАТЭ)
BR_BI212_TL208 = 0.3594

# соответствие «нуклид -> файл библиотеки»; ключ — как нуклид назван в отчёте
_LIB_FILES = {"Pb-212": "212pb", "Bi-212": "212bi", "Tl-208": "208tl",
              "Ac-228": "228ac", "Ra-224": "224ra", "Rn-220": "220rn",
              "Th-228": "228th", "Th-232": "232th", "Ra-228": "228ra"}


def lookup_line(e_want, tol=0.6):
    """Нуклид и выход линии — из библиотеки МАГАТЭ, поиском по ВСЕМ файлам.

    Отдаётся самая сильная линия в окне ±tol. Доплеровски расщеплённые линии
    здесь не встречаются (расщепление отдачей проявляется в модельном спектре,
    а не в библиотеке), но соседи в пределах окна — да, поэтому берётся
    сильнейшая, а не первая найденная.
    """
    best = None
    for nuc, stem in _LIB_FILES.items():
        p = os.path.join(LIB, "%s_gammas.csv" % stem)
        if not os.path.exists(p):
            continue
        for r in csv.DictReader(io.open(p, encoding="utf-8")):
            try:
                e = float(r["energy"])
                i = float(r["intensity"])
            except (TypeError, ValueError, KeyError):
                continue
            if abs(e - e_want) <= tol and (best is None or i > best[2]):
                best = (nuc, e, i)
    if best is None:
        raise SystemExit("линия %.2f кэВ не найдена в библиотеке %s"
                         % (e_want, LIB))
    return best[0], best[2] / 100.0

RNG = np.random.default_rng(20260807)
N_MC = 400000


def escape_single_rod(mu_cm, n=N_MC):
    """Доля нерассеянных квантов, вышедших из ОДНОГО стержня, по всем 4pi.

    Точка розыгрыша равномерна по объёму цилиндра, направление изотропно.
    Считается путь до боковой поверхности; торцы не учитываются — стержень
    длиной 175 мм при радиусе 1,6 мм, вклад торцов пренебрежим (доля телесного
    угла на торец меньше 0,2 % и для неё путь тоже длинный).
    """
    R = ROD_D_CM / 2.0
    # равномерно по площади круга
    r = R * np.sqrt(RNG.random(n))
    phi = 2 * math.pi * RNG.random(n)
    x = r * np.cos(phi)
    y = r * np.sin(phi)
    # изотропное направление
    cos_t = 2 * RNG.random(n) - 1.0
    sin_t = np.sqrt(np.clip(1 - cos_t ** 2, 0, None))
    psi = 2 * math.pi * RNG.random(n)
    ux = sin_t * np.cos(psi)
    uy = sin_t * np.sin(psi)
    # путь до боковой поверхности в проекции на плоскость сечения
    ur2 = ux ** 2 + uy ** 2
    b = x * ux + y * uy
    c = x ** 2 + y ** 2 - R ** 2
    disc = np.clip(b ** 2 - ur2 * c, 0, None)
    # Параметр t решения — УЖЕ трёхмерная длина, а не длина проекции.
    # Уравнение записано в компонентах ux = sinθ·cosψ, uy = sinθ·sinψ полного
    # единичного направления, поэтому смещение по лучу за параметр t равно t·|U|
    # = t. Прежняя редакция делила t на sinθ ещё раз, завышая путь в металле в
    # 1/sinθ и занижая выход на 7-19 % (находка S1 внешнего аудита от
    # 07.08.2026, подтверждена прямым тестом: луч из оси цилиндра даёт
    # t/эталон = 1,0000 при θ = 90/60/30/10°).
    path = (-b + np.sqrt(disc)) / np.maximum(ur2, 1e-12)
    return float(np.mean(np.exp(-mu_cm * path)))


def escape_pack_upward(mu_cm, n=N_MC):
    """Доля, вышедшая из ПАЧКИ вверх, в полусферу со стороны прибора.

    Учитываются соседние стержни: луч, идущий вбок, пересекает их и промежутки
    воздуха между ними. Воздух не ослабляет (при 1,65 мм это ниже 0,01 % даже на
    59 кэВ), поэтому суммируется только путь по металлу.
    """
    R = ROD_D_CM / 2.0
    centres = (np.arange(N_RODS) - (N_RODS - 1) / 2.0) * PITCH_CM
    # стержень старта — равновероятно любой из десяти
    k = RNG.integers(0, N_RODS, n)
    r = R * np.sqrt(RNG.random(n))
    phi = 2 * math.pi * RNG.random(n)
    x = centres[k] + r * np.cos(phi)
    y = r * np.sin(phi)
    # только верхняя полусфера: прибор сверху
    cos_t = 2 * RNG.random(n) - 1.0
    sin_t = np.sqrt(np.clip(1 - cos_t ** 2, 0, None))
    psi = math.pi * RNG.random(n)          # 0..pi -> uy >= 0
    ux = sin_t * np.cos(psi)
    uy = sin_t * np.sin(psi)
    path = np.zeros(n)
    for j, xc in enumerate(centres):
        dx = x - xc
        b = dx * ux + y * uy
        cc = dx ** 2 + y ** 2 - R ** 2
        ur2 = np.maximum(ux ** 2 + uy ** 2, 1e-12)
        disc = b ** 2 - ur2 * cc
        ok = disc > 0
        sq = np.sqrt(np.clip(disc, 0, None))
        t1 = (-b - sq) / ur2
        t2 = (-b + sq) / ur2
        t1 = np.clip(t1, 0, None)          # назад по лучу не считаем
        t2 = np.clip(t2, 0, None)
        seg = np.where(ok, np.maximum(t2 - t1, 0.0), 0.0)
        path += seg
    # без деления на sinθ: параметр t уже трёхмерная длина, см. escape_single_rod
    return float(np.mean(np.exp(-mu_cm * path)))


def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(_DET, "results")
    os.makedirs(outdir, exist_ok=True)

    # 1. удельная активность тория-232
    a_sp_th = math.log(2) * N_A / (TH232_T12_S * TH232_M_U)      # Бк/г тория
    # 2. состав
    m_tho2 = TH232_M_U + 2 * O_M_U
    th_in_tho2 = TH232_M_U / m_tho2
    th_frac_alloy = THO2_MASS_FRAC * th_in_tho2
    a_sp_alloy = a_sp_th * th_frac_alloy                          # Бк/г сплава
    # 3. масса пачки
    v_rod = math.pi * (ROD_D_CM / 2.0) ** 2 * ROD_L_CM
    m_pack = v_rod * N_RODS * RHO_ALLOY
    a_pack = a_sp_alloy * m_pack

    print("=== ИСТОЧНИК ПО СОСТАВУ (прямая задача) ===")
    print("  Th-232: T1/2 = %.4e с, M = %.6f а.е.м. (МАГАТЭ NDS)" % (TH232_T12_S, TH232_M_U))
    print("  удельная активность Th-232       %8.1f Бк/г тория" % a_sp_th)
    print("  доля Th в ThO2 по атомным массам %8.5f" % th_in_tho2)
    print("  доля Th в сплаве при 2 %% ThO2    %8.5f  (= %.4f %% масс.)"
          % (th_frac_alloy, 100 * th_frac_alloy))
    print("  УДЕЛЬНАЯ АКТИВНОСТЬ СПЛАВА       %8.1f Бк/кг" % (a_sp_alloy * 1000))
    print("  объём стержня %.5f см3, пачки %.4f см3" % (v_rod, v_rod * N_RODS))
    print("  масса пачки                      %8.2f г" % m_pack)
    print("  активность Th-232 в пачке        %8.0f Бк" % a_pack)
    print("  (в вековом равновесии столько же на каждое звено ряда)")

    # 4. самопоглощение
    print()
    print("=== САМОПОГЛОЩЕНИЕ (Монте-Карло, %d историй на точку) ===" % N_MC)
    print("  mu/rho — NIST XCOM для состава W 0,980000 / Th 0,017576 / O 0,002424")
    print()
    print("  E, кэВ   mu/rho   mu,1/см   mu*R    выход 4pi   выход вверх из пачки")
    rows = []
    R = ROD_D_CM / 2.0
    for e in sorted(MU_RHO):
        mu = MU_RHO[e] * RHO_ALLOY
        f4pi = escape_single_rod(mu)
        fup = escape_pack_upward(mu)
        rows.append((e, MU_RHO[e], mu, mu * R, f4pi, fup))
        print("  %7.2f  %7.4f  %8.3f  %6.3f    %7.4f       %7.4f"
              % (e, MU_RHO[e], mu, mu * R, f4pi, fup))

    # 5. выход квантов по линиям
    print()
    print("=== ВЫХОД КВАНТОВ ПО ЛИНИЯМ при номинале 2 %% ThO2 ===")
    print("  нуклид      E, кэВ  выход/расп  испущено, 1/с  вышло из пачки вверх, 1/с")
    line_rows = []
    for e in LINE_ENERGIES:
        nuc, yld = lookup_line(e)
        # активность звена в вековом равновесии равна активности Th-232,
        # кроме Tl-208: он образуется лишь в 35,94 % распадов Bi-212
        a_nuc = a_pack * (BR_BI212_TL208 if nuc == "Tl-208" else 1.0)
        emitted = a_nuc * yld
        mu = MU_RHO[e] * RHO_ALLOY
        fup = escape_pack_upward(mu)
        out = emitted * fup
        line_rows.append((nuc, e, yld, a_nuc, emitted, fup, out))
        print("  %-8s  %8.2f  %9.4f  %13.0f  %13.0f"
              % (nuc, e, yld, emitted, out))

    p = os.path.join(outdir, "wt20_source_forward.csv")
    with io.open(p, "w", encoding="utf-8", newline="") as f:
        f.write("# прямая задача: пачка WT-20 как источник при номинале 2 % масс. ThO2\n")
        f.write("# удельная активность сплава, Бк/кг;%.1f\n" % (a_sp_alloy * 1000))
        f.write("# масса пачки, г;%.2f\n" % m_pack)
        f.write("# активность Th-232 в пачке, Бк;%.0f\n" % a_pack)
        f.write("нуклид;E_кэВ;выход_на_распад;активность_звена_Бк;"
                "испущено_1/с;выход_вверх;вышло_1/с\n")
        for r in line_rows:
            f.write("%s;%.2f;%.4f;%.0f;%.0f;%.4f;%.0f\n"
                    % (r[0], r[1], r[2], r[3], r[4], r[5], r[6]))
    print()
    print("записано:", p)

    p2 = os.path.join(outdir, "wt20_selfabsorption.csv")
    with io.open(p2, "w", encoding="utf-8", newline="") as f:
        f.write("# самопоглощение в стержне и в пачке, Монте-Карло, %d историй\n" % N_MC)
        f.write("# mu/rho — NIST XCOM, сплав W 0.980000 / Th 0.017576 / O 0.002424\n")
        f.write("E_кэВ;mu_rho_см2/г;mu_1/см;mu*R;выход_4pi;выход_вверх_из_пачки\n")
        for r in rows:
            f.write("%.2f;%.4f;%.3f;%.3f;%.4f;%.4f\n" % r)
    print("записано:", p2)


if __name__ == "__main__":
    main()
