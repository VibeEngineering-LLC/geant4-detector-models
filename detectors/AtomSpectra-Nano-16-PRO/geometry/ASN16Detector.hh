// Спектрометр AtomSpectra Nano 16 PRO: брусок CsI(Tl) 18 x 15 x 60 мм в
// алюминиевой экструзии 86 x 42 x 25 мм с АЛЮМИНИЕВЫМИ торцевыми крышками
// 1,50 мм; в передней напротив кристалла фрезеровка до 0,60 мм — входное окно.
//
// МИРОВАЯ СИСТЕМА КООРДИНАТ: начало — в ЦЕНТРЕ КРИСТАЛЛА.
//   Z — вдоль корпуса; +Z к ПЕРЕДНЕМУ торцу (грань 18 x 15 мм) и к источнику,
//       −Z к грани с SiPM. Опорный замер Cs-137 снят с +Z, на 10 см от
//       НАРУЖНОЙ поверхности передней крышки. Направление выбрано не
//       произвольно: конус GPS (/gps/ang/maxtheta) разыгрывается вокруг −Z,
//       поэтому источник должен стоять на +Z — иначе конус светит мимо, а
//       прогон отрабатывает без единой жалобы.
//   X — по ширине корпуса (42 мм).
//   Y — по высоте (25 мм), +Y к рабочей грани 18 x 60 мм под стенкой 1,20 мм.
//
// ПРИБОР АНИЗОТРОПЕН: грань 18 x 60 = 10,80 см² и торец 18 x 15 =
// 2,70 см², отношение 4,00. Без указания грани значение эффективности не
// определено — это не деталь оформления, а часть определения величины.
//
// Происхождение каждого числа — reference/geometry-source.md и комментарии в
// ASN16Detector.cc. Опубликованного чертежа прибора нет.
#pragma once
#include "G4VUserDetectorConstruction.hh"
#include "globals.hh"

class G4LogicalVolume;
class G4Material;

// --- Геометрия Nano 16 PRO (мм) ---------------------------------------------
// Метки происхождения: ОПЕРАТОР — со слов оператора; ПРОФИЛЬ — чертёж экструзии
// линейки Nano (Nano 5 PRO); ФОТО — фотография открытого торца; ДОПУЩЕНИЕ —
// не задано ни одним источником.
struct Nano16Geom {
  // кристалл: БРУСОК, не цилиндр
  double cryX = 18.00;      // ОПЕРАТОР
  double cryY = 15.00;      // ОПЕРАТОР
  double cryZ = 60.00;      // ОПЕРАТОР, 06.08.2026: «18 × 15 × 60 кристалл
                            // этот». Прежде стояло 57,00 — размер снят со
                            // справки, собранной по фотографии ATOM NANO 15,
                            // соседней модели линейки. Довод в пользу 60:
                            // цифра в названии — объём в см³, 18×15×60 =
                            // 16,20 см³ («Nano 16»), тогда как 18×15×57 =
                            // 15,39 («Nano 15»). Масса кристалла 73,06 г.

  // обёртка — на ПЯТИ гранях из шести; на задней грани её нет: там SiPM в
  // оптическом контакте с кристаллом (ОПЕРАТОР, 05.08.2026)
  double ptfe   = 1.00;     // ОПЕРАТОР
  double alFoil = 0.10;     // ОПЕРАТОР

  // корпус — экструзия линейки Nano
  double bodyX = 42.00;     // ОПЕРАТОР
  double bodyY = 25.00;     // ОПЕРАТОР
  double bodyZ = 86.00;     // ОПЕРАТОР
  // ОПЕРАТОР, 06.08.2026: «профиль корпуса Атом Нано всех серий имеет верхнюю
  // и нижнюю стенки 1.5». Отменяет прежний перенос с чертежа профиля Nano 5
  // PRO (1,20 и 2,05): указание относится ко ВСЕЙ линейке, то есть к более
  // широкому основанию, чем один чертёж соседней модели.
  double wFront = 1.50;     // ОПЕРАТОР: верхняя стенка над кристаллом
  double wBot   = 1.50;     // ОПЕРАТОР: нижняя стенка (дно)
  double wSide  = 1.95;     // ДОПУЩЕНИЕ: перенос с Nano 5 PRO, (39,50−35,60)/2
  double wCap   = 1.50;     // ОПЕРАТОР, 06.08.2026. Материал — АЛЮМИНИЙ,
                            // см. matCap ниже.

  // ФРЕЗЕРОВКА В ПЕРЕДНЕЙ КРЫШКЕ (ОПЕРАТОР, 06.08.2026): «напротив детектора
  // сделана фрезеровка до толщины 0,6. Площадь фрезеровки — чуть больше
  // площади торца. Возьми +1 мм с каждой стороны детектора».
  // Это и есть входное окно прибора: в пучке стоит 0,60 мм алюминия, а не
  // 1,50. Без выборки торцевой стек был бы 0,6518 г/см², с ней 0,4089 —
  // разница в 1,6 раза приходится ровно на мягкий край.
  bool   capWindow = true;  // фрезеровка ЕСТЬ. Переключается командой
                            // /asn16/capWindow on|off ДО /run/initialize:
                            // кривая «без окна» нужна как мера самого эффекта
                            // фрезеровки и обязана идти от ТОЙ ЖЕ ревизии
                            // исходников, иначе разность двух кривых нельзя
                            // приписать одному только окну.
  double wCapWin = 0.60;    // ОПЕРАТОР: остаточная толщина в окне
  double capWinPad = 1.00;  // ОПЕРАТОР: припуск окна на сторону от КРИСТАЛЛА
                            // (окно 20,00 x 17,00 при кристалле 18 x 15).
                            // ДОПУЩЕНИЕ: окно уже обёртки (20,20 x 17,20), то
                            // есть обёртка упирается в ободок крышки, а не в
                            // дно выборки. Сторона выборки источником не
                            // задана; принята ВНУТРЕННЯЯ — наружная плоскость
                            // корпуса тогда остаётся на прежнем месте, и
                            // опорная плоскость замера не меняется. На
                            // ослабление сторона не влияет: в пучке в обоих
                            // случаях 0,60 мм алюминия, разница лишь в том, по
                            // какую сторону от них лежат 0,90 мм воздуха.

  // плата по дну полости во всю длину, кристалл опирается на неё (ФОТО)
  double pcbT  = 1.60;      // ДОПУЩЕНИЕ: толщина не измерена, типовая FR4
  double sipmT = 1.50;      // ДОПУЩЕНИЕ: толщина сборки не задана

  // Кристалл упёрт в рабочую стенку — воздушного зазора в лицевом стеке нет
  // (ОПЕРАТОР). Лицевой стек Al 1,50 + фольга 0,10 + ПТФЭ 1,00 = 0,652 г/см²,
  // но В ПУЧКЕ в настоящей постановке стоит ТОРЦЕВОЙ, и именно в окне
  // фрезеровки: Al 0,60 + фольга 0,10 + ПТФЭ 1,00 = 0,409 г/см². Вне окна
  // крышка 1,50 даёт те же 0,652. Мягкий край кривой живёт в окне.

  // ВЕЩЕСТВА-ЗАМЕНИТЕЛИ. Сплав корпуса не назван, состав платы — тоже; взяты
  // материалы базы NIST с ЯВНОЙ пометкой, а не выдуманные смеси.
  //   корпус  — G4_Al (ρ = 2,699 по базе NIST) при заявленном «алюминиевый
  //             сплав»: разница плотностей сплавов ~1 %;
  //   крышки  — G4_Al. АЛЮМИНИЙ 1,50 мм с фрезеровкой до 0,60 мм напротив
  //             кристалла (ОПЕРАТОР, 06.08.2026, окончательное уточнение
  //             после трёх разошедшихся указаний того же дня: «алюминий» ->
  //             «1.5 мм» -> «Альберт подтвердил пластик» -> «Крышка -
  //             алюминий 1,5, фрезеровка до 0,6»). Сплав не назван, поэтому
  //             чистый Al остаётся ЗАМЕНОЙ. История указаний целиком —
  //             в reference/operator-directives.md;
  //   плата   — G4_BAKELITE вместо FR4: у FR4 стеклонаполнение поднимает
  //             плотность заметно выше бакелита, замена ЗАНИЖАЕТ массу платы;
  //   SiPM    — G4_Si: голый кремний вместо сборки с корпусом и подложкой.
  // Все четыре подлежат замене на подтверждённые источником составы до того,
  // как из модели пойдут публикуемые числа. ReportMaterials() печатает этот
  // список при каждом запуске, чтобы замена не осталась незамеченной.
  G4String matBody = "G4_Al";
  G4String matCap  = "G4_Al";
  G4String matPcb  = "G4_BAKELITE";
  G4String matSipm = "G4_Si";

  // --- ИСТОЧНИК: пачка вольфрамовых электродов WT-20 -------------------------
  // Постановка замера 01.06.2024 (ОПЕРАТОР, 06.08.2026): прибор ЛЕЖИТ на
  // пачке СТОРОНОЙ ПЛАТЫ, то есть излучение входит через дно корпуса и плату,
  // а не через фрезерованное окно. Пачка — под прибором, стержни параллельны
  // длинной оси корпуса («вдоль электродов, по центру»).
  //
  // Размеры с ЭТИКЕТКИ пачки (фотография оператора, 06.08.2026):
  // «Tungsten Electrodes 3.2mm x 175mm [approx. 1/8" x 7"], 10 Pieces,
  //  2%Thoriated(WT20), Ground Finish, ANSI/AWS A5.12M-98, ISO 6848».
  // РАСХОЖДЕНИЕ, оставленное в записи: в сообщении оператора стояло «2,0 мм»,
  // на фотографии другой пачки того же типа — «2,4 X 175 ММ»; принято 3,2 мм
  // по этикетке пачки, снятой в этом замере, и подтверждено оператором.
  bool   wt20 = false;      // строить пачку (команда /asn16/wt20 on|off)
  int    wt20N = 10;        // ЭТИКЕТКА: 10 Pieces
  double wt20D = 3.20;      // ЭТИКЕТКА: 3.2 мм
  double wt20L = 175.00;    // ЭТИКЕТКА: 175 мм
  double wt20ThO2 = 2.0;    // ЭТИКЕТКА: 2 % масс. ThO2 (WT20). По ISO 6848
                            // допуск на марку 1,70–2,20 % — это и есть
                            // неопределённость содержания, а 2,0 — номинал.
  // Диоксида тория в базе NIST НЕТ (проверено перебором имён материалов в
  // G4materials.dll: есть G4_URANIUM_OXIDE, G4_PLUTONIUM_DIOXIDE, тория нет),
  // поэтому ThO2 собирается из элементов, и его плотность приходится задавать
  // числом. Влияние слабое: при 2 % масс. сдвиг плотности сплава от замены
  // 9,7 на 10,0 г/см³ — 0,06 %.
  // ИСТОЧНИК: PNNL-15870 Rev.2 (Detwiler, McConn et al., 2021), запись 349
  // «Thorium Dioxide», с. 238: «Density (g/cm3) = 9.7», молярная масса
  // 264,0365 г/моль, массовая доля тория 0,878809. Точность заявлена в две
  // значащие цифры.
  double rhoThO2 = 9.70;    // г/см³
  // ДОПУЩЕНИЯ (этикеткой и фотографией не заданы, влияют на самопоглощение и
  // телесный угол, поэтому объявлены полями, а не зашиты в код):
  // ЗАМЕР ПО КРАСНЫМ КОНЧИКАМ, два независимых счёта (06.08.2026):
  //   оператор — 4,89 мм (разброс промежутков 4,34…5,57, зазор 1,69);
  //   этот контур (analysis/measure_tips_pitch.py) — 4,80 мм на двух рабочих
  //   сканлиниях из трёх, ±0,09.
  // Принято 4,85 мм. Зазор между поверхностями 1,65 мм, вся пачка
  // 9·4,85 + 3,2 = 46,85 мм.
  //
  // ПОЧЕМУ ПО КОНЧИКАМ. Голый вольфрам полирован: порог по яркости берёт блик,
  // а не тело прутка. Красная маркировка WT-20 матовая и кроет цилиндр
  // целиком, поэтому в канале «краснота» R − (G+B)/2 сегмент — полный силуэт.
  // Граница объявлена явно: полувысота красного плато над нулём красноты
  // (webp подвыбирает цветность, кромка размыта на несколько пикселей).
  //
  // ИСТОРИЯ ЗНАЧЕНИЯ, чтобы не переигрывать заново. Период укладки во ВСЕХ
  // замерах один и тот же (52–53 px на кадре 6971217310); расходилась только
  // принятая ширина прутка, а с ней масштаб мм/px:
  //   3,30 — допущение «лежат вплотную», снято оператором;
  //   6,15 — мой замер по доле металла: порог «выше средней яркости» брал
  //          затенённые рёбра лотка вместе с прутком, ширина завышена;
  //   8,10 — замер по блику на голом вольфраме: ширина, наоборот, ЗАНИЖЕНА,
  //          блик уже прутка;
  //   4,85 — по красным кончикам, полный силуэт. ОТМЕНЯЕТ оба предыдущих.
  double wt20Pitch = 4.85;
  double wt20Wall = 1.50;   // ОПЕРАТОР, 06.08.2026: «крышка пенала — акрил
                            // 1,5 мм». Толщина отнесена ко ВСЕМ стенкам
                            // пенала: названа только крышка, но она и стоит
                            // в пучке — прибор лежит на ней.
  double wt20Gap  = 0.50;   // ДОПУЩЕНИЕ: зазор стержни — верхняя стенка пенала
  // НОЖКИ ПРИБОРА (ОПЕРАТОР, 06.08.2026): «силиконовая пуговичка высотой
  // 3–4 мм в углах корпуса». Прибор НЕ лежит на пенале дном — он стоит на
  // четырёх ножках, и между дном корпуса и крышкой пенала остаётся воздух.
  // Это прибавляется прямо к плечу «источник — кристалл»: было 11,00 мм от оси
  // стержня до нижней грани кристалла, стало 14,50.
  double feetH = 3.50;      // мм, середина названного оператором 3–4
  double feetXY = 6.00;     // мм, сторона пуговички (ДОПУЩЕНИЕ)
  double feetInset = 3.00;  // мм, отступ от края корпуса (ДОПУЩЕНИЕ)
  G4String matFeet = "G4_RUBBER_NATURAL";   // ЗАМЕНА силикона
  G4String matCase = "G4_PLEXIGLASS";    // ОПЕРАТОР: акрил (ПММА)

  // СТОЛ ПОД ПАЧКОЙ. Постановка контактная, и то, на чём лежит источник,
  // рассеивает обратно в детектор. Проверяется ГИПОТЕЗА: измеренный спектр
  // мягче модельного (избыток ниже 400 кэВ при недостатке в жёстком
  // континууме), и рассеяние от подложки — первый кандидат. Строится только
  // по команде /asn16/table on, чтобы разность двух прогонов можно было
  // приписать одному только столу.
  bool   table = false;
  double tableT = 20.0;      // мм, толщина столешницы (ДОПУЩЕНИЕ)
  double tableGap = 0.0;     // мм, пенал лежит на столе
  double tableRho = 0.65;    // г/см³, ДСП/дерево (ДОПУЩЕНИЕ)
  double tableXY = 280.0;    // мм, сторона плиты. Больше нельзя: мир имеет
                             // полуразмер 150 мм по X, и плита 300 мм вышла бы
                             // за его границу
};

class ASN16Detector : public G4VUserDetectorConstruction {
public:
  ASN16Detector() = default;
  G4VPhysicalVolume* Construct() override;

  Nano16Geom fGeom;

  G4LogicalVolume* fCrystalLV = nullptr;

  // --- Опорные плоскости, от которых отмеряется положение источника ---------
  // Возвращают мировую координату НАРУЖНОЙ поверхности, а не грани кристалла:
  // расстояние в замере отсчитано от корпуса. Разница (крышка + обёртка)
  // на плече 100 мм даёт поправку к телесному углу порядка 6 % — величину
  // того же порядка, что статистика площади пика, поэтому опорная плоскость
  // обязана быть названа явно, а не подразумеваться.
  double FrontFaceZ() const;    // наружная поверхность передней крышки, мм
  double WorkFaceY() const;     // наружная поверхность стенки 1,20 мм, мм
  double CrystalFrontZ() const; // передняя грань кристалла, мм (для сверки)
  double CrystalTopY() const;   // рабочая грань кристалла, мм (для сверки)
  double BottomFaceY() const;   // НАРУЖНАЯ поверхность дна — на неё лёг прибор

  // Масса вольфрама пачки, г (0, если пачка не построена). Считается по
  // построенным телам, а не по формуле в отчёте: расхождение между тем, что
  // посчитано, и тем, что напечатано, здесь уже ловили.
  double PackMassG() const;

  // Печатает массы построенных тел и список веществ-заменителей.
  void ReportMasses() const;
  void ReportPlanes() const;

private:
  void DefineMaterials();
  G4Material* MakeWT20();

  double fPackW = 0.0;      // масса вольфрама пачки, г
  double fPackYRod = 0.0;   // ось стержней по Y, мм
};
