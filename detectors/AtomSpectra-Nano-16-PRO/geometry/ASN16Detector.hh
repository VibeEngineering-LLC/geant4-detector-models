// Спектрометр AtomSpectra Nano 16 PRO: брусок CsI(Tl) 18 x 15 x 60 мм в
// алюминиевой экструзии 86 x 42 x 25 мм с пластиковыми торцевыми крышками.
//
// МИРОВАЯ СИСТЕМА КООРДИНАТ: начало — в ЦЕНТРЕ КРИСТАЛЛА.
//   Z — вдоль корпуса; +Z к ПЕРЕДНЕМУ торцу (грань 18 x 15 мм) и к источнику,
//       −Z к грани с SiPM. Опорный замер Cs-137 снят с +Z, на 10 см от
//       НАРУЖНОЙ поверхности передней крышки. Направление выбрано не
//       произвольно: конус GPS (/gps/ang/maxtheta) разыгрывается вокруг −Z,
//       поэтому источник должен стоять на +Z — иначе конус светит мимо, а
//       прогон отрабатывает без единой жалобы.
//   X — по ширине корпуса (42 мм).
//   Y — по высоте (25 мм), +Y к рабочей грани 18 x 60 мм под стенкой 1,20 мм.
//
// ПРИБОР АНИЗОТРОПЕН: грань 18 x 60 = 10,80 см² и торец 18 x 15 =
// 2,70 см², отношение 4,00. Без указания грани значение эффективности не
// определено — это не деталь оформления, а часть определения величины.
//
// Происхождение каждого числа — reference/geometry-source.md и комментарии в
// ASN16Detector.cc. Опубликованного чертежа прибора нет.
#pragma once
#include "G4VUserDetectorConstruction.hh"
#include "globals.hh"

class G4LogicalVolume;
class G4Material;

// --- Геометрия Nano 16 PRO (мм) ---------------------------------------------
// Метки происхождения: ОПЕРАТОР — со слов оператора; ПРОФИЛЬ — чертёж экструзии
// линейки Nano (Nano 5 PRO); ФОТО — фотография открытого торца; ДОПУЩЕНИЕ —
// не задано ни одним источником.
struct Nano16Geom {
  // кристалл: БРУСОК, не цилиндр
  double cryX = 18.00;      // ОПЕРАТОР
  double cryY = 15.00;      // ОПЕРАТОР
  double cryZ = 60.00;      // ОПЕРАТОР, 06.08.2026: «18 × 15 × 60 кристалл
                            // этот». Прежде стояло 57,00 — размер снят со
                            // справки, собранной по фотографии ATOM NANO 15,
                            // соседней модели линейки. Довод в пользу 60:
                            // цифра в названии — объём в см³, 18×15×60 =
                            // 16,20 см³ («Nano 16»), тогда как 18×15×57 =
                            // 15,39 («Nano 15»). Масса кристалла 73,06 г.

  // обёртка — на ПЯТИ гранях из шести; на задней грани её нет: там SiPM в
  // оптическом контакте с кристаллом (ОПЕРАТОР, 05.08.2026)
  double ptfe   = 1.00;     // ОПЕРАТОР
  double alFoil = 0.10;     // ОПЕРАТОР

  // корпус — экструзия линейки Nano
  double bodyX = 42.00;     // ОПЕРАТОР
  double bodyY = 25.00;     // ОПЕРАТОР
  double bodyZ = 86.00;     // ОПЕРАТОР
  double wFront = 1.20;     // ПРОФИЛЬ: рабочая стенка над кристаллом
  double wBot   = 2.05;     // ПРОФИЛЬ: дно
  double wSide  = 1.95;     // ДОПУЩЕНИЕ: перенос с Nano 5 PRO, (39,50−35,60)/2
  double wCap   = 1.50;     // ОПЕРАТОР, 06.08.2026: «уточнение - крышка
                            // 1.5 мм». Прежде 2,00 (ДОПУЩЕНИЕ). Материал —
                            // ПЛАСТИК, см. matCap ниже.

  // плата по дну полости во всю длину, кристалл опирается на неё (ФОТО)
  double pcbT  = 1.60;      // ДОПУЩЕНИЕ: толщина не измерена, типовая FR4
  double sipmT = 1.50;      // ДОПУЩЕНИЕ: толщина сборки не задана

  // Кристалл упёрт в рабочую стенку — воздушного зазора в лицевом стеке нет
  // (ОПЕРАТОР). Лицевой стек Al 1,20 + фольга 0,10 + ПТФЭ 1,00 = 0,571 г/см²,
  // но В ПУЧКЕ в настоящей постановке стоит ТОРЦЕВОЙ: крышка 1,50 + фольга 0,10
  // + ПТФЭ 1,00 = 0,406 г/см². Мягкий край кривой живёт в торцевом.

  // ВЕЩЕСТВА-ЗАМЕНИТЕЛИ. Сплав корпуса не назван, состав платы — тоже; взяты
  // материалы базы NIST с ЯВНОЙ пометкой, а не выдуманные смеси.
  //   корпус  — G4_Al (ρ = 2,699 по базе NIST) при заявленном «алюминиевый
  //             сплав»: разница плотностей сплавов ~1 %;
  //   крышки  — G4_POLYSTYRENE вместо ABS: стирол — основной компонент ABS,
  //             плотности близки, но это ЗАМЕНА, а не состав крышки.
  //             МАТЕРИАЛ ПОДТВЕРЖДЁН АВТОРОМ ПРИБОРА (ОПЕРАТОР, 06.08.2026:
  //             «и Альберт подтвердил пластик») — раньше он держался только
  //             на фотографии. Промежуточная правка на G4_Al, сделанная по
  //             более раннему указанию того же дня, отменена; след обеих
  //             формулировок — в reference/operator-directives.md;
  //   плата   — G4_BAKELITE вместо FR4: у FR4 стеклонаполнение поднимает
  //             плотность заметно выше бакелита, замена ЗАНИЖАЕТ массу платы;
  //   SiPM    — G4_Si: голый кремний вместо сборки с корпусом и подложкой.
  // Все четыре подлежат замене на подтверждённые источником составы до того,
  // как из модели пойдут публикуемые числа. ReportMaterials() печатает этот
  // список при каждом запуске, чтобы замена не осталась незамеченной.
  G4String matBody = "G4_Al";
  G4String matCap  = "G4_POLYSTYRENE";
  G4String matPcb  = "G4_BAKELITE";
  G4String matSipm = "G4_Si";
};

class ASN16Detector : public G4VUserDetectorConstruction {
public:
  ASN16Detector() = default;
  G4VPhysicalVolume* Construct() override;

  Nano16Geom fGeom;

  G4LogicalVolume* fCrystalLV = nullptr;

  // --- Опорные плоскости, от которых отмеряется положение источника ---------
  // Возвращают мировую координату НАРУЖНОЙ поверхности, а не грани кристалла:
  // расстояние в замере отсчитано от корпуса. Разница (крышка + обёртка)
  // на плече 100 мм даёт поправку к телесному углу порядка 6 % — величину
  // того же порядка, что статистика площади пика, поэтому опорная плоскость
  // обязана быть названа явно, а не подразумеваться.
  double FrontFaceZ() const;    // наружная поверхность передней крышки, мм
  double WorkFaceY() const;     // наружная поверхность стенки 1,20 мм, мм
  double CrystalFrontZ() const; // передняя грань кристалла, мм (для сверки)
  double CrystalTopY() const;   // рабочая грань кристалла, мм (для сверки)

  // Печатает массы построенных тел и список веществ-заменителей.
  void ReportMasses() const;
  void ReportPlanes() const;

private:
  void DefineMaterials();
};
