"""Просадка аттестованной кривой на каскадных нуклидах (задачи 93, 109, 128).

ВОПРОС. Плато около 7 %, на которое эффективность модели превышает
аттестованную на 583…861 кэВ, до сих пор приписывалось модели. Но
аттестованная кривая сама не есть истина, и у неё есть свой механизм занижения:
если при её построении не вводилась поправка на КАСКАДНОЕ СУММИРОВАНИЕ, то узлы,
снятые с каскадных нуклидов, окажутся систематически НИЖЕ истинной кривой —
часть отсчётов ушла из пика в суммарный.

ПОЧЕМУ ВОПРОС ВООБЩЕ ВСТАЛ. Файл `.efr` хранит, каким нуклидом взят каждый
узел. Прочтение показывает, что ВСЕ узлы плато и жёсткого края точечной
геометрии 5 см сняты с Th-228: 238,632 / 583,187 / 727,330 / 860,557 /
2614,511. Th-228 — цепочка с каскадами (Tl-208: 583,2 ⊕ 2614,5; 860,6 ⊕
2614,5), то есть ровно тот случай, где суммирование действует. Метод построения
аттестации оператору неизвестен, поэтому «поправка была введена» — допущение, а
не факт.

КАК ПРОВЕРИТЬ БЕЗ ВНЕШНЕГО ЭТАЛОНА. Кривая обязана быть ГЛАДКОЙ: эффективность
детектора — плавная функция энергии. Значит узлы, снятые с ОДИНОЧНЫХ гамма-
излучателей (суммироваться нечему), задают опорную гладкую линию, а узлы
каскадных нуклидов обязаны на неё ложиться. Систематическая просадка каскадных
узлов ниже опорной линии — прямое свидетельство неучтённого суммирования.
Никакого внешнего эталона тест не требует, поэтому он идёт в набор задачи 128.

КЛАССИФИКАЦИЯ НУКЛИДОВ — СТРУКТУРНАЯ, НЕ ПО ЧИСЛАМ. «Одиночный» здесь значит:
в одном акте распада испускается один регистрируемый гамма-квант, и складывать
его не с чем. Обоснование по каждому нуклиду записано в `SINGLE`/`CASCADE`
рядом со значением; спорные случаи (Co-57 с переходом 14,41 кэВ, Am-241 и
Cd-109 с характеристическим излучением) отнесены к каскадным намеренно — при
сомнении нуклид уходит из опорного набора, а не в него, иначе опора сама
окажется просаженной и тест занизит эффект.

ОБЛАСТЬ ДЕЙСТВИЯ ТЕСТА. Чистых одиночных излучателей в комплекте три:
661,657 (Cs-137), 834,848 (Mn-54), 1115,539 (Zn-65). Опорная линия строится
только по ним, поэтому тест действует в диапазоне 662…1116 кэВ и НЕ переносится
на 2614,5: выше 1115,5 одиночных узлов нет, и любое утверждение о жёстком крае
было бы экстраполяцией втрое по энергии. Тест говорит о ПЛАТО, не о разрыве.
"""
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402
import paths  # noqa: E402
import stamp  # noqa: E402

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "tools"))
from fetch_efr import parse_efr  # noqa: E402

OUT = str(paths.results("Gamma-1S"))
EFR = "УДС-ГЦ-63х63-USB__SN-01_-_Точечная-5см.efr"

# Одиночные гамма-излучатели: в одном акте распада один регистрируемый квант,
# складывать не с чем. Опорный набор.
SINGLE = {
    "Cs-137": "Ba-137m разряжается одним переходом 661;657",
    "Mn-54": "электронный захват в Cr-54; один переход 834;848",
    "Zn-65": "один переход 1115;539 (аннигиляционная ветвь 1;4 % пренебрежима)",
}
# Каскадные и сомнительные — все прочие. Сомнительные помечены отдельно: при
# сомнении нуклид уходит ИЗ опоры, иначе опора просядет вместе с проверяемыми.
CASCADE = {
    "Co-60": "1173;2 и 1332;5 в одном акте",
    "Y-88": "898;0 и 1836;1 в одном акте",
    "Eu-152": "многоступенчатые каскады",
    "Th-228": "цепочка; у Tl-208 583;2 и 860;6 идут вместе с 2614;5",
    "Na-22": "1274;5 вместе с двумя аннигиляционными 511",
    "Ba-133": "несколько каскадных ветвей",
    "Co-57": "СОМНИТЕЛЬНЫЙ: 122;06 идёт вместе с переходом 14;41",
    "Am-241": "СОМНИТЕЛЬНЫЙ: 59;54 вместе с L-рентгеном",
    "Cd-109": "СОМНИТЕЛЬНЫЙ: 88;03 вместе с K-рентгеном серебра",
}

OBS = {
    "quantity": "отклонение узла аттестованной кривой от опорной линии;"
                " построенной ТОЛЬКО по одиночным гамма-излучателям",
    "area": "величины взяты из файла .efr как есть — это уже готовые узлы"
            " эффективности; площади здесь не снимаются",
    "window": "не применимо — узлы кривой; а не спектр",
    "shelf": "не применимо",
    "blurred": "не применимо — сравниваются узлы аттестованной кривой"
               " между собой",
    "reference": "степенная линия eps = k*E^p по трём одиночным узлам"
                 " 661;657 / 834;848 / 1115;539",
    "scope": "662…1116 кэВ — диапазон опорных узлов; на 2614;5 тест НЕ"
             " переносится (одиночных узлов выше 1115;5 нет)",
}


def read_nodes():
    p = os.path.join(str(paths.ref("Gamma-1S")), EFR)
    if not os.path.exists(p):
        p = os.path.join(os.environ.get("G1S_EFR_DIR", ""), EFR)
    if not os.path.exists(p):
        raise SystemExit(
            "Не найден %s.\nЗадайте G1S_EFR_DIR на каталог с файлами .efr"
            " комплекта." % EFR)
    txt = open(p, "rb").read().decode("utf-8", errors="replace")
    nodes = []
    for s in parse_efr(txt):
        for pt in s["points"]:
            nodes.append((float(pt[0]), float(pt[1]), float(pt[2]),
                          str(pt[3]).strip()))
    return sorted(nodes)


def power_fit(pts):
    """(k; p) в eps = k*E^p — МНК по логарифмам."""
    xs = [math.log(E) for E, y in pts]
    ys = [math.log(y) for E, y in pts]
    n = len(xs)
    sx, sy = sum(xs), sum(ys)
    sxx = sum(x * x for x in xs)
    sxy = sum(x * y for x, y in zip(xs, ys))
    p = (n * sxy - sx * sy) / (n * sxx - sx * sx)
    k = math.exp((sy - p * sx) / n)
    return k, p


def main():
    nodes = read_nodes()
    ref = [(E, y) for E, y, _, nuc in nodes if nuc in SINGLE]
    if len(ref) < 3:
        raise SystemExit(
            "Опорных одиночных узлов %d — меньше трёх; линию строить не по"
            " чему." % len(ref))
    k, p = power_fit(ref)
    lo = min(E for E, _ in ref)
    hi = max(E for E, _ in ref)

    print("Просадка аттестованной кривой на каскадных нуклидах.")
    print("Опора: %s — %d узла; eps = %.4g * E^%.4f; диапазон %.1f…%.1f кэВ.\n"
          % ("; ".join(sorted(SINGLE)), len(ref), k, p, lo, hi))
    print("%10s %-8s %12s %12s %8s %7s %s"
          % ("E, кэВ", "нуклид", "eps узла", "опорная", "откл.%", "сигм",
             "роль"))
    rows = []
    for E, y, dpct, nuc in nodes:
        if not (lo <= E <= hi):
            continue
        pred = k * E ** p
        dev = 100 * (y - pred) / pred
        sig = abs(dev) / dpct if dpct > 0 else float("inf")
        role = "опора" if nuc in SINGLE else "каскад"
        print("%10.3f %-8s %12.6e %12.6e %+8.2f %7.1f %s"
              % (E, nuc, y, pred, dev, sig, role))
        rows.append((E, nuc, y, pred, dev, dpct, sig, role))

    # СИСТЕМАТИЧЕСКИЙ ПОЛ МЕТОДА. Опорные узлы сами не ложатся на степенной
    # закон идеально: их остатки и есть мера того, насколько форма кривой в
    # принципе описывается двумя параметрами по трём точкам. Всё, что меньше
    # этого разброса, методом не различается — сравнивать просадку каскадных
    # узлов только с их собственной погрешностью значило бы объявить значимым
    # то, что тонет в негодности самой опоры.
    refdev = [r[4] for r in rows if r[7] == "опора"]
    floor = math.sqrt(sum(d * d for d in refdev) / len(refdev))
    print("\nСИСТЕМАТИЧЕСКИЙ ПОЛ. Опорные узлы отклоняются от собственной"
          " линии на %s %% — СКО %.2f %%."
          % ("; ".join("%+.2f" % d for d in refdev), floor))
    print("  Эта величина входит в оценку значимости наравне со статистикой:"
          " ниже неё метод не различает.")

    def wmean(sub):
        w = [1.0 / r[5] ** 2 for r in sub]
        m = sum(r[4] * ww for r, ww in zip(sub, w)) / sum(w)
        stat = (1.0 / sum(w)) ** 0.5
        return m, stat, math.hypot(stat, floor)

    casc = [r for r in rows if r[7] == "каскад"]
    print("\nПО НУКЛИДАМ (усреднять всё вместе нельзя: сила каскада у каждого"
          " своя).")
    per = {}
    for r in casc:
        per.setdefault(r[1], []).append(r)
    for nuc in sorted(per):
        m, st, tot = wmean(per[nuc])
        print("  %-8s узлов %d: %+6.2f %% (стат %.2f; с полом %.2f) — %.1f"
              " сигмы" % (nuc, len(per[nuc]), m, st, tot, abs(m) / tot))

    print("\nВЫВОД.")
    if not casc:
        print("  В диапазоне опоры каскадных узлов нет — судить не о чем.")
    else:
        mean, st, tot = wmean(casc)
        below = sum(1 for r in casc if r[4] < 0)
        print("  Все каскадные узлы вместе: %d; ниже опорной линии %d;"
              " среднее %+.2f +- %.2f %% (%.1f сигмы)."
              % (len(casc), below, mean, tot, abs(mean) / tot))
        # Th-228 — единственный нуклид; с которого сняты узлы ПЛАТО; поэтому
        # решает именно он; а не смесь нуклидов с разной силой каскада.
        th = per.get("Th-228", [])
        if th:
            m, st, tot = wmean(th)
            n = abs(m) / tot
            print("  РЕШАЮЩИЙ ПОДНАБОР — Th-228 (именно с него сняты узлы"
                  " плато 583…861 и край 2614;5):")
            print("     %+.2f %% при %d узлах; статистика %.2f; с"
                  " систематическим полом %.2f — %.1f сигмы."
                  % (m, len(th), st, tot, n))
            if m < 0 and n >= 3.0:
                print("     Узлы Th-228 систематически ЗАНИЖЕНЫ относительно"
                      " одиночных излучателей — ожидаемый след неучтённого")
                print("     каскадного суммирования. СЛЕДСТВИЕ: плато"
                      " принадлежит АТТЕСТАЦИИ примерно на %.0f из 7 п.п."
                      % abs(m))
            elif m < 0:
                print("     ПРОСАДКА ЕСТЬ; НО НЕ ДОКАЗАНА: %.1f сигмы с"
                      " учётом систематического пола." % n)
                print("     Величина %+.2f %% указывает направление и"
                      " порядок — до %.0f из 7 п.п. плато могут"
                      % (m, abs(m)))
                print("     принадлежать аттестации, — но подтверждения"
                      " требует независимая проверка:")
                print("     прогон модели по НЕКАСКАДНОМУ нуклиду в тех же"
                      " условиях либо расширение опорного набора.")
            else:
                print("     Просадки нет — суммирование; по-видимому; учтено.")
    print("\n  ОБЛАСТЬ ДЕЙСТВИЯ: %.0f…%.0f кэВ. На 2614;5 тест НЕ переносится:"
          " одиночных узлов выше %.0f кэВ" % (lo, hi, hi))
    print("  в комплекте нет; экстраполяция втрое по энергии доказательством"
          " не является.")

    csvio.write(
        os.path.join(OUT, "attested_cascade_check.csv"),
        ["E_keV", "nuclide", "eps_attested", "eps_reference", "dev_pct",
         "d_node_pct", "n_sigma", "role"],
        [("%.3f" % E, nuc, "%.6e" % y, "%.6e" % pr, "%+.2f" % d,
          "%.4f" % dp, "%.1f" % s, role)
         for E, nuc, y, pr, d, dp, s, role in rows],
        comments=[
            "Проверка БЕЗ внешнего эталона: кривая обязана быть гладкой;"
            " одиночные излучатели задают опору; каскадные проверяются.",
            "Опора — только Cs-137 661;657; Mn-54 834;848; Zn-65 1115;539:"
            " в одном акте один регистрируемый квант.",
            "Сомнительные (Co-57 с 14;41; Am-241 и Cd-109 с рентгеном)"
            " отнесены к каскадным намеренно: при сомнении — вон из опоры.",
            "Просадка каскадных узлов — след неучтённого суммирования в"
            " аттестации; то есть занижения аттестованной eps.",
            "Диапазон действия — только между крайними опорными узлами;"
            " на 2614;5 тест не переносится.",
        ],
        stamp=stamp.lines(
            "detectors/Gamma-1S/analysis/attested_cascade_check.py", OBS,
            geometry_dir=str(paths.geometry("Gamma-1S")),
            names=stamp.SRC_LISTS["Gamma-1S"], repo_dir=str(paths.REPO)))
    print("\nтаблица: %s"
          % os.path.join(OUT, "attested_cascade_check.csv"))


if __name__ == "__main__":
    main()
