"""Сум-пик Ba-133 437 кэВ на модели: проверка ВНЕ фотопика (задача 124).

ЗАЧЕМ. Все сравнения с аттестованной кривой — проверка транспорта:
отношение активностей есть тождество полиномов (разбор аудитора). Сум-пик
437,011 кэВ (356,013 плюс 80,998, реальной линии нет) задаётся ПОЛНОЙ
эффективностью eps_T(81 кэВ), которую аттестованная кривая по фотопику НЕ
ограничивает. Модель предсказывает eps_T сама — это первая величина в
проекте, проверяющая модель напрямую, не через полином.

ЧТО ПОДТВЕРЖДЕНО. В МК-спектре распада Ba-133 точечной 5 см (истинное
суммирование, resolving_time 1000 нс) фотопик-фантом 437,011 существует:
депозит есть, ЭМИССИИ на 437 нет вовсе (в природе линии нет). Значит весь
счёт там — истинное каскадное суммирование, воспроизведённое моделью.

КАНАЛЫ СУММИРОВАНИЯ (IAEA NDS/ENSDF, корпус sci-search):
  356,013 (437,0113->80,9979) + 80,998 (80,9979->0) = 437,011 — нет линии;
  302,851 (383,8491->80,9979) + 80,998                = 383,849 — ЕСТЬ линия.
Первый канал (произв. выходов 62,05*32,95) сильнее второго (18,34*32,95) в
3,4 раза и ложится на пустое место 437; второй подпирает реальную 383,849.

ПЕРЕХОД 80,998 СИЛЬНО КОНВЕРСИОННЫЙ — без этого множителя расчёт сум-пиков
неверен в 2,6 раза. По IAEA NDS (rad_types=e, разделение по энергиям связи
Cs): для перехода 80,998 конверсионные электроны K 45,011 (42,504 %),
L 75,281 (7,117 %), M 79,778 (1,473 %), N 80,765 (0,309 %), O 80,973
(0,042 %), Σ = 51,44 %. При I_gamma = 32,949 % это alpha_total = 1,561 и

    P(гамма | переход 80,998) = 32,949 / 84,393 = 0,390

Признак, видимый прямо в данных модели без справочника: эмиссий 356
(246642) БОЛЬШЕ, чем эмиссий 81 (143719) — в обязательном каскаде
дочерних квантов не может быть меньше родительских.

БАЗА расчёта — пик356 ПЛЮС события, ушедшие в сум-пик: они тоже были
полнопоглощёнными по 356.

КАНАЛ РЕНТГЕНА Cs. Конверсия создаёт K-вакансию, и рентген K-серии Cs
идёт с интенсивностью больше кванта на распад (модель: Kalpha 97,7 %,
Kbeta 22,0 % на распад). 356,013 + 30,973 = 386,99 кэВ — это 0,08 ПШПВ от
383,849, то есть ВНУТРИ фотопика, отдельным пиком не видно. Канал найден
аудитором; в модели присутствует.

ИЗМЕРЕНИЕ СУМ-ИН независимо от формул: сравнение eps_p из спектра распада
с eps_p моно-сетки (сетка суммирования не содержит). Отношение
распад/сетка: 81 -> 1,011; 302,9 -> 0,985; 356,0 -> 0,963 (сум-АУТ);
383,8 -> 1,089 (сум-ИН). Избыток на 384 = 77 отсчётов, из них гамма-канал
302x81 даёт 37, остаток ~40 — рентгеновский канал.

РАЗДЕЛИТЕЛЬ каналов в измерении: рентгеновский сидит на +3...+7 кэВ и
тянет центроид 384 ВВЕРХ, утечка от 356 тянула бы ВНИЗ. Знак сдвига
центроида измерим.

Репер 662 чист: у Cs-137 такого канала нет (661,657 излучает Ba-137m с
T1/2 2,552 мин, мгновенных совпадений нет).

Спектры p5_Ba133.csv / p5_Ba133_emit.csv в рабочем каталоге модели, в
репозиторий не входят.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402

RESULTS = os.path.abspath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "results"))

# Выходы линий Ba-133 (осн. состояние, p_energy==0), % — IAEA NDS/ENSDF.
YIELD = {80.998: 32.949, 302.851: 18.336, 356.013: 62.05, 383.849: 8.941,
         437.011: 0.0}
# Доля гамма-канала перехода 80,998 (остальное — конверсионные электроны).
P_GAMMA_81 = 0.390
# Чистая singles-эффективность 81 кэВ из МОНО-прогона (не из распада: там
# она занижена сум-аутом). scat_p5_full_E81.0.csv, N=1600000, пик 69976.
EPS_P_81_MONO = 0.04374


def peak(path, E0, half=3.0):
    s = 0.0
    for ln in open(path, encoding="utf-8"):
        if ln.startswith(("#", "E_keV")) or not ln.strip():
            continue
        e, c = ln.split(",")
        if abs(float(e) - E0) < half:
            s += float(c)
    return s


def find_build():
    b = os.environ.get("G4MODELS_BUILD_GAMMA_1S")
    for c in ([b] if b else []):
        if c and os.path.exists(os.path.join(c, "p5_Ba133.csv")):
            return c
    raise SystemExit(
        "Не найден p5_Ba133.csv. Задайте G4MODELS_BUILD_GAMMA_1S или\n"
        "воспроизведите: python detectors/Gamma-1S/drivers/run_point_decay.py")


if __name__ == "__main__":
    build = find_build()
    dep = os.path.join(build, "p5_Ba133.csv")
    emit = os.path.join(build, "p5_Ba133_emit.csv")

    print("Сум-пик Ba-133 437 кэВ, модель точечной 5 см, истинное"
          " суммирование.\n")
    print("%-10s %8s %10s %10s %s"
          % ("E, кэВ", "выход,%", "депозит", "эмиссия", "заметка"))
    rows = []
    for E0 in (80.998, 302.851, 356.013, 383.849, 437.011):
        d, e = peak(dep, E0), peak(emit, E0)
        note = ("ФАНТОМ: эмиссии нет, весь счёт от суммирования"
                if E0 == 437.011 else "")
        print("%-10.3f %8.3f %10.0f %10.0f %s"
              % (E0, YIELD[E0], d, e, note))
        rows.append((E0, YIELD[E0], d, e))

    d437 = peak(dep, 437.011)
    d384 = peak(dep, 383.849)
    d356 = peak(dep, 356.013)
    d302 = peak(dep, 302.851)
    e437 = peak(emit, 437.011)
    print("\nФантом 437,011: депозит %.0f, эмиссия %.0f." % (d437, e437))
    if e437 == 0:
        print("  Эмиссия НУЛЕВАЯ -> модель воспроизводит истинное каскадное"
              " суммирование, а не линию.")

    print("\nКонтроль конверсии прямо в данных (без справочника):")
    print("  эмиссий 356 = %.0f, эмиссий 81 = %.0f — дочерних МЕНЬШЕ"
          " родительских," % (peak(emit, 356.013), peak(emit, 80.998)))
    print("  что в обязательном каскаде невозможно: переход 80,998 идёт"
          " гаммой лишь в %.1f %% случаев." % (100 * P_GAMMA_81))

    print("\nПредсказание сум-пиков (база = пик + ушедшее в сум-пик):")
    pred437 = (d356 + d437) * P_GAMMA_81 * EPS_P_81_MONO
    pred384 = d302 * P_GAMMA_81 * EPS_P_81_MONO
    print("  437,011 = (%.0f+%.0f)*%.3f*%.5f = %.0f; наблюдение %.0f;"
          " набл/пред %.2f"
          % (d356, d437, P_GAMMA_81, EPS_P_81_MONO, pred437, d437,
             d437 / pred437))
    print("  подавление %.0f %% — масштаб угловой корреляции каскада"
          % (100 * (1 - d437 / pred437)))
    print("  гамма-канал 302x81 в линию 383,849 = %.0f отсчётов (%.1f %%"
          " линии)" % (pred384, 100 * pred384 / d384))
    print("  БЕЗ множителя %.3f предсказание было бы завышено в %.1f раза —"
          " это и была ошибка первого захода."
          % (P_GAMMA_81, 1 / P_GAMMA_81))

    csvio.write(
        os.path.join(RESULTS, "ba133_sumpeak.csv"),
        ["E_keV", "yield_pct", "deposit_counts", "emission_counts"],
        [("%.3f" % E, "%.3f" % y, "%.0f" % d, "%.0f" % e)
         for E, y, d, e in rows],
        comments=[
            "Ba-133 точечная 5 см; МК-спектр распада с истинным"
            " суммированием (resolving_time 1000 нс; 400000 распадов).",
            "437,011 кэВ — сум-пик 356,013 плюс 80,998; реальной линии нет"
            " (выход 0; эмиссия 0); весь депозит от суммирования.",
            "Переход 80;998 сильно конверсионный: alpha_total = 1;561;"
            " P(гамма) = 0;390 (IAEA NDS rad_types=e). Без этого множителя",
            "  расчёт сум-пиков завышен в 2;6 раза — ошибка первого захода.",
            "Предсказание 437 = (пик356 + N_437)*0;390*eps_p81_моно(0;04374)"
            " = 107; наблюдение 97; набл/пред 0;91 — подавление 9 %",
            "  масштаба угловой корреляции каскада.",
            "Сум-ин измерен независимо сравнением с моно-сеткой: отношение"
            " распад/сетка 356 -> 0;963 (сум-аут); 384 -> 1;089 (сум-ин);",
            "  избыток на 384 = 77 отсчётов; гамма-канал 302x81 даёт 37;"
            " остаток ~40 — канал 356 + рентген K-серии Cs.",
        ])
    print("\nтаблица: %s" % os.path.join(RESULTS, "ba133_sumpeak.csv"))
