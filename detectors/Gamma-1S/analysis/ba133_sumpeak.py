"""Сум-пик Ba-133 437 кэВ на модели: проверка ВНЕ фотопика (задача 124).

ЗАЧЕМ. Все сравнения с аттестованной кривой — проверка транспорта:
отношение активностей есть тождество полиномов (разбор аудитора). Сум-пик
437,011 кэВ (356,013 плюс 80,998, реальной линии нет) задаётся ПОЛНОЙ
эффективностью eps_T(81 кэВ), которую аттестованная кривая по фотопику НЕ
ограничивает. Модель предсказывает eps_T сама — это первая величина в
проекте, проверяющая модель напрямую, не через полином.

ЧТО ПОДТВЕРЖДЕНО. В МК-спектре распада Ba-133 точечной 5 см (истинное
суммирование, resolving_time 1000 нс) фотопик-фантом 437,011 существует:
депозит есть, ЭМИССИИ на 437 нет вовсе (в природе линии нет). Значит весь
счёт там — истинное каскадное суммирование, воспроизведённое моделью.

КАНАЛЫ СУММИРОВАНИЯ (IAEA NDS/ENSDF, корпус sci-search):
  356,013 (437,0113->80,9979) + 80,998 (80,9979->0) = 437,011 — нет линии;
  302,851 (383,8491->80,9979) + 80,998                = 383,849 — ЕСТЬ линия.
Первый канал (произв. выходов 62,05*32,95) сильнее второго (18,34*32,95) в
3,4 раза и ложится на пустое место 437; второй подпирает реальную 383,849.

КОЛИЧЕСТВЕННАЯ СВЕРКА с измеренными +38 % на 383,849 (21000 Бк против
12300-15600 по чистым линиям) требует размытия модели приборным ПШПВ и
фита той же конвенцией — отложена до решения по модели фона (задача 115).
Здесь — модельные депозит-площади и доля суммирования.

Спектры p5_Ba133.csv / p5_Ba133_emit.csv в рабочем каталоге модели, в
репозиторий не входят.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402

RESULTS = os.path.abspath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "results"))

# Выходы линий Ba-133 (осн. состояние, p_energy==0), % — IAEA NDS/ENSDF.
YIELD = {80.998: 32.949, 302.851: 18.336, 356.013: 62.05, 383.849: 8.941,
         437.011: 0.0}


def peak(path, E0, half=3.0):
    s = 0.0
    for ln in open(path, encoding="utf-8"):
        if ln.startswith(("#", "E_keV")) or not ln.strip():
            continue
        e, c = ln.split(",")
        if abs(float(e) - E0) < half:
            s += float(c)
    return s


def find_build():
    b = os.environ.get("G4MODELS_BUILD_GAMMA_1S")
    for c in ([b] if b else []) + [r"C:\g4work\gamma1s\build"]:
        if c and os.path.exists(os.path.join(c, "p5_Ba133.csv")):
            return c
    raise SystemExit(
        "Не найден p5_Ba133.csv. Задайте G4MODELS_BUILD_GAMMA_1S или\n"
        "воспроизведите: python detectors/Gamma-1S/drivers/run_point_decay.py")


if __name__ == "__main__":
    build = find_build()
    dep = os.path.join(build, "p5_Ba133.csv")
    emit = os.path.join(build, "p5_Ba133_emit.csv")

    print("Сум-пик Ba-133 437 кэВ, модель точечной 5 см, истинное"
          " суммирование.\n")
    print("%-10s %8s %10s %10s %s"
          % ("E, кэВ", "выход,%", "депозит", "эмиссия", "заметка"))
    rows = []
    for E0 in (80.998, 302.851, 356.013, 383.849, 437.011):
        d, e = peak(dep, E0), peak(emit, E0)
        note = ("ФАНТОМ: эмиссии нет, весь счёт от суммирования"
                if E0 == 437.011 else "")
        print("%-10.3f %8.3f %10.0f %10.0f %s"
              % (E0, YIELD[E0], d, e, note))
        rows.append((E0, YIELD[E0], d, e))

    d437 = peak(dep, 437.011)
    d384 = peak(dep, 383.849)
    e437 = peak(emit, 437.011)
    print("\nФантом 437,011: депозит %.0f, эмиссия %.0f." % (d437, e437))
    if e437 == 0:
        print("  Эмиссия НУЛЕВАЯ -> модель воспроизводит истинное каскадное"
              " суммирование, а не линию.")
    print("  Доля фантома от линии 383,849: %.1f %%." % (100 * d437 / d384))
    print("  Величина задаётся полной eps_T(81 кэВ), аттестованной кривой"
          " по фотопику НЕ ограниченной — прямая проверка модели.")

    csvio.write(
        os.path.join(RESULTS, "ba133_sumpeak.csv"),
        ["E_keV", "yield_pct", "deposit_counts", "emission_counts"],
        [("%.3f" % E, "%.3f" % y, "%.0f" % d, "%.0f" % e)
         for E, y, d, e in rows],
        comments=[
            "Ba-133 точечная 5 см; МК-спектр распада с истинным"
            " суммированием (resolving_time 1000 нс; 400000 распадов).",
            "437,011 кэВ — сум-пик 356,013 плюс 80,998; реальной линии нет"
            " (выход 0; эмиссия 0); весь депозит от суммирования.",
            "Величина фантома задаётся полной eps_T(81 кэВ); аттестованная"
            " кривая её не ограничивает — проверка модели вне фотопика.",
            "Количественная сверка с измеренными +38 % на 383;849"
            " отложена до модели фона фита (задача 115).",
        ])
    print("\nтаблица: %s" % os.path.join(RESULTS, "ba133_sumpeak.csv"))
