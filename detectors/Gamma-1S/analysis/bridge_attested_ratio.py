"""Отношение штатная/наша на линиях Th-228: значение, погрешность, ковариация
(задача 151, хвост P1-4; версия 4 — после внешнего аудита 01.08.2026).

ЧТО СЧИТАЕТСЯ. Отношение аттестованной эффективности к расчётной на четырёх
чистых линиях Th-228, по коэффициентам полиномов зон .efa обеих кривых.
Опора — тождество

    A_наша / A_штатная  =  eps_штатная(E) / eps_наша(E)   [при одной площади]

Тождество следует из формулы активности производителя: все поправки (на
самопоглощение, на суммирование, на истинные совпадения) входят в один
мультипликативный знаменатель вместе с эффективностью, поэтому не зависящее
от кривой сокращается точно. Подтверждено и прогоном программы обработки
30.07.2026 на записи с шестью линиями одного нуклида.

ПОЧЕМУ ПОЛИНОМ, А НЕ УЗЕЛ ФАЙЛА. Программа считает активность по полиному
зон, а не по точкам (доказано прогоном: подмена узлов ничего не меняла, пока
секция Zones оставалась мастерской — см. `export_point5cm.py`). Сам штатный
полином отходит от своих узлов до нескольких процентов, поэтому узловое
чтение считало бы не ту величину, которую тождество связывает с прогоном.

ПОГРЕШНОСТЬ — СТРОГАЯ, С КОВАРИАЦИЕЙ (версия 4). Раньше здесь стояло
4-е поле Zone_k, переведённое как 10**D-1, одинаковое для всех линий зоны.
Внешний аудит показал две ошибки: (1) конвенция ЛСРМ определяет погрешность
как 230*D*||Q(X)||, то есть с множителем нормы базисного вектора, который
на 2614,5 кэВ равен 3,61 и был отброшен; (2) комбинировать погрешности
разных линий одной кривой квадратурой нельзя — они предсказаны одним
полиномом и коррелированы.

Теперь погрешность считается модулем `efa_cov` как строгая погрешность
предсказания взвешенного МНК, и рядом выдаётся ковариационная матрица.
Погрешность нашей стороны — сумма двух источников: аппроксимация гладкой
расчётной кривой полиномом (мала) и статистика Монте-Карло самой сетки
(`results/eff_p5cm.csv`, лог-лог интерполяция между узлами). Погрешность
штатной стороны включает разброс экспериментальных точек аттестации через
оценку дисперсии единицы веса.

СЛЕДСТВИЕ. Погрешность отношения НЕ плоская по энергии: 1,2…1,3 % на
плато против 3,2 % на 2614,5 кэВ — жёсткий край определён втрое хуже, и
прежняя плоская оценка прятала именно ту особенность, ради которой линия
взята реперной.

ИСТОЧНИКИ.
  - Штатный полином — блок «Точечная-5см» рабочего файла прибора
    `G1S_LSRM_MASTER_EFA`. Файл несёт заводской номер в имени и в шапке,
    поэтому путь задаётся переменной окружения; при её отсутствии берётся
    обезличенная копия того же файла, закоммиченная в `reference/lsrm`
    (числовая часть совпадает, проверяется хешем блока — см. ниже).
  - Наш полином — `results/efa_export/G4MC_проба_Точечная-5см.efa`.

ХЕШ БЛОКА В ШТАМПЕ. В рабочем каталоге прибора лежит более одного
многоблочного .efa, и их полиномы на 2614,5 кэВ расходятся заметно: у
одного узел на этой энергии есть, у другого его нет и полином там
экстраполирует. Молчаливая подмена файла изменила бы центральный результат,
поэтому хеш прочитанного блока пишется в штамп таблицы. Хеш идентификатором
прибора не является.
"""
import hashlib
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402
import paths  # noqa: E402
import stamp  # noqa: E402

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import efa_cov  # noqa: E402

RESULTS = str(paths.results("Gamma-1S"))
GEOM = "Точечная-5см"
OURS_EFA = os.path.join(RESULTS, "efa_export", "G4MC_проба_Точечная-5см.efa")
GRID_CSV = os.path.join(RESULTS, "eff_p5cm.csv")

# Те же четыре чистые линии, что в hard_edge_th228.CLEAN — единственные, для
# которых плато и жёсткий край разделены по независимому физическому критерию.
LINES = (583.187, 727.330, 860.557, 2614.511)

OBS = {
    "quantity": "отношение eps_штатная(E)/eps_наша(E) на линиях Th-228 по"
                " полиномам зон .efa; с погрешностью предсказания фита и"
                " ковариацией между линиями",
    "area": "не применимо — величина не из съёма площади; а из полинома"
            " градуировочной характеристики",
    "window": "не применимо",
    "shelf": "не применимо",
    "blurred": "не применимо",
}


def master_path():
    """Путь к штатному .efa: переменная окружения либо committed-копия."""
    env = os.environ.get("G1S_LSRM_MASTER_EFA")
    if env and os.path.exists(env):
        return env, "рабочий каталог прибора"
    fallback = paths.efficiency_curve(GEOM, "efa")
    if fallback and os.path.exists(str(fallback)):
        return str(fallback), "committed reference (обезличенная копия)"
    raise SystemExit(
        "Не найден штатный .efa: ни G1S_LSRM_MASTER_EFA, ни копия в"
        " reference/lsrm.\nБез него отношение не посчитать.")


def block_sha1(path, geom):
    """Хеш числовой части блока — сторож против подмены исходного файла."""
    body = "\n".join(ln.strip() for ln in efa_cov.block_of(path, geom)
                     if "=" in ln and not ln.startswith("["))
    return hashlib.sha1(body.encode("utf-8")).hexdigest()[:12]


def mc_rel(E):
    """Относительная статистическая погрешность расчётной сетки в точке E.

    Точный узел сетки — d_eps/eps напрямую; между узлами — лог-лог
    интерполяция обеих величин по отдельности, тем же правилом, каким
    `export_point5cm.py` интерполирует саму кривую.
    """
    rows = []
    for r in csvio.read(GRID_CSV):
        rows.append((float(r["E_keV"]), float(r["eps_net"]), float(r["d_eps"])))
    rows.sort()
    for e, eps, d in rows:
        if abs(e - E) <= 0.01:
            return d / eps
    xs = [math.log(e) for e, _1, _2 in rows]
    x = math.log(E)
    i = next((k for k, v in enumerate(xs) if v >= x), len(xs) - 1)
    i = max(1, min(i, len(xs) - 1))
    (_e0, p0, d0), (_e1, p1, d1) = rows[i - 1], rows[i]
    t = (x - xs[i - 1]) / (xs[i] - xs[i - 1])
    eps = math.exp(math.log(p0) + t * (math.log(p1) - math.log(p0)))
    d = math.exp(math.log(d0) + t * (math.log(d1) - math.log(d0)))
    return d / eps


def main():
    mpath, msrc = master_path()
    if not os.path.exists(OURS_EFA):
        raise SystemExit("Нет %s — прогнать export_point5cm.py." % OURS_EFA)
    if not os.path.exists(GRID_CSV):
        raise SystemExit("Нет %s — прогнать export_curves.py." % GRID_CSV)

    m = efa_cov.Curve(mpath, GEOM)
    o = efa_cov.Curve(OURS_EFA, GEOM)
    msha = block_sha1(mpath, GEOM)

    print("Отношение штатная/наша на линиях Th-228 (полиномы зон .efa).")
    print("Штатная кривая: %s; хеш блока %s.\n" % (msrc, msha))
    print("%10s %13s %13s %9s %10s %7s"
          % ("E, кэВ", "eps штатн.", "eps наша", "r=шт/наш", "превыш.%", "+-%"))
    rows = []
    for E in LINES:
        em, eo = m.eps(E), o.eps(E)
        r = em / eo
        # ln r = ln eps_m - ln eps_o; источники независимы, статистика
        # расчётной сетки добавляется отдельным независимым членом.
        var = m.cov_ln(E, E) + o.cov_ln(E, E) + mc_rel(E) ** 2
        d_rel = math.sqrt(var)
        print("%10.3f %13.4e %13.4e %9.4f %+10.2f %7.2f"
              % (E, em, eo, r, 100 * (1 / r - 1), 100 * d_rel))
        rows.append((E, em, eo, r, 100 * d_rel,
                     100 * m.d_rel(E), 100 * o.d_rel(E), 100 * mc_rel(E)))

    print("\nКорреляции отношения между линиями (одна кривая — один полином):")
    corr = {}
    for i, E1 in enumerate(LINES):
        for E2 in LINES[i + 1:]:
            c = m.cov_ln(E1, E2) + o.cov_ln(E1, E2)
            s1 = math.sqrt(m.cov_ln(E1, E1) + o.cov_ln(E1, E1) + mc_rel(E1) ** 2)
            s2 = math.sqrt(m.cov_ln(E2, E2) + o.cov_ln(E2, E2) + mc_rel(E2) ** 2)
            corr[(E1, E2)] = c / (s1 * s2)
            print("   ро(%8.3f; %8.3f) = %+.3f" % (E1, E2, corr[(E1, E2)]))
    print("\nОтрицательная корреляция плато с краем означает, что для их"
          " РАЗНОСТИ квадратура ЗАНИЖАЕТ погрешность:")
    print("остаток сверх плато обязан считаться с ковариацией"
          " (residual_budget_2614.py).")

    print("\nСверка со формой производителя (230*D*||Q||), %:")
    print("%10s %12s %12s" % ("E, кэВ", "штатная строго", "по формуле"))
    for E in LINES:
        print("%10.3f %11.2f %11.2f"
              % (E, 100 * m.d_rel(E), m.lsrm_delta_pct(E)))

    csvio.write(
        os.path.join(RESULTS, "bridge_attested_ratio.csv"),
        ["E_keV", "eps_master", "eps_ours", "ratio_attested_over_ours",
         "d_ratio_pct", "d_master_pct", "d_ours_fit_pct", "d_ours_mc_pct"],
        [("%.3f" % E, "%.6e" % em, "%.6e" % eo, "%.4f" % r, "%.3f" % dr,
          "%.3f" % dm, "%.3f" % do, "%.3f" % dmc)
         for E, em, eo, r, dr, dm, do, dmc in rows],
        comments=[
            "r(E) = eps_master(E)/eps_ours(E) по коэффициентам полиномов зон"
            " .efa обеих кривых. Тождество r = A_наша/A_штатная при одной"
            " площади следует из формулы активности производителя и"
            " подтверждено прогоном программы 30.07.2026.",
            "d_ratio_pct — СТРОГАЯ погрешность предсказания взвешенного МНК"
            " (модуль efa_cov); складывается из трёх независимых источников:"
            " d_master_pct (включает разброс точек аттестации);"
            " d_ours_fit_pct (аппроксимация расчётной кривой полиномом);"
            " d_ours_mc_pct (статистика Монте-Карло; eff_p5cm.csv).",
            "ВАЖНО: линии одной кривой КОРРЕЛИРОВАНЫ (один полином одной"
            " зоны); ковариация плато с краем ОТРИЦАТЕЛЬНА; поэтому для их"
            " разности квадратура занижает погрешность. Комбинировать"
            " величины по нескольким линиям — только через efa_cov.combo.",
            "Погрешность НЕ плоская по энергии: жёсткий край определён"
            " примерно втрое хуже плато. Прежняя версия таблицы давала"
            " одинаковое число на все линии зоны (4-е поле Zone_k без"
            " множителя нормы базиса) — отозвано внешним аудитом 01.08.2026.",
            "master_block_sha1 в штампе — сторож против подмены исходного"
            " .efa: в рабочем каталоге прибора их более одного; у части нет"
            " узла на 2614;5 кэВ; и полином там экстраполирует.",
        ],
        stamp=stamp.lines(
            "detectors/Gamma-1S/analysis/bridge_attested_ratio.py",
            dict(OBS, master_block_sha1=msha, master_source=msrc),
            geometry_dir=str(paths.geometry("Gamma-1S")),
            names=stamp.SRC_LISTS["Gamma-1S"], repo_dir=str(paths.REPO)))
    print("\nтаблица: %s" % os.path.join(RESULTS, "bridge_attested_ratio.csv"))


if __name__ == "__main__":
    main()
