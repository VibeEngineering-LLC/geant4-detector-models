"""Мост методик, ИЗМЕРЕННЫЙ программой обработки (сеанс 01.08.2026).

ОТЗЫВ (02.08.2026, состязательный аудит, вердикт НЕ ПОДТВЕРЖДЁН). Измерение
ниже дефектно: экспортированный `.spe` нёс в заголовке чужой полином ПШПВ
(95,8 кэВ на 2614,5, из опорной записи поверки 2016 года) вместо ширины,
которой спектр был реально размыт (108,4 кэВ) — программа читала шапку, а не
мерила пик. Собственный фит аудитора в заявленной конвенции прибора
воспроизводит прежний модельный мост (0,9626 против 0,9612), а не измеренное
здесь значение 0,8633. Все числа модуля и `bridge_measured.csv` цитированию
не подлежат — оставлены как есть по правилу репозитория «отозванное не
стирается, а помечается» (`common/docs/method-rules.md` §8). Подробности —
там же и в `article/gamma1s-method.md` (запись 02.08.2026).

ЧТО ЭТО (текст ниже — состояние ДО отзыва, сохранён для истории попытки). Поправка B(E) — во сколько раз конвенция съёма площади, принятая
при аттестации, отличается от истинной площади пика полного поглощения:

    B(E) = площадь, снятая программой / истинный ППП того же спектра

До 01.08.2026 B считался СВОИМ фитом, воспроизводящим конвенцию прибора
(`bridge_mono.py`: зона +-2,5 ПШПВ, полином 2-й степени, ступенька). Это
было приближение чужого алгоритма, и статья честно называла его
непроверенным: «прямая проверка — прогон тех же моноэнергетических
спектров через программу обработки — не выполнена».

ТЕПЕРЬ ПРОВЕРКА ВЫПОЛНЕНА. Моноэнергетические расчётные спектры
экспортированы в приборный формат (`export_mono_spe.py`) и обработаны
программой; площади сняты её штатным фитом. Условия сеанса: параметры
съёма из конфигурации прибора — зона пика +-2,5 ПШПВ (LeftPeakBound =
RightPeakBound = 2,5), подложка полиномом 2-й степени (BackgrPower = 2),
поправка на суммирование выключена (SummCorrection = 0). Это те же
параметры, которыми строилась аттестованная характеристика.

ГЛАВНЫЙ РЕЗУЛЬТАТ. Воспроизведение чужого алгоритма ошибалось НЕРАВНОМЕРНО
по энергии: на среднем участке диапазона своя реализация завышала B на
1,6...2,4 %, а на жёстком крае — на 10,2 %. Именно там, где решается
вывод о балансе. Механизм виден в самом замере: ширина фита программы на
2614,5 кэВ составила 95,8 кэВ против приборных 108,4 — алгоритм сжимает
пик примерно на 12 % и теряет его хвосты.

СЛЕДСТВИЕ. Несведённый остаток на жёстком крае падает с +12,8 % (по
модельному мосту) до +3,4 % (по измеренному) — то есть становится
сравним со своей неопределённостью. Отсюда пересматривается заключение
раздела о пригодности; см. `residual_budget_2614.py`.

ОГОВОРКИ, КОТОРЫЕ ОСТАЮТСЯ.
  - Спектры моноэнергетические: континуум под пиком только собственный, а
    на реальной записи Th-228 добавляется континуум соседних линий.
    Перенос B на многолинейчатую запись остаётся приближением, хотя уже
    не приближением алгоритма.
  - Энергетическая шкала экспортированных спектров взята из записи
    поверки 2016 года, и центроиды в сеансе смещены вправо на 3,6...6,7
    кэВ. На площадь это не влияет (программа снимает её там, где пик
    стоит), но при следующем экспорте шкалу брать из свежей записи.
  - Линия 122,1 кэВ приведена справочно: окно полки конвенции лежит там
    ближе центра, чем одна ПШПВ, и конвенция к ней неприменима по
    арифметике (та же оговорка, что в `bridge_mono.py`).
"""
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402
import paths  # noqa: E402
import stamp  # noqa: E402

RESULTS = str(paths.results("Gamma-1S"))

# Сеанс 01.08.2026. Ключ — линия; значения: площадь, снятая программой;
# истинный ППП того же спектра (печатается экспортёром в комментарий .spe);
# ширина фита программы, кэВ; центроид, кэВ; неопределённость центроида.
# Числа перенесены из окна «Параметры пиков» вручную — это ЕДИНСТВЕННОЕ
# место, где они вводятся, и дальше читаются только отсюда.
MEASURED = {
    122.100: (67572, 71185, 13.802, 125.707, 0.431),
    583.187: (25253, 25702, 39.034, 587.580, 0.380),
    661.657: (22300, 22753, 41.889, 665.739, 0.417),
    727.330: (20327, 20752, 44.282, 731.410, 0.499),
    860.557: (17210, 17578, 49.428, 863.874, 0.582),
    2614.511: (5133, 5946, 95.803, 2621.197, 1.432),
}
# Линия вне области применимости конвенции (см. докстроку).
REFERENCE_ONLY = (122.100,)

OBS = {
    "quantity": "B(E) — отношение площади; снятой программой обработки; к"
                " истинному пику полного поглощения того же спектра."
                " ИЗМЕРЕНО программой; не воспроизведено своим фитом",
    "area": "числитель — чистая площадь штатного фита программы (подложка"
            " вычтена ею же); знаменатель — сумма отсчётов истинного пика"
            " депозит-спектра; печатается экспортёром в шапку .spe",
    "window": "конвенция прибора: зона пика +-2;5 ПШПВ; подложка полиномом"
              " 2-й степени; поправка на суммирование выключена",
    "shelf": "подложку строит программа; своя реализация не применяется",
    "blurred": "да — спектры размыты приборной шириной перед экспортом"
               " (той же; какой размывает bridge_mono.py)",
    "geometry": "точечный источник на оси; 5 см от наружной поверхности"
                " корпуса; полный 4pi",
}


def main():
    rows = []
    print("Мост методик, ИЗМЕРЕННЫЙ программой обработки (сеанс 01.08.2026)")
    print("ОТЗЫВ 02.08.2026: измерение дефектно (программа читала чужой")
    print("полином ПШПВ из шапки .spe, не мерила пик) — см. докстроку модуля\n")
    print("%10s %10s %10s %8s %9s %9s"
          % ("E, кэВ", "площадь", "истинный", "B", "ПШПВ фит", "центроид"))
    for E in sorted(MEASURED):
        area, true, fw, cen, dcen = MEASURED[E]
        B = area / true
        # Погрешность B: пуассон числителя и знаменателя. Они сняты с ОДНИХ
        # событий и потому коррелированы — сумма в квадратурах есть ВЕРХНЯЯ
        # оценка, та же конвенция, что в bridge_mono.py.
        dB = B * math.hypot(1.0 / math.sqrt(max(area, 1)),
                            1.0 / math.sqrt(max(true, 1)))
        tag = "справочно" if E in REFERENCE_ONLY else ""
        print("%10.3f %10d %10d %8.4f %9.1f %9.1f  %s"
              % (E, area, true, B, fw, cen, tag))
        rows.append((E, area, true, B, dB, fw, cen, dcen,
                     0 if E in REFERENCE_ONLY else 1))

    dec = [(E, B) for E, _a, _t, B, _d, _f, _c, _dc, u in rows if u]
    plat = [B for E, B in dec if E < 2000.0]
    edge = [B for E, B in dec if E >= 2000.0]
    if plat:
        m = sum(plat) / len(plat)
        print("\nсредний участок (%d линии): B = %.4f; разброс %.4f"
              % (len(plat), m, max(plat) - min(plat)))
    if edge:
        print("жёсткий край: B = %.4f" % edge[0])
        if plat:
            print("край/участок = %.4f — во столько раз конвенция теряет на"
                  " краю БОЛЬШЕ; чем на среднем участке" % (edge[0] / m))

    csvio.write(
        os.path.join(RESULTS, "bridge_measured.csv"),
        ["E_keV", "area_program", "area_true", "bridge", "d_bridge",
         "fwhm_fit_keV", "centroid_keV", "d_centroid_keV", "decisive"],
        [("%.3f" % E, "%d" % a, "%d" % t, "%.4f" % B, "%.4f" % dB,
          "%.3f" % f, "%.3f" % c, "%.3f" % dc, "%d" % u)
         for E, a, t, B, dB, f, c, dc, u in rows],
        comments=[
            "ОТЗЫВ 02.08.2026 (состязательный аудит): измерение ниже"
            " дефектно, программа читала чужой полином ПШПВ из шапки .spe"
            " (95;8 кэВ; запись поверки 2016), а не мерила реально размытый"
            " пик (108;4 кэВ). Цитированию не подлежит; подробности --"
            " common/docs/method-rules.md §8.",
            "B(E) ИЗМЕРЕН программой обработки; а не воспроизведён своим"
            " фитом (сеанс 01.08.2026). Условия: зона пика +-2;5 ПШПВ;"
            " подложка полиномом 2-й степени; поправка на суммирование"
            " выключена — параметры конфигурации прибора.",
            "Сравнение с модельным мостом (bridge_mono.csv): своя"
            " реализация завышала B на 1;6...2;4 % на среднем участке"
            " и на 10;2 % на жёстком крае. Ошибка НЕРАВНОМЕРНА по энергии;"
            " и максимальна там; где решается вывод о балансе.",
            "Механизм: ширина фита программы на 2614;5 кэВ равна 95;8 кэВ"
            " против приборных 108;4 — алгоритм сжимает пик примерно на"
            " 12 % и теряет хвосты.",
            "d_bridge — верхняя оценка: числитель и знаменатель сняты с"
            " одних событий и коррелированы.",
            "decisive=0 — линия 122;1 кэВ; окно полки конвенции лежит там"
            " ближе центра; чем одна ПШПВ; конвенция к ней неприменима.",
            "Центроиды смещены вправо на 3;6...6;7 кэВ: энергетическая"
            " шкала экспорта взята из записи поверки 2016 года. На площадь"
            " не влияет; при следующем экспорте брать свежую шкалу.",
        ],
        stamp=stamp.lines(
            "detectors/Gamma-1S/analysis/bridge_measured.py", OBS,
            geometry_dir=str(paths.geometry("Gamma-1S")),
            names=stamp.SRC_LISTS["Gamma-1S"], repo_dir=str(paths.REPO)))
    print("\nтаблица: %s" % os.path.join(RESULTS, "bridge_measured.csv"))


if __name__ == "__main__":
    main()
