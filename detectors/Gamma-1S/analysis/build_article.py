def tabs_and_panels(items, group, slug_of):
    """items: список (label, html). group: id-префикс группы вкладок."""
    btns, panels = [], []
    for i, (label, body) in enumerate(items):
        slug = slug_of(label, i)
        btns.append(
            '<button type="button" role="tab" data-panel="%s-%s" '
            'data-group="%s" aria-selected="%s">%s</button>'
            % (group, slug, group, "true" if i == 0 else "false", esc(label)))
        panels.append(
            '<div class="panel" id="%s-%s" data-group="%s"%s>%s</div>'
            % (group, slug, group, "" if i == 0 else " hidden", body))
    return ('<div class="tabs" role="tablist">%s</div>' % "".join(btns),
            "".join(panels))


