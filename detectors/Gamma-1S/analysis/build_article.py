import re

# главные разделы диссертационной нити — нумеруются 1..10 в порядке появления;
# служебные (Воспроизведение, Ссылки, Приложение) остаются без номера.
_MAIN_IDS = ["checks", "compare", "setup", "spectra", "curves", "spectraline",
             "georesp", "where", "vessels", "answer-h"]


def number_sections(page_html):
    counter = [0]

    def repl(m):
        sid = m.group(1)
        if sid in _MAIN_IDS:
            counter[0] += 1
            return '<h2 id="%s">%d.&nbsp;%s</h2>' % (sid, counter[0], m.group(2))
        return m.group(0)

    return re.sub(r'<h2 id="([a-z0-9-]+)">(.*?)</h2>', repl, page_html,
                  flags=re.S)


def external_blank(page_html):
    """Внешние ссылки (http/https) — открывать в новом окне. Внутренние якоря
    (#…) и относительные ссылки не трогаются."""
    def repl(m):
        attrs = m.group(1)
        if "target=" in attrs:
            return m.group(0)
        return '<a %s target="_blank" rel="noopener noreferrer">' % attrs.strip()

    return re.sub(r'<a\s+([^>]*href="https?://[^"]*"[^>]*)>', repl, page_html)


