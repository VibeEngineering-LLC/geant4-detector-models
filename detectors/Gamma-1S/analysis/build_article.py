def build():
    blocks, summary, srows = bw.geometry_data()
    spec_blocks, spec_rows, spec_legend, records = bw.spectra_section()
    gspan, gn = bw.grid_span()

    geo_items = [(title, html_) for title, html_ in blocks]
    geo_tabs, geo_panels = tabs_and_panels(
        geo_items, "geo", lambda label, i: GEO_SLUG.get(label, "g%d" % i))

    rec_items = [("%s — %s" % (geo, nuc), html_) for geo, nuc, html_ in records]
    rec_slugs = {}

    def rec_slug(label, i):
        base = GEO_SLUG.get(label.split(" — ")[0], "x")
        n = rec_slugs.get(base, 0)
        rec_slugs[base] = n + 1
        return "%s-%d" % (base, n)

    rec_tabs, rec_panels = tabs_and_panels(rec_items, "rec", rec_slug)
    # Скрипт интерактивных спектров живёт в хвосте blocks у spectra_section();
    # сюда его надо добавить отдельно — панели записей без него остаются
    # пустыми контейнерами (пойманный дефект, а не теория).
    import spectra_figs as sf
    rec_panels += sf.SPECTRA_JS

    out = TMPL % dict(
        css_href=bw.CSS_HREF, ngeo=len(geo_items), gridspan=gspan,
        gridspanE=gspan[:-len(" кэВ")] if gspan.endswith(" кэВ") else gspan,
        gridn=gn, gridnusl=bw.nusl(gn),
        setup=bw.SETUP_HTML % dict(gridspan=gspan, gridn=gn,
                                   gridnusl=bw.nusl(gn)),
        georesp=bw.GEORESP_HTML,
        summary=srows, legend=bw.legend(True),
        geo_tabs=geo_tabs, geo_panels=geo_panels,
        deconv_legend=spec_legend, rec_tabs=rec_tabs, rec_panels=rec_panels,
        balance=bw.balance_table(), continuum=bw.continuum_table(),
        deconv=spec_rows, tab_js=TAB_JS)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("статья: %s (%.0f КБ)" % (OUT, os.path.getsize(OUT) / 1024))
    print("вкладок геометрий: %d, записей: %d" % (len(geo_items), len(rec_items)))


if __name__ == "__main__":
    build()
