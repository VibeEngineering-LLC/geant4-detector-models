"""Предсказание просадки узлов Th-228 моделью (путь 2 задачи 140; закрывает 142).

ЗАЧЕМ. Узлы аттестованной кривой, снятые с Th-228, лежат на 4…5 % ниже линии,
построенной по одиночным излучателям (`attested_cascade_check.py`). Совпадение
ВЕЛИЧИНЫ с независимым предсказанием было бы подтверждением куда более
сильным, чем совпадение знака.

ИТОГ (01.08.2026, длинный прогон, 3e6 распадов; пересмотрен адверсариальным
аудитом в тот же день). На короткой статистике модель на 860,6 кэВ давала
−3,29 ± 8,10 % — тот же знак, что наблюдение (−4,67 %), но погрешность (±8,1)
больше самой величины: тест был НЕ РАЗРЕШЁН, совпадение знака ничего не
доказывало (см. задачу 122 — тот же прогон был нужен обеим задачам). На
длинной статистике знак ПЕРЕВЕРНУЛСЯ: 727,3 кэВ +2,96 %, 860,6 кэВ +0,90 % —
оба положительные, наблюдение отрицательное на обеих линиях. Расхождение
2,1 и 1,5 сигмы (комбинированная погрешность: модель + собственная
погрешность узла + систематический пол опоры attested_cascade_check.py —
без пола сигма завышена до 2,4/1,7, аудит поймал). При ДВУХ линиях, худшая
из которых 1,5σ, и при том, что обе используют одну и ту же опорную прямую
(частичная, не полная независимость) — строгого «механизм опровергнут» эта
статистика не даёт. Вывод формулируется мягче: каскадное суммирование в
равновесной цепи Th-228, как её разыгрывает Geant4, наблюдённую просадку НЕ
ВОСПРОИЗВОДИТ ни знаком, ни величиной — это снимает вырождение (задача 142),
но не доказывает пайлап: он остаётся ЕДИНСТВЕННЫМ ИЗ РАССМОТРЕННЫХ кандидатов
правильного порядка и знака (3,7…4,9 % при загрузке записи,
`pileup_check.py`/`attestation_pileup.py`), сам количественно не проверен —
tau тракта не измерен по паспорту, а оценён на глаз (5 мкс/3 мкс в двух
скриптах, разные формулы).

ЧТО СЧИТАЕТСЯ. Поправка на каскадное суммирование `C = eps_моно / eps_распад`
для точечной геометрии 5 см:

  eps_моно   — эффективность на чистой моноэнергии (складывать не с чем);
  eps_распад — та же линия в прогоне полного распада Th-228, где часть
               отсчётов уходит из пика в суммарный.

`C > 1` означает, что в распаде пик недобирает. Код считает `under = 1/C − 1`
(отрицательное при `C > 1` — тем самым «занижение» кодируется отрицательным
числом, как и наблюдённая просадка); это число сравнивается с наблюдённой
просадкой напрямую, знак к знаку.

ОБЕ СТОРОНЫ СНИМАЮТСЯ ОДНИМ ПРАВИЛОМ — `peakwin.area`, окно и полка в каналах.
Разные конвенции на числителе и знаменателе дали бы `C`, в которую войдёт
разница правил, а не физика; этот класс дефекта в линии Гамма-1С ловился пять
раз за один вечер.

ЧЕГО СРАВНЕНИЕ НЕ ДОКАЗЫВАЕТ. `C` модели относится к цепочке Th-228 в том
изотопном равновесии, в каком её разыгрывает Geant4. Источник комплекта мог
быть в ином состоянии равновесия, и тогда доли каскадных переходов отличаются.
Совпадение величин — сильный довод, расхождение — не опровержение.
"""
