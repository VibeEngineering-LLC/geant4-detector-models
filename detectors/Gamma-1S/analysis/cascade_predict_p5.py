BUILD = str(paths.build("Gamma-1S"))
OUT = str(paths.results("Gamma-1S"))

DECAY = "p5_Th228_long"
# Моно-прогоны того же положения источника и того же 4pi — из набора моста
# (задача 115). Ключ — энергия линии, значение — имя файла.
MONO = {583.187: "bridge4pi_E0583.2.csv",
        727.330: "bridge4pi_E0727.3.csv",
        860.557: "bridge4pi_E0860.6.csv",
        2614.511: "bridge4pi_E2614.5.csv"}
# Наблюдённая просадка узла относительно опоры одиночных излучателей и её
# ПОЛНАЯ погрешность — results/attested_cascade_check.csv, столбцы
# dev_pct/d_node_pct, ДОПОЛНЕННЫЕ систематическим полом самой опоры
# (СКО остатков трёх опорных узлов вокруг степенной линии, тот же скрипт,
# geometry "точечная 5 см": 1,64 %; hypot(d_node_pct, 1.64), как считает
# сам attested_cascade_check.py при сводке своих выводов). Вне 662…1116 кэВ
# опоры нет — там None.
# НАЙДЕНО (01.08.2026, при закрытии задачи 142, адверсариальный аудит):
# (1) прежняя версия сравнивала разницу модель-минус-наблюдение только с
# погрешностью МОДЕЛИ (d_underest_pct) — сигма была завышена; исправлено
# квадратурой. (2) первая версия ЭТОГО исправления брала d_node_pct БЕЗ
# систематического пола опоры, которым сам attested_cascade_check.py
# пользуется для собственных выводов — несогласованность внутри одного
# обоснования; исправлено (пол внесён явно, ниже).
_FLOOR_P5 = 1.64  # systematic пол опоры, точечная 5 см (attested_cascade_check.py)
OBSERVED = {583.187: None,
            727.330: (-4.31, math.hypot(2.1734, _FLOOR_P5)),
            860.557: (-4.67, math.hypot(1.9028, _FLOOR_P5)),
            2614.511: None}

OBS = {
    "quantity": "C — поправка на каскадное суммирование для точечной 5 см;"
                " отношение эффективности на моноэнергии к эффективности"
                " той же линии в прогоне полного распада",
    "area": "чистая площадь пика за вычетом полки; ОДНО правило на обе"
            " стороны (common/py/peakwin.area)",
    "window": "+-6 кэВ в каналах; полка [E-25; E-10] — конвенция peakwin",
    "shelf": "односторонняя слева; вычитается на обеих сторонах одинаково",
    "blurred": "нет — депозит-спектры как есть",
    "geometry": "точечный источник z = 91 мм; полный 4pi; моно и распад в"
                " одинаковых условиях",
}


def read_hist(path):
    hist, N = {}, None
    for ln in open(path, encoding="utf-8"):
        if ln.startswith("#"):
            if "N_primaries" in ln:
                N = int(ln.split("=")[1])
            continue
        if ln and ln[0].isdigit():
            e, c = ln.split(",")
            hist[float(e)] = float(c)
    return hist, N


def emitted(E, tol=2.0):
    """Сколько квантов этой энергии испущено в прогоне распада.

    Из `*_emit.csv` того же расчёта, а не из справочника выходов: справочник —
    другой источник, и разница выходов вошла бы в C как физика.
    """
    p = os.path.join(BUILD, "%s_emit.csv" % DECAY)
    if not os.path.exists(p):
        return None
    tot = 0.0
    for ln in open(p, encoding="utf-8"):
        if ln.startswith("#") or not ln.strip():
            continue
        if ln[0].isdigit():
            e, c = ln.split(",")
            if abs(float(e) - E) <= tol:
                tot += float(c)
    return tot


def main():
    dpath = os.path.join(BUILD, "%s.csv" % DECAY)
    if not os.path.exists(dpath):
        raise SystemExit("Нет прогона распада %s в %s." % (DECAY, BUILD))
    dhist, _ = read_hist(dpath)

    print("Предсказание просадки: поправка на суммирование C для точечной"
          " 5 см.\n")
    print("%10s %12s %12s %8s %12s %12s %8s"
          % ("E, кэВ", "площ.распад", "испущено", "C", "занижение",
             "наблюдено", "разница"))
    rows = []
    for E in sorted(MONO):
        mp = os.path.join(BUILD, MONO[E])
        if not os.path.exists(mp):
            print("%10.3f  нет моно-прогона %s — пропущена" % (E, MONO[E]))
            continue
        mhist, mN = read_hist(mp)
        nem = emitted(E)
        if not nem:
            print("%10.3f  в *_emit.csv нет этой линии — пропущена" % E)
            continue
        a_mono = peakwin.area(mhist, E)
        a_dec = peakwin.area(dhist, E)
        eps_mono = a_mono / mN
        eps_dec = a_dec / nem
        C = eps_mono / eps_dec
        under = 100 * (1.0 / C - 1.0)          # занижение узла; %
        # Погрешность C определяется РАСПАДНОЙ стороной: там площадь пика на
        # два порядка меньше, чем в моно. Без этой строки предсказание из
        # сотни отсчётов выглядело бы наравне с наблюдением из миллиона.
        rel = math.sqrt(1.0 / max(a_dec, 1.0) + 1.0 / max(a_mono, 1.0))
        d_under = 100 * rel / C
        entry = OBSERVED.get(E)
        obs, d_obs = entry if entry is not None else (None, None)
        if obs is None:
            diff = ""
        else:
            diff = "%+.2f" % (under - obs)
        print("%10.3f %12.0f %12.0f %8.4f %8.2f+-%.2f %11s %8s"
              % (E, a_dec, nem, C, under, d_under,
                 "—" if obs is None else "%+.2f %%" % obs, diff))
        rows.append((E, a_dec, nem, C, under, d_under, obs, d_obs))

    print("\nВЫВОД.")
    pair = [(E, u, du, o, do) for E, _, _, _, u, du, o, do in rows
            if o is not None]
    if not pair:
        print("  Нет линий; где есть и предсказание; и наблюдение.")
    else:
        # Сигма — по КОМБИНИРОВАННОЙ погрешности обеих независимых сторон
        # (модель и наблюдение), не только модели: обе величины измерены
        # с конечной статистикой, складывать нужно в квадратуре. Прежняя
        # версия скрипта делила на d_under одной модели — сигма была
        # завышена (найдено 01.08.2026 при закрытии задачи 142).
        sig = [(E, u, du, o, do, math.sqrt(du ** 2 + do ** 2))
               for E, u, du, o, do in pair]
        for E, u, du, o, do, comb in sig:
            n = abs(u - o) / comb if comb > 0 else float("inf")
            same_sign = (u > 0) == (o > 0)
            print("  %.1f кэВ: модель %+.2f+-%.2f %%; наблюдается %+.2f+-%.2f"
                  " %%; расхождение %+.2f п.п. = %.1f сигмы (комб.); знак %s"
                  % (E, u, du, o, do, u - o, n,
                     "совпадает" if same_sign else "ПРОТИВОПОЛОЖЕН"))
        worst = max(abs(u - o) / comb for _, u, _, o, _, comb in sig)
        prec = max(comb for _, _, _, _, _, comb in sig)
        need = max(abs(o) for _, _, _, o, _, _ in sig)
        any_wrong_sign = any((u > 0) != (o > 0) for _, u, _, o, _, _ in sig)
        if prec > need:
            print("  ТЕСТ НЕ РАЗРЕШЁН. Точность сравнения (%.1f %%) хуже"
                  " самой проверяемой просадки (%.1f %%): ни совпадение,"
                  " ни расхождение здесь не довод." % (prec, need))
        elif any_wrong_sign:
            print("  ЗНАК НЕ СОВПАДАЕТ ни на одной из %d доступных линий"
                  " (худшее расхождение %.1f сигмы; линии делят одну"
                  " опорную прямую — не полностью независимы)."
                  % (len(sig), worst))
            print("  Каскадное суммирование, как его разыгрывает модель на"
                  " равновесной цепочке Geant4, наблюдённую просадку узлов"
                  " не воспроизводит ни знаком, ни величиной — это НЕ")
            print("  строгое статистическое опровержение при 1,5-2,1 сигмы"
                  " на двух точках, но и не подтверждение. Пайлап остаётся"
                  " ЕДИНСТВЕННЫМ ИЗ РАССМОТРЕННЫХ кандидатов верного порядка")
            print("  и знака (attestation_pileup.py/pileup_check.py) — сам"
                  " количественно не проверен независимо (tau тракта не"
                  " измерен по паспорту, а оценён на глаз).")
        elif worst < 2.0:
            print("  Величины СОГЛАСУЮТСЯ по знаку и величине (%.1f сигмы)"
                  " — независимый расчёт воспроизводит наблюдённую просадку;"
                  " механизм каскадного суммирования подтверждён." % worst)
        else:
            print("  Знак совпадает, но величина расходится значимо"
                  " (%.1f сигмы): суммирование в аттестации учитывалось"
                  " частично, либо изотопное равновесие источника"
                  " комплекта отличается от разыгрываемого моделью."
                  % worst)
    print("  ОГОВОРКА: C модели относится к цепочке Th-228 в равновесии"
          " Geant4; состояние источника комплекта")
    print("  не установлено. Совпадение — сильный довод; расхождение — не"
          " опровержение обязательно ВСЕГО механизма, но отклоняет модель"
          " как ОБЪЯСНЕНИЕ наблюдённой просадки в её нынешнем виде.")

    csvio.write(
        os.path.join(OUT, "cascade_predict_p5.csv"),
        ["E_keV", "peak_decay", "emitted", "C_summing", "underest_pct",
         "d_underest_pct", "observed_pct", "d_observed_pct", "n_sigma_comb"],
        [("%.3f" % E, "%.0f" % a, "%.0f" % n, "%.4f" % C, "%+.2f" % u,
          "%.2f" % du, "" if o is None else "%+.2f" % o,
          "" if do is None else "%.2f" % do,
          "" if o is None else "%.1f" % (abs(u - o)
                                          / math.sqrt(du ** 2 + do ** 2)))
         for E, a, n, C, u, du, o, do in rows],
        comments=[
            "C = eps(моно) / eps(распад) для точечной 5 см: во сколько раз"
            " пик недобирает в полном распаде из-за суммирования.",
            "underest_pct = 1/C - 1 — на столько занижен узел аттестации;"
            " ЕСЛИ поправка при её построении не вводилась.",
            "observed_pct/d_observed_pct — просадка узла относительно опоры"
            " одиночных излучателей и её погрешность (attested_cascade_check.csv,"
            " dev_pct/d_node_pct); вне 662…1116 опоры нет.",
            "n_sigma_comb — |модель-наблюдение| к КОМБИНИРОВАННОЙ погрешности"
            " обеих независимых сторон (в квадратуре), не только модели.",
            "Обе стороны C сняты ОДНИМ правилом peakwin.area — иначе в C"
            " вошла бы разница конвенций; а не физика.",
            "C модели относится к цепочке в равновесии Geant4; состояние"
            " источника комплекта не установлено.",
        ],
        stamp=stamp.lines(
            "detectors/Gamma-1S/analysis/cascade_predict_p5.py", OBS,
            inputs=[dpath] + [os.path.join(BUILD, MONO[E]) for E in sorted(MONO)
                              if os.path.exists(os.path.join(BUILD, MONO[E]))],
            geometry_dir=str(paths.geometry("Gamma-1S")),
            names=stamp.SRC_LISTS["Gamma-1S"], repo_dir=str(paths.REPO)))
    print("\nтаблица: %s" % os.path.join(OUT, "cascade_predict_p5.csv"))


if __name__ == "__main__":
    main()
