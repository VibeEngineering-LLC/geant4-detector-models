A_PASS_BQ_KG = 1940.0

# Сеансы СпектраЛайн, метод «По всем зонам» (AllZones), один спектр.
# E -> (площадь, активность Бк/кг, погрешность %); None — верхний предел.
SL_LSRM = {238.632: (660000, 1900, 22), 338.32: (154000, 2200, 16),
           510.77: (101000, 2800, 22), 583.187: (198000, 1650, 16),
           911.204: (113000, 1660, 16), 2614.511: (54500, 1600, 28)}
SL_OURS = {238.632: (660000, 2200, 23), 338.32: (154000, 2200, 21),
           510.77: (62000, 1700, 26), 583.187: (195000, 1600, 19),
           911.204: (113000, 1500, 24), 2614.511: (54500, None, None)}

# Наш конвейер, чистая линия 2614,5 (единственная годная по чистоте).
OUR_ALGO = {"наша": 0.796, "ЛСРМ": 0.902}


# Объявление наблюдаемой — что именно за число лежит в таблице. Без него
# таблицу нельзя сравнивать ни с какой другой: за один вечер 30.07.2026
# подмена определения стоила вывода четыре раза (method-rules §5).
OBS = {
    "quantity":
        "активность по аттестационной записи в четырёх сочетаниях кривая x алгоритм",
    "area":
        "площадь снимает СпектраЛайн своим алгоритмом; сюда приходит готовое число из окна программы",
    "window":
        "задаётся конфигурацией прибора (границы пиков в долях ПШПВ)",
    "shelf":
        "ступенька-из-образа плюс полином — конвенция программы",
    "blurred":
        "не применимо — измеренный спектр",
}


def _stamp(inputs=None):
    return stamp.lines("detectors/Gamma-1S/analysis/cell_2x2.py", OBS,
                       inputs=inputs,
                       geometry_dir=str(paths.geometry("Gamma-1S")),
                       names=stamp.SRC_LISTS["Gamma-1S"],
                       repo_dir=str(paths.REPO))


def lsrm_average(vals):
    """Средневзвешенное по правилу ЛСРМ + хи2/ню согласия линий."""
    pts = [(a, a * p / 100.0) for a, p in vals if a]
    w = [1.0 / d ** 2 for _a, d in pts]
    m = sum(a * wi for (a, _d), wi in zip(pts, w)) / sum(w)
    dm = math.sqrt(1.0 / sum(w))
    c2 = (sum(wi * (a - m) ** 2 for (a, _d), wi in zip(pts, w))
          / (len(pts) - 1)) if len(pts) > 1 else float("nan")
    return m, dm, c2, len(pts)


if __name__ == "__main__":
    print("Эксперимент 2x2 на аттестационном спектре маринелли Th-232"
          " (паспорт %.0f Бк/кг).\n" % A_PASS_BQ_KG)
    rows = []
    print("%-26s %10s %8s %8s %7s" %
          ("клетка", "A, Бк/кг", "A/пасп", "хи2/ню", "линий"))
    for name, d in (("кривая ЛСРМ x СпектраЛайн", SL_LSRM),
                    ("кривая наша x СпектраЛайн", SL_OURS)):
        m, dm, c2, n = lsrm_average([(a, p) for _S, a, p in d.values()])
        print("%-26s %10.0f %8.3f %8.2f %7d"
              % (name, m, m / A_PASS_BQ_KG, c2, n))
        rows.append((name, m, m / A_PASS_BQ_KG, c2, n))
    for cur, r in OUR_ALGO.items():
        name = "кривая %s x наш алгоритм" % cur
        print("%-26s %10.0f %8.3f %8s %7d"
              % (name, r * A_PASS_BQ_KG, r, "—", 1))
        rows.append((name, r * A_PASS_BQ_KG, r, None, 1))

    print("\nРазложение (сводные величины одной методики):")
    sl = [r[2] for r in rows[:2]]
    ours = [OUR_ALGO["ЛСРМ"], OUR_ALGO["наша"]]
    print("  вклад КРИВОЙ  (ЛСРМ->наша): у СпектраЛайн %+.1f %%,"
          " у нас %+.1f %%"
          % (100 * (sl[1] / sl[0] - 1), 100 * (ours[1] / ours[0] - 1)))
    print("  вклад АЛГОРИТМА (SL->наш): на кривой ЛСРМ %+.1f %%,"
          " на нашей %+.1f %%"
          % (100 * (ours[0] / sl[0] - 1), 100 * (ours[1] / sl[1] - 1)))

    print("\nФактически применённые программой eps против наших узлов"
          " (по парам A/S одного спектра):")
    lsrm_eps = {238.632: 4.344207e-2, 338.32: 3.325384e-2,
                510.77: 3.001447e-2, 583.187: 2.171222e-2,
                911.204: 1.346059e-2, 2614.511: 4.713864e-3}
    ours_node = {238.632: 4.4282e-2, 338.32: 3.8354e-2, 510.77: 2.8459e-2,
                 583.187: 2.5362e-2, 911.204: 1.7382e-2,
                 2614.511: 7.0485e-3}
    facs = []
    print("%9s %12s %12s %10s" %
          ("E, кэВ", "факт. н/л", "узлы н/л", "узлы/факт"))
    for E in sorted(SL_LSRM):
        So, Ao, _p = SL_LSRM[E]
        Sn, An, _q = SL_OURS[E]
        if An is None:
            print("%9.1f %12s %12.3f %10s"
                  % (E, "верхн.предел", ours_node[E] / lsrm_eps[E], "—"))
            continue
        fact = (Ao / So) / (An / Sn)
        node = ours_node[E] / lsrm_eps[E]
        facs.append(node / fact)
        print("%9.1f %12.3f %12.3f %10.3f" % (E, fact, node, node / fact))
    print("средний множитель узлы/факт = %.3f — редактор воспроизвёл ФОРМУ"
          " и перенормировал УРОВЕНЬ" % (sum(facs) / len(facs)))

    out = os.path.abspath(os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "results",
        "cell_2x2.csv"))
    csvio.write(
        out, ["cell", "A_Bq_kg", "ratio_to_passport", "chi2_dof", "n_lines"],
        [(n, "%.0f" % a, "%.4f" % r, "" if c is None else "%.2f" % c,
          "%d" % k) for n, a, r, c, k in rows],
        comments=[
            "Эксперимент 2x2 (кривая x алгоритм) на аттестационной записи"
            " Th232_420-7-17_Маринелли_0cm, паспорт 1940 Бк/кг.",
            "Клетки СпектраЛайн — метод «По всем зонам», один сеанс"
            " разметки; сводка по правилу ЛСРМ с погрешностями окна.",
            "Клетки нашего алгоритма — по чистой линии 2614,5 (у нас она"
            " единственная годная по чистоте).",
            "ВАЖНО: редактор эффективности перенормировал нашу кривую"
            " (множитель ~1,12), поэтому клетка «наша x SL» отвечает",
            "  о ФОРМЕ кривой, не об уровне.",
        ],
        stamp=_stamp())
    print("\nтаблица: %s" % out)
