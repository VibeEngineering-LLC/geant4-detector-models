"""Сведение эксперимента 2x2: кривая x алгоритм (задача 116).

Замысел. Расхождение активности раскладывается на вклад КРИВОЙ
эффективности и вклад АЛГОРИТМА обработки, для чего один и тот же спектр
считается четырьмя способами. Спектр — аттестационная запись
Th232_420-7-17_Маринелли_0cm (поверка 2024, паспорт 1940 Бк/кг при массе
1,6 кг, то есть 3104 Бк).

Как получены клетки.
  (ЛСРМ x наш)  — cell_lsrm_curve.py: наши площади, eps из штатного .efr.
  (наша x наш)  — kit_recalc.py: наш конвейер целиком.
  (ЛСРМ x SL)   — сеанс СпектраЛайн оператора на штатной кривой.
  (наша x SL)   — сеанс СпектраЛайн после того, как оператор построил
                  кривую по НАШИМ точкам в редакторе эффективности.

Почему подмена точек в .efa не сработала (проверено отдельно): программа
считает активность по ПОЛИНОМУ ЗОН, точки файла в расчёт не входят —
копия мастера с заменёнными 18 узлами дала те же A/S во всех методах.
Кривую пришлось строить редактором, который сам записывает полином.

ЧТО ВЫЯСНИЛОСЬ ПРИ СВЕДЕНИИ. Отношение eps, фактически применённых
программой, к нашим узлам оказалось не единицей, а ~1,12 постоянным
множителем по всем линиям: редактор ВОСПРОИЗВЁЛ ФОРМУ нашей кривой и
ПЕРЕНОРМИРОВАЛ уровень. Это ровно тот механизм, о котором предупреждал
оператор: штатная кривая подгоняется по близости результата к паспорту.
Поэтому клетка (наша x SL) отвечает на вопрос о ФОРМЕ, но не об уровне.

Погрешности активностей по линиям — из окна СпектраЛайн (столбец
«Неопр. активности, %»), они включают систематику эффективности 5 % и
хи-квадрат (UseChiSquare=1 в конфиге).
"""
