# -*- coding: utf-8 -*-
"""Работают ли окна /process/had/rdm/nucleusLimits, или они декоративны.

ЗАЧЕМ ЭТА ПРОВЕРКА СУЩЕСТВУЕТ
На окнах nucleusLimits стоит весь метод ветвлений: прогон «одиночного» нуклида
обязан оборвать цепочку на нём, иначе в спектр примешаются дочерние линии, а
выход линии на распад родителя окажется посчитан не на того родителя. При этом
порог долгого распада поднят до 1e30 нс — то есть ничто, кроме окна, цепочку не
держит. Известно, что в аналоговом режиме (он здесь по умолчанию и нигде не
переопределён) окна могут не срабатывать. Молчание тут не доказательство:
проверка обязана дать число.

КАК УСТРОЕН ТЕСТ
Am-241 (окно 241 241 93 95) распадается в Np-237, у того период 2,14 млн лет,
дальше Pa-233 (27 сут) с сильными линиями 300,1 и 311,9 кэВ. По ширине окна
Np-237 отсечён по МАССОВОМУ числу: A = 237 вне 241..241. Если окно работает,
линий Pa-233 в спектре испускания быть не должно. Если не работает, при
поднятом пороге времени Np-237 распадётся, и линии придут в полную силу.

ЧТО СЧИТАТЬ ПРОВАЛОМ
Выходы Pa-233: 300,1 кэВ — 6,6 %, 311,9 кэВ — 38,6 % на распад. На 400 000
первичных ядер работающая цепочка дала бы порядка 180 000 отсчётов в этих двух
линиях. Порог провала поставлен на два порядка ниже — 1 % от ожидаемого.

    python detectors/Gamma-1S/analysis/check_nucleuslimits.py

Возврат: 0 — окна работают, 1 — не работают либо нет данных.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import paths  # noqa: E402

BUILD = str(paths.build("Gamma-1S"))
RUN = "p5_Am241_emit.csv"
LINES = ((300.1, 6.6), (311.9, 38.6))     # кэВ, выход на распад Pa-233, %
WIN = 2.5
FAIL_FRAC = 0.01                          # доля ожидаемого, считаемая провалом


def main():
    p = os.path.join(BUILD, RUN)
    if not os.path.exists(p):
        print("Нет %s.\nПрогон делается драйвером:\n"
              "    python detectors/Gamma-1S/drivers/run_point_decay.py" % p)
        return 1
    N, tot = None, {E: 0 for E, _ in LINES}
    own = 0
    for ln in open(p, encoding="utf-8"):
        if ln.startswith("#"):
            if "N_primaries" in ln:
                N = int(ln.split("=")[1])
            continue
        if not ln[:1].isdigit():
            continue
        e, c = ln.split(",")
        e, c = float(e), int(c)
        for E, _ in LINES:
            if abs(e - E) <= WIN:
                tot[E] += c
        if abs(e - 59.54) <= WIN:          # своя линия Am-241, контроль
            own += c
    if not N:
        print("В %s нет N_primaries — файл неполон." % RUN)
        return 1

    expect = sum(N * y / 100.0 for _, y in LINES)
    got = sum(tot.values())
    print("Проверка окон nucleusLimits по прогону %s" % RUN)
    print("  первичных ядер Am-241: %d" % N)
    print("  своя линия 59,5 кэВ:   %d отсчётов, выход %.3f на распад "
          "(справочно 0,359)" % (own, own / N))
    for E, y in LINES:
        print("  линия Pa-233 %.1f кэВ: %d отсчётов (ожидалось бы %.0f, "
              "если бы цепочка шла)" % (E, tot[E], N * y / 100.0))
    print("  итого по линиям Pa-233: %d против ожидаемых %.0f — %.4f %% "
          "ожидаемого" % (got, expect, 100.0 * got / expect))

    if got > FAIL_FRAC * expect:
        print("\nОКНА НЕ РАБОТАЮТ: цепочка проходит сквозь nucleusLimits.\n"
              "Значит все прогоны «одиночных» нуклидов заражены дочерними\n"
              "линиями, и обрывать ряды надо иначе — фильтром по A и Z трека\n"
              "в Stepping/Tracking либо отдельным прогоном на каждый член.")
        return 1
    print("\nОКНА РАБОТАЮТ. Линии Pa-233 подавлены в %.0f раз против того, что\n"
          "дала бы идущая цепочка; остаток — случайные совпадения окна с\n"
          "континуумом. Метод ветвлений опирается на окна законно."
          % (expect / max(got, 1)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
