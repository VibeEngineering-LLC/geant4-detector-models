"""Насколько угловые корреляции каскада меняют суммирование.

Сравниваются два прогона Co-60, различающиеся ОДНИМ флагом
`/process/had/deex/correlatedGamma` (драйвер `run_corr_gamma.py`). Всё
остальное — геометрия, источник, число распадов, зерно розыгрыша по умолчанию
— совпадает.

ПРЕДСКАЗАНИЕ, ЗАПИСАННОЕ ДО ПРОГОНА. Угловая корреляция каскада 4→2→0 у Co-60
описывается W(θ) = 1 + 0,1020·P₂(cosθ) + 0,0091·P₄(cosθ). При малых углах между
партнёрами W > 1 — совпадений больше, чем при независимом розыгрыше; вблизи 90°
W < 1. Источник стоит вплотную к торцу, детектор занимает одну полусферу,
поэтому углы между партнёрами, при которых оба кванта попадают в кристалл,
смещены в сторону малых — ожидается УСИЛЕНИЕ совпадений. Величина усреднения
W по телесному углу этой геометрии заранее не считалась, поэтому предсказывается
знак и порядок, а не точное число: эффект положительный, по порядку единицы
процентов от самой величины суммирования.

ЧТО ИМЕННО СРАВНИВАЕТСЯ. Сумм-пик 2505 кэВ — прямая мера числа совпадений, в
которых оба кванта поглотились полностью; он чувствительнее к корреляциям, чем
убыль одиночных пиков, потому что складывается только из совпадений, тогда как
пик 1173 теряет малую долю от большого числа. Приводятся обе величины.

Площади берутся узкими окнами по неуширенным спектрам — так же, как в
`tcc_selfcheck.py`, и по той же причине: полки уширенного окна у Co-60 садятся
на соседний пик.
"""
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from point_recalc import BUILD, area_sim, load_hist  # noqa: E402

# Метки без запятых: csvio требует, чтобы файл читался наивным split(",").
LINES = [("пик 1173 кэВ", 1173.23), ("пик 1332 кэВ", 1332.49)]
SUM_PEAK = ("сумм-пик 2506 кэВ", 2505.72)


def peak(hist, N, E):
    a = area_sim(hist, E, broad=False)
    if a <= 0 or not N:
        return None, None
    return a / N, math.sqrt(abs(a)) / N


def main():
    off = os.path.join(BUILD, "corr_off.csv")
    on = os.path.join(BUILD, "corr_on.csv")
    for p in (off, on):
        if not os.path.exists(p):
            raise SystemExit(
                "Нет %s — сначала drivers/run_corr_gamma.py" % p)

    h_off, n_off = load_hist(off)
    h_on, n_on = load_hist(on)
    print("Угловые корреляции каскада: флаг correlatedGamma включён против"
          " выключенного.")
    print("Co-60 вплотную к торцу, распадов: %d без корреляций, %d с ними.\n"
          % (n_off, n_on))

    print("%-18s %13s %13s %11s" % ("величина", "без корр.", "с корр.",
                                    "отношение"))
    rows = []
    for lab, E in LINES + [SUM_PEAK]:
        a, da = peak(h_off, n_off, E)
        b, db = peak(h_on, n_on, E)
        if a is None or b is None:
            print("%-18s   нет отсчётов" % lab)
            continue
        r = b / a
        dr = r * math.sqrt((da / a) ** 2 + (db / b) ** 2)
        sig = (r - 1.0) / dr if dr > 0 else 0.0
        print("%-18s %13.5e %13.5e %6.3f±%.3f  (%+.1fσ от 1)"
              % (lab, a, b, r, dr, sig))
        rows.append((lab, "%.6e" % a, "%.6e" % b, "%.4f" % r, "%.4f" % dr,
                     "%+.2f" % sig))

    print("\nОтношение больше единицы у сумм-пика означает, что корреляции"
          " усиливают\nсовпадения; меньше единицы у одиночных пиков — что они"
          " сильнее выбиваются.")

    if rows:
        op = os.path.abspath(os.path.join(
            os.path.dirname(os.path.abspath(__file__)), "..", "results",
            "corr_gamma_effect.csv"))
        csvio.write(
            op,
            ["quantity", "eps_off", "eps_on", "ratio", "d_ratio", "sigma"],
            rows,
            comments=[
                "Влияние /process/had/deex/correlatedGamma на суммирование:"
                " Co-60 вплотную к торцу.",
                "Флаг по умолчанию ВЫКЛЮЧЕН, и включить его из макроса нельзя"
                " — параметр деэксцитации принимается только до инициализации,",
                "  а команда в макросе отвергается с нулевым кодом возврата."
                " Включается переменной G1S_CORRELATED_GAMMA.",
                "Геометрия вплотную выбрана намеренно: на рабочих 5 см сдвиг"
                " составил бы 0,23 процентного пункта и потребовал бы",
                "  около 130 млн распадов, чтобы отличаться от нуля на трёх"
                " сигмах.",
            ])
        print("\nсводка: %s" % op)


if __name__ == "__main__":
    main()
