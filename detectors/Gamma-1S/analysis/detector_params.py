"""Параметры детектора Гамма-1С — ОДНО место на весь анализ.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Разрешающая способность и энергии вылета материала
кристалла жили копиями: `FWHM662 = 49.9` стояло и в `point_recalc.py`, и в
`kit_recalc.py`, а `ESCAPES` разошлись прямо в работе — точечная ветвь выключила
вырез полос вылета по результатам задачи 135, объёмная осталась с `(28.6,)`, и
комментарий рядом с ней продолжал утверждать, что «оба файла описывают ОДИН
прибор, и расхождение здесь было бы дефектом». Расхождение и случилось. Это
пятый случай класса «одно правило в двух местах» в этом репозитории и первый,
где разошлась характеристика самого прибора, а не правило обработки.

Найдено независимым аудитом, не автором.
"""
import math

# Разрешающая способность: ПШПВ на линии 662 кэВ, измерена по записи цезия
# (7,5 % при паспортном пределе 8 %). Закон ширины — корневой,
# ПШПВ(E) = FWHM662·√(E/661,657); это приближение одной опорной точки, оно
# завышает ширину на 583 кэВ и занижает на 2614 кэВ (см. results/fwhm_check.csv).
FWHM662 = 49.9

# Энергии вылета материала кристалла — обязательный входной параметр детектора
# наравне с ПШПВ (method-rules §6). NaI(Tl) — один вылет, K-рентген иода.
# У CsI их два (иод 28,6 и цезий 30,97), поэтому величина принадлежит ПРИБОРУ,
# а не правилу обработки.
ESCAPE_KEV = 28.6

# Паспортный диапазон регистрируемых энергий (п. 2.2 паспорта; сверено со
# сканом 28.07.2026, см. REPORT.md §2.1). Свойство ПРИБОРА, поэтому живёт
# здесь, а не в экспортёре: за этими границами прибор не аттестован, и
# расхождение расчёта с измерением там не довод ни за модель, ни против неё.
# Узлы сетки за границами НЕ удаляются — они годятся для сверки с другим кодом
# (EffCalcMC), — но обязаны быть помечены (задача 97).
ATTESTED_RANGE_KEV = (50.0, 3000.0)

# ВЫРЕЗ ПОЛОС ВЫЛЕТА ВЫКЛЮЧЕН НА ВСЕХ ВЕТВЯХ (задача 135) — решение, не
# недоделка. На модельном спектре шаг 1 кэВ и подложка держит 15…50 каналов;
# на измеренном ~3 кэВ на канал и подложка шириной 1 ПШПВ держит единицы
# каналов, так что вырез ±0,5·ПШПВ съедает почти всю подложку, и съём молча
# уходит на одностороннюю — заново внося чувствительность к наклону континуума.
# Заражение вместо этого ОБЪЯВЛЕНО как систематика с полосой действия ниже.
# Подробно — method-rules §1 и docstring `escape_balance.py`.
ESCAPES = ()


def fwhm(E):
    """ПШПВ прибора на энергии E, кэВ."""
    return FWHM662 * math.sqrt(E / 661.657)


# ИЗМЕРЕННАЯ разрешающая способность по шести линиям окна «Параметры пиков»
# (сеанс СпектраЛайн 30.07.2026): (энергия кэВ, разрешение % от энергии).
# Держится здесь по той же причине, что и FWHM662: это характеристика ПРИБОРА.
# Прежде эти шесть пар жили внутри `bridge_p5_th228.py` — второй, независимой
# от FWHM662 параметризацией ширины, о которой остальной анализ не знал.
FWHM_MEASURED = ((238.632, 9.835), (300.087, 9.075), (583.187, 7.192),
                 (727.330, 6.664), (860.557, 6.283), (2614.511, 4.098))


def _fwhm_fit_coeffs(points=FWHM_MEASURED):
    """(k; p) в ПШПВ(E) = k·E^p — МНК по логарифмам.

    ПОЧЕМУ НЕ sqrt(a + b·E), КАК БЫЛО. Именно эта форма стояла в
    `bridge_p5_th228.py`, и она НЕ ОПИСЫВАЕТ собственные точки: подгонка по
    ПШПВ² с равными весами определяется одной верхней точкой (ПШПВ² на
    2614,5 кэВ в сорок раз больше, чем на 238,6), и на 238,632 кэВ модель
    даёт 16,55 кэВ против измеренных 23,47 — промах 29,5 % В ТОЧКЕ ПОДГОНКИ.
    Хуже: подобранное a отрицательно, `a + b·E` обращается в ноль на
    179,9 кэВ, и ниже формула бессмысленна — прежний код гасил это
    `max(..., 1.0)`, то есть возвращал ПШПВ = 1 кэВ молча. Пока мост считался
    только на 662/861/2614, дефект не проявлялся.

    Степенной закон воспроизводит все шесть точек в пределах 1,1 % (СКО
    0,9 %) и остаётся конечным и монотонным вниз по энергии. Трёхчлен
    a + b·E + c·E² ложится чуть лучше (0,95 %), но его корень приходится на
    76,1 кэВ — то же скрытое ограничение снизу, только ближе к рабочему краю.
    """
    xs = [math.log(E) for E, _ in points]
    ys = [math.log(pc / 100.0 * E) for E, pc in points]
    n = len(xs)
    sx, sy = sum(xs), sum(ys)
    sxx = sum(x * x for x in xs)
    sxy = sum(x * y for x, y in zip(xs, ys))
    p = (n * sxy - sx * sy) / (n * sxx - sx * sx)
    k = math.exp((sy - p * sx) / n)
    return k, p


def fwhm_measured(E, points=FWHM_MEASURED):
    """ПШПВ прибора на энергии E по ИЗМЕРЕННЫМ шести линиям, кэВ.

    Отличается от `fwhm()`: та строит корневой закон по ОДНОЙ опорной точке
    662 кэВ. Там, где спектр модели размывается для сравнения с АТТЕСТОВАННОЙ
    конвенцией съёма площади, брать надо эту: она снята тем же сеансом и тем
    же прибором, что и площади, с которыми идёт сравнение.

    ДВЕ ОЦЕНКИ ШИРИНЫ НА 662 кэВ РАСХОДЯТСЯ НА 10 %, и это не округление:
    FWHM662 = 49,9 кэВ снято по записи цезия комплекта, а шесть линий сеанса
    30.07 дают в той же точке 45,2 кэВ (интерполяция между 583,2 → 41,94 и
    727,3 → 48,47 даёт ≈45,5, то есть расходится именно запись цезия, а не
    подгонка). Правдоподобный механизм — наложения: цезиевая запись идёт на
    960 отсч/с, торий на единицах, а наложения уширяют пик. Пока расхождение
    НЕ разобрано, обе величины оставлены раздельно и НЕ сводятся к одной.
    """
    k, p = _fwhm_fit_coeffs(points)
    return k * E ** p


def in_attested_range(E, rng=ATTESTED_RANGE_KEV):
    """Лежит ли энергия внутри паспортного диапазона регистрации."""
    return rng[0] <= E <= rng[1]


def escape_band(esc_keV=ESCAPE_KEV, fwhm662=FWHM662):
    """Полоса энергий, где пик вылета попадает в подложку конвенции ±1 ПШПВ.

    Выводится, а не задаётся числом: подложка слева — `[E−2·ПШПВ, E−1·ПШПВ]`,
    вылет лежит внутри неё при `ПШПВ(E) ≤ E_выл ≤ 2·ПШПВ(E)`; при `ПШПВ = k√E`
    это даёт замкнутый интервал `[(E_выл/2k)², (E_выл/k)²]`.
    """
    k = fwhm662 / math.sqrt(661.657)
    return (esc_keV / (2 * k)) ** 2, (esc_keV / k) ** 2


def lines_in_escape_band(lines, esc_keV=ESCAPE_KEV, fwhm662=FWHM662):
    """Какие из переданных линий попадают в полосу заражения.

    Список затронутых линий тоже СОБИРАЕТСЯ, а не пишется рядом: вписанный
    руками, он разойдётся с полосой при первой же правке ПШПВ или энергии
    вылета — ровно тот дефект, который в §3.2 отчёта назван главным уроком.
    """
    lo, hi = escape_band(esc_keV, fwhm662)
    return tuple(E for E in sorted(lines) if lo <= E <= hi)
