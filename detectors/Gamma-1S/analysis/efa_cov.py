# -*- coding: utf-8 -*-
"""Погрешность и КОВАРИАЦИЯ предсказания градуировочной кривой .efa.

ЗАЧЕМ. Эффективности, снятые с одной кривой на разных энергиях, НЕ
независимы: их предсказывает один полином одной зоны, подогнанный по общему
набору узлов. Любая величина, составленная из нескольких точек одной кривой
(отношение край/плато, среднее по линиям, разность), обязана считаться с
ковариационными членами — квадратура даёт неверный ответ, причём знак
ошибки зависит от знака ковариации и заранее не очевиден.

Для точечной 5 см ковариация линий 583/727/861 кэВ с 2614,5 кэВ
ОТРИЦАТЕЛЬНА (ρ = −0,28…−0,17 для отношения кривых): взвешенный центроид
узлов зоны 2 лежит около 900 кэВ, линии плато стоят почти на нём, а
2614,5 кэВ — на полдекады выше, и ошибки предсказания по разные стороны
центроида антикоррелированы. Для РАЗНОСТИ «край минус плато» отрицательная
ковариация означает, что квадратура ЗАНИЖАЕТ погрешность (внешний аудит
01.08.2026; знак подтверждён здесь независимым расчётом).

ЧТО СЧИТАЕТСЯ. Взвешенный МНК по узлам зоны, отклик y = lg(eps):

    Cov(коэффициенты)      = s^2 * (P^T W P)^-1
    Cov(y(E1), y(E2))      = s^2 * p(E1)^T (P^T W P)^-1 p(E2)

где p(E) — вектор значений базисных полиномов Curve_k_j в точке lg E;
W — веса узлов из третьего поля (заявленная погрешность точки в процентах,
переведённая в lg делением на 100*ln10); s^2 — оценка дисперсии единицы
веса, s^2 = хи2/ню по остаткам записанного полинома. Значение s^2 около
единицы означает, что фит согласуется с объявленными погрешностями узлов;
у аттестованной кривой s^2 заметно больше единицы (разброс точек больше
объявленного), у нашей — меньше (полином аппроксимирует гладкую расчётную
кривую точнее, чем заявленные погрешности узлов шаблона).

ОТНОШЕНИЕ К ФОРМУЛЕ ПРОИЗВОДИТЕЛЯ. ЛСРМ даёт погрешность кривой как
230*D*||Q(X)||, где D — 4-е поле Zone_k, а ||Q(X)|| — норма вектора p(E).
Это та же величина с точностью до нормировки базиса: базис Curve_k_j
ортогонален по весам узлов, но НЕ ортонормирован (диагональ P^T W P равна
не единице), поэтому формула производителя не содержит обратной матрицы
Грама и является приближением. Здесь считается строгая форма; функция
`lsrm_delta_pct` оставлена для сверки с тем, что показывает программа.

ЧЕГО МОДУЛЬ НЕ ДЕЛАЕТ. Не учитывает погрешность самих узловых значений
как источник (она входит через веса и s^2, но корреляции между узлами
считаются нулевыми) и не знает о статистике Монте-Карло расчётной кривой —
её вызывающий добавляет отдельно, из таблицы сетки.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import efa_zones  # noqa: E402

LN10 = math.log(10.0)


def block_of(path, geom):
    """Блок геометрии `geom` из многоблочного .efa (конвенция export_point5cm)."""
    raw = open(path, "rb").read().decode("cp1251")
    out, take = [], False
    for ln in raw.replace("\r\n", "\n").split("\n"):
        if ln.startswith("["):
            if take:
                break
            take = (";" + geom + "]") in ln
            if take:
                out = [ln]
                continue
        if take:
            out.append(ln)
    return out


def _inv(M):
    """Обращение малой матрицы (Гаусс — Жордан); размер 3x3 у обеих зон."""
    n = len(M)
    A = [row[:] + [1.0 if i == j else 0.0 for j in range(n)]
         for i, row in enumerate(M)]
    for i in range(n):
        p = max(range(i, n), key=lambda r: abs(A[r][i]))
        A[i], A[p] = A[p], A[i]
        d = A[i][i]
        if d == 0.0:
            raise SystemExit("efa_cov: вырожденная матрица плана зоны")
        A[i] = [v / d for v in A[i]]
        for r in range(n):
            if r != i and A[r][i]:
                f = A[r][i]
                A[r] = [a - f * b for a, b in zip(A[r], A[i])]
    return [row[n:] for row in A]


class Curve(object):
    """Кривая .efa: значение, погрешность и ковариация предсказания."""

    def __init__(self, path, geom="Точечная-5см"):
        lines = block_of(path, geom)
        if not lines:
            raise SystemExit("efa_cov: в %s нет блока %s" % (path, geom))
        self.path = path
        self.nodes, self.zones, self.basis, self.coef = \
            efa_zones.parse_block(lines)
        self.st = {}
        for z, zf in self.zones.items():
            ndeg = int(zf[0]) + 1
            inz = [(E, eps, d) for E, eps, d in self.nodes
                   if zf[1] - 1e-9 <= math.log10(E) <= zf[2] + 1e-9]
            if len(inz) <= ndeg:
                continue
            G = [[0.0] * ndeg for _ in range(ndeg)]
            chi2 = 0.0
            for E, eps, d in inz:
                w = 1.0 / (d / 100.0 / LN10) ** 2
                p = self._p(z, ndeg, E)
                for i in range(ndeg):
                    for j in range(ndeg):
                        G[i][j] += w * p[i] * p[j]
                yhat = sum(self.coef[z][i] * p[i] for i in range(ndeg))
                chi2 += w * (math.log10(eps) - yhat) ** 2
            nu = len(inz) - ndeg
            self.st[z] = dict(Gi=_inv(G), ndeg=ndeg, s2=chi2 / nu, nu=nu,
                              n=len(inz), D=zf[3], lo=zf[1], hi=zf[2])

    def _p(self, z, ndeg, E):
        x = math.log10(E)
        return [efa_zones.horner(self.basis[(z, i + 1)], x)
                for i in range(ndeg)]

    def zone(self, E):
        """Зона, применяемая в точке E.

        Диапазоны зон в .efa ПЕРЕКРЫВАЮТСЯ. По документации производителя
        на границах полиномы сглаживаются, обеспечивая непрерывность кривой
        и её первой производной, то есть отдельная зона там не «выбирается».
        Для точечных величин берётся зона с наибольшим номером, покрывающая
        точку: она построена по большему числу узлов и покрывает весь
        рабочий диапазон.
        """
        x = math.log10(E)
        zs = [z for z, d in self.st.items()
              if d["lo"] - 1e-6 <= x <= d["hi"] + 1e-6]
        if not zs:
            raise SystemExit("efa_cov: %.3f кэВ вне зон %s" % (E, self.path))
        return max(zs)

    def eps(self, E):
        z = self.zone(E)
        d = self.st[z]
        p = self._p(z, d["ndeg"], E)
        return 10.0 ** sum(self.coef[z][i] * p[i] for i in range(d["ndeg"]))

    def cov_ln(self, E1, E2):
        """Cov(ln eps(E1), ln eps(E2)) — в НАТУРАЛЬНОМ логарифме.

        Точки разных зон считаются некоррелированными: их предсказывают
        разные наборы коэффициентов. Это приближение — узлы области
        перекрытия входят в обе зоны, — и оно ЗАНИЖАЕТ ковариацию; для
        линий одной зоны (все четыре опорные линии Th-228 лежат в зоне 2)
        приближение не используется.
        """
        z1, z2 = self.zone(E1), self.zone(E2)
        if z1 != z2:
            return 0.0
        d = self.st[z1]
        p1 = self._p(z1, d["ndeg"], E1)
        p2 = self._p(z1, d["ndeg"], E2)
        v = sum(p1[i] * d["Gi"][i][j] * p2[j]
                for i in range(d["ndeg"]) for j in range(d["ndeg"]))
        return d["s2"] * v * LN10 ** 2

    def d_rel(self, E):
        """Относительная погрешность предсказания в точке E (доля единицы)."""
        return math.sqrt(self.cov_ln(E, E))

    def lsrm_delta_pct(self, E):
        """Погрешность по формуле производителя: 230*D*||Q(X)||, %.

        Оставлено для сверки с тем, что показывает программа обработки;
        строгая оценка — `d_rel`. Расхождение двух форм есть мера того,
        насколько базис отступает от ортонормированности.
        """
        z = self.zone(E)
        d = self.st[z]
        p = self._p(z, d["ndeg"], E)
        return 100.0 * LN10 * d["D"] * math.sqrt(sum(v * v for v in p))


def combo(curves_terms, extra_var=0.0):
    """Дисперсия линейной комбинации логарифмов эффективностей.

    curves_terms — [(кривая, {E: коэффициент}), ...]: слагаемые от РАЗНЫХ
    кривых считаются независимыми (разные источники), внутри одной кривой
    берётся полная ковариационная матрица.
    extra_var — дисперсия независимых добавок (мост, статистика расчёта),
    уже в квадрате относительной величины.

    Возвращает дисперсию суммы в натуральном логарифме.
    """
    var = extra_var
    for curve, terms in curves_terms:
        for E1, a1 in terms.items():
            for E2, a2 in terms.items():
                var += a1 * a2 * curve.cov_ln(E1, E2)
    return var
