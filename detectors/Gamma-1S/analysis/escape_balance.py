# -*- coding: utf-8 -*-
"""Воспроизводит ли модель пик вылета так же, как измерение (задача 135).

ЗАЧЕМ. Полка в долях ПШПВ заражена пиком вылета K-рентгена иода на пяти линиях
мягкого края (`method-rules` §1). Есть два способа с этим обойтись:

  (а) ВЫРЕЗАТЬ полосу вылета из оценки полки. Проверено прямым измерением —
      на ИЗМЕРЕННОМ спектре не работает: 1024 канала на ~3 МэВ дают ~3 кэВ на
      канал, полка шириной 1 ПШПВ содержит ВСЕГО 7…8 каналов, и вырез
      ±0,5·ПШПВ съедает 6…7 из них. Съём молча уходит на одностороннюю полку,
      заново внося чувствительность к наклону континуума. Сдвиг скорости счёта
      достигал +15 % — это не работа выреза, а откат.

  (б) НЕ ВЫРЕЗАТЬ, опираясь на то, что заражены ОБЕ стороны сравнения и в
      отношении `A = скорость / eps_модели` смещение сокращается.

Способ (б) держится на допущении, что модель воспроизводит вылет ВЕРНО. Это
допущение и проверяется здесь — измерением, а не рассуждением. Пока оно не
проверено, ни (а), ни (б) выбирать нельзя: (а) сломано, (б) недоказано.

ЧТО СЧИТАЕТСЯ. Доля вылета `вылет/пик` одним и тем же оценщиком на обеих
сторонах: сумма в окне `±0,5·ПШПВ` вокруг `E − E_выл` за вычетом подложки,
делённая на площадь пика. Оценщик грубый, но ОДИН на обе стороны — сравниваются
не абсолютные доли, а их согласие.

ИСХОД ПРОВЕРКИ 30.07.2026: **ОЦЕНЩИК НЕПРИГОДЕН, ВОПРОС ОСТАЁТСЯ ОТКРЫТЫМ.**
Скрипт оставлен как запись отрицательного результата, числа его НЕ ЦИТИРОВАТЬ.

Признак негодности виден без справочника: доли вышли ОТРИЦАТЕЛЬНЫМИ (−6,7 % на
Am-241, −14,1 % у модели на Ba-133, −35,0 % на Ce-139). Доля площади пика вылета
к площади линии отрицательной быть не может; значит вычитание подложки в окне
вылета уводит результат в минус, а не измеряет вылет.

Две причины, обе установлены по схемам распада, а не по догадке:

1. **Окно вылета садится на РЕАЛЬНЫЕ линии.** У Ba-133 линия 53,162 кэВ стоит
   ровно там, где ожидается вылет от 80,998 (`81,0 − 28,6 = 52,4`). У Am-241
   рядом с `59,54 − 28,6 = 30,9` лежат линия 26,34 кэВ и L-рентген нептуния
   13…21 кэВ. Для этих двух нуклидов величина не отделяется от собственных
   линий в принципе.
2. **Континуум под окном вылета круто падает**, и симметричная трапеция на таком
   склоне ПЕРЕВЫЧИТАЕТ. Это тот же механизм, что разбирается в `method-rules`
   §1, только применённый не к линии, а к вылету.

Чистыми по схеме распада остаются Cd-109 (`88,03 − 28,6 = 59,4`, соседей нет) и
Co-57 (`122,06 − 28,6 = 93,5`, соседей нет) — и именно они дали наименьшие
расхождения, 4,1 и 2,2 σ, тогда как загрязнённые дали 29…37 σ. Согласованность
этого признака с независимо известным составом схем распада подтверждает
диагноз: расхождение вносит оценщик, а не физика.

ЧТО НУЖНО, ЧТОБЫ ВОПРОС ЗАКРЫТЬ (не сделано): моноэнергетический ИЗМЕРЕННЫЙ
спектр, где вылет не смешан с собственными линиями источника. Такого в комплекте
нет — все эталоны многолинейные. Обходной путь — фит области вылета с явной
моделью континуума вместо трапеции, но это отдельная работа.
"""
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import becqmoni as bm  # noqa: E402
import csvio  # noqa: E402
import paths  # noqa: E402
import stamp  # noqa: E402

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import point_recalc as pr  # noqa: E402

ESC = 28.6      # K-рентген иода, кэВ
HALF = 0.5      # полуширина окна вылета в долях ПШПВ линии

# Линии мягкого края, попадающие в полосу заражения 54,3…217,4 кэВ, и нуклид,
# у которого линия чистая (см. отбор по чистоте в point_recalc).
LINES = [(59.540, "Am-241", "Am241"),
         (80.998, "Ba-133", "Ba133"),
         (88.030, "Cd-109", "Cd109"),
         (122.060, "Co-57", "Co57"),
         (165.860, "Ce-139", "Ce139")]


def escape_over_peak_measured(sp, bg, E, fwhm):
    """(доля, sigma) по ИЗМЕРЕННОМУ спектру за вычетом измеренного фона."""
    r = bm.net_rate(sp, bg, E, fwhm, roi=1.0, side=1.0)
    if not r or r[0] <= 0:
        return None
    Ee = E - ESC
    fe = pr.fwhm(Ee)
    # Окно вылета и его подложка — теми же правилами, что пик: иначе
    # сравнивались бы две разные конвенции внутри одного числа.
    q = bm.net_rate(sp, bg, Ee, fe, roi=HALF, side=HALF)
    if q is None:
        return None
    val = q[0] / r[0]
    dv = abs(val) * math.hypot(q[1] / q[0] if q[0] else 1.0, r[1] / r[0])
    return val, dv


def escape_over_peak_model(tag, E, fwhm):
    """(доля, sigma) по РАЗМЫТОМУ модельному спектру прогона распада."""
    p = os.path.join(pr.BUILD, "p5_%s.csv" % tag)
    if not os.path.exists(p):
        return None
    pr.USED.add(p)
    hist, N = pr.load_hist(p)
    if not N:
        return None
    key = "esc:" + tag
    if key not in pr._BROAD:
        pr._BROAD[key] = bm.broaden(hist, pr.FWHM662)
    arr = pr._BROAD[key]
    a, _b = bm.area_broadened(arr, E, fwhm, roi=1.0, side=1.0)
    Ee = E - ESC
    e, _b2 = bm.area_broadened(arr, Ee, pr.fwhm(Ee), roi=HALF, side=HALF)
    if a <= 0:
        return None
    val = e / a
    # sigma по пуассону исходных отсчётов; размытие перераспределяет, но не
    # создаёт статистику, поэтому берётся по числу событий в окне.
    dv = abs(val) * math.hypot(1.0 / math.sqrt(max(abs(e), 1.0)),
                               1.0 / math.sqrt(max(a, 1.0)))
    return val, dv


def main():
    rows = []
    print("Доля вылета K-рентгена иода (E-%.1f кэВ) к площади пика:"
          " измерение против модели.\n" % ESC)
    print("%-8s %9s %10s %10s %9s %8s"
          % ("нуклид", "E, кэВ", "измерение", "модель", "разность", "sigma"))
    for E, nuc, tag in LINES:
        p = pr.record("Point_5cm", nuc)
        if not p:
            print("%-8s %9.3f  записи нет" % (nuc, E))
            continue
        sp, bg = bm.read_checked(p)[:2]
        fw = pr.fwhm(E)
        m = escape_over_peak_measured(sp, bg, E, fw)
        g = escape_over_peak_model(tag, E, fw)
        if not m or not g:
            print("%-8s %9.3f  не посчиталось" % (nuc, E))
            continue
        d = m[0] - g[0]
        sd = math.hypot(m[1], g[1])
        print("%-8s %9.3f %9.4f%% %9.4f%% %+8.4f%% %8.1f"
              % (nuc, E, 100 * m[0], 100 * g[0], 100 * d,
                 abs(d) / sd if sd else 0.0))
        rows.append((nuc, "%.3f" % E, "%.5f" % m[0], "%.5f" % m[1],
                     "%.5f" % g[0], "%.5f" % g[1],
                     "%.2f" % (abs(d) / sd if sd else 0.0)))

    if rows:
        neg = [r for r in rows if float(r[2]) < 0 or float(r[4]) < 0]
        print("\nСАМОПРОВЕРКА ОЦЕНЩИКА.")
        if neg:
            print("  ОТРИЦАТЕЛЬНЫЕ доли на %d линиях из %d — оценщик НЕПРИГОДЕН."
                  % (len(neg), len(rows)))
            print("  Доля площади вылета к площади линии не может быть меньше"
                  " нуля; значит трапеция под окном вылета")
            print("  перевычитает (крутой континуум) либо окно накрывает"
                  " СОБСТВЕННУЮ линию источника.")
            print("  Загрязнены по схеме распада: Ba-133 (линия 53,162 против"
                  " ожидаемого вылета 52,4),")
            print("  Am-241 (линия 26,34 и L-рентген Np 13...21 против 30,9).")
            print("  Чисты: Cd-109 (59,4) и Co-57 (93,5) — и они дали"
                  " наименьшие расхождения.")
            print("  ВЫВОД О МОДЕЛИ НЕ ДЕЛАЕТСЯ. Числа не цитировать;"
                  " см. задачу 135.")
        else:
            worst = max(float(r[6]) for r in rows)
            print("  Отрицательных долей нет; наибольшее расхождение %.1f"
                  " sigma." % worst)

    verdict, detail = stamp.check_inputs(
        sorted(pr.USED), str(paths.geometry("Gamma-1S")),
        stamp.SRC_LISTS["Gamma-1S"])
    print("\nПРОВЕНАНС входов: %s (%s)" % (verdict, detail))

    if rows:
        op = os.path.join(str(paths.results("Gamma-1S")),
                          "escape_balance.csv")
        csvio.write(
            op, ["nuclide", "E_keV", "meas_ratio", "d_meas", "model_ratio",
                 "d_model", "sigma"], rows,
            comments=[
                "Доля пика вылета K-рентгена иода (E-28;6 кэВ) к площади"
                " линии: измерение против модели.",
                "Оценщик ОДИН на обе стороны: сумма в +-0;5 ПШПВ вокруг"
                " E-28;6 за вычетом подложки; сравнивается согласие; а не",
                "  абсолютная доля.",
                "Проверяет допущение; на котором держится отказ от выреза"
                " полос вылета: заражены обе стороны сравнения; и в",
                "  отношении A = скорость/eps смещение сокращается ТОЛЬКО"
                " если модель передаёт вылет верно.",
            ],
            stamp=stamp.lines(
                "detectors/Gamma-1S/analysis/escape_balance.py",
                {"quantity": "отношение площади пика вылета к площади линии;"
                             " измерение против модели",
                 "area": "пик полного поглощения; окно вылета +-0;5 ПШПВ",
                 "window": "линия +-1;0 ПШПВ; вылет +-0;5 ПШПВ",
                 "shelf": "симметричные полки той же доли ПШПВ; вырез полос"
                          " НЕ применяется (проверяется именно его нужность)",
                 "blurred": "модель размыта до приборного ПШПВ; измерение как"
                            " есть",
                 "escape_keV": "28;6 (K-рентген иода)"},
                inputs=sorted(pr.USED),
                geometry_dir=str(paths.geometry("Gamma-1S")),
                names=stamp.SRC_LISTS["Gamma-1S"],
                repo_dir=str(paths.REPO)))
        print("таблица: %s" % op)


if __name__ == "__main__":
    main()
