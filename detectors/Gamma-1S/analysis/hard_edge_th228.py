def applied_eps(S, A, E):
    """Эффективность, фактически применённая программой.

    Восстанавливается из тройки (площадь, активность, выход линии) и не
    зависит ни от разметки, ни от округления вывода — именно этим приёмом
    было доказано, что прежние прогоны шли на штатной кривой.
    """
    return (S / T_LIVE) / (A * INTENS[E])


def lsrm_average(d):
    """Средневзвешенное по правилу ЛСРМ и хи2/ню согласия линий."""
    pts = [(a, a * u / 100.0) for _S, a, u in d.values()]
    w = [1.0 / s ** 2 for _a, s in pts]
    m = sum(a * x for (a, _s), x in zip(pts, w)) / sum(w)
    c2 = (sum(x * (a - m) ** 2 for (a, _s), x in zip(pts, w))
          / (len(pts) - 1))
    return m, math.sqrt(1.0 / sum(w)), c2


