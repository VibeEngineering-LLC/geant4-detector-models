def lsrm_average(d, keys=None):
    """Средневзвешенное по правилу ЛСРМ и хи2/ню согласия линий.

    ВНИМАНИЕ: sqrt(1/Σw) — оценка σ для НЕЗАВИСИМЫХ измерений. Линии делят
    один паспорт, живое время и кривую (систематика кривой — проверяемая
    величина), поэтому σ здесь ЗАВЫШЕНА; печатается как справочная, не для
    вывода «интервал накрыл единицу».
    """
    keys = sorted(d) if keys is None else keys
    pts = [(d[E][1], d[E][1] * d[E][2] / 100.0) for E in keys]
    w = [1.0 / s ** 2 for _a, s in pts]
    m = sum(a * x for (a, _s), x in zip(pts, w)) / sum(w)
    c2 = (sum(x * (a - m) ** 2 for (a, _s), x in zip(pts, w))
          / (len(pts) - 1)) if len(pts) > 1 else float("nan")
    return m, math.sqrt(1.0 / sum(w)), c2


