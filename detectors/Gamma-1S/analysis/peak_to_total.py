"""Отношение пик / полная площадь: форма отклика против уровня (задача 122).

ЗАЧЕМ. Эффективность модели по ППП выше аттестованной, и до разделения двух
объяснений вывод неполон:

  (а) УРОВЕНЬ — модель поглощает слишком хорошо (эффективный объём или
      плотность кристалла, недостача утечки рассеянных);
  (б) ФОРМА — площадь снимается по-разному, и часть расхождения создаётся
      способом измерения, а не детектором.

Отношение `P/T` = площадь пика / полная площадь в том же окне от абсолютного
уровня эффективности НЕ зависит: общий множитель сокращается. Поэтому

  * `P/T` модели совпало с измеренным → форма отклика верна, расхождение
    целиком в уровне (а);
  * `P/T` модели ВЫШЕ измеренного → модель кладёт в пик то, что прибор
    рассыпает в подложку, и часть расхождения принадлежит (б).

ОПРЕДЕЛЕНИЕ «ПОЛНОЙ ПЛОЩАДИ» ПРОЧИТАНО, А НЕ ДОМЫСЛЕНО. Оговорка задачи
требовала уточнить его по документации ЛСРМ ДО расчёта, потому что «площадь
зоны под сшивкой» и «сумма отсчётов в окне» — разные величины, и неверный
выбор сделал бы тест бессмысленным. Руководство «SpectraLineXX 1.7. Основные
функции», раздел про окно «Параметры пиков» (с. 111 и 229), определяет столбец
дословно: «полная площадь пика [импульсы], как сумма площади под пиком и фона
под пиком; границы пика определяются параметрами конфигурации Границы пиков
(в долях ПШПВ)». То есть это ВАЛОВАЯ сумма отсчётов в окне пика, а не площадь
зоны и не результат сшивки.

Границы взяты из рабочего `lsrm.cnf` прибора: `LeftPeakBound = RightPeakBound
= 2.5` (ПШПВ), `BackgrPower = 2`. В слепке эпохи аттестации они те же — в
`results/config_drift.csv` этих ключей нет, а туда попадают только
РАСХОДЯЩИЕСЯ ключи.

ПОЧЕМУ РАСПАДНЫЙ СПЕКТР, А НЕ МОНО. Измеренная величина снята с записи Th-228,
где в окно ±2,5 ПШПВ попадает континуум ВСЕЙ цепочки, а не только рассеяние
самой линии. Моно-прогон такого континуума не содержит, его `T` был бы заведомо
меньше, а `P/T` — заведомо выше. Сравнивать надо с прогоном распада `p5_Th228`.

ДЛИННЫЙ ПРОГОН (задача 122, закрыта 01.08.2026). Короткий `p5_Th228.csv` не
разрешал единственную чистую линию (2614,5 кэВ: 2,9 сигмы — статистика
недостаточна для вывода). Длинный прогон `p5_Th228_long.csv` (3·10^6 распадов,
та же геометрия, `src_sha1` не изменился) даёт 5139 отсчётов в окне против 530
и разрешает вопрос на 7,1 сигмы: `P/T` модели НИЖЕ измеренного на 6,8 %. По
логике самого теста (см. выше) это значит, что форма отклика превышение
эффективности НЕ объясняет — оно принадлежит УРОВНЮ, не конвенции съёма или
форме пика. `RUN` переведён на длинный файл как основной; короткий остаётся в
`build/` для `selfcheck_suite.py` (не статистический тест, не требует замены).

ЧЕГО ЭТОТ ТЕСТ НЕ УЧИТЫВАЕТ. В измеренной записи есть фон помещения, в модели
его нет; фон поднимает `T` и опускает измеренное `P/T`. Поправка не вводится,
поэтому измеренное `P/T` — НИЖНЯЯ оценка, а расхождение модель-минус-измерение
— ВЕРХНЯЯ. Если и с этой поправкой знак вывода не меняется, вывод устойчив.
"""
import math
import os
import sys

import numpy as np
from scipy.optimize import curve_fit
from scipy.special import erfc

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402
