BUILD = str(paths.build("Gamma-1S"))
OUT = str(paths.results("Gamma-1S"))
RUN = "p5_Th228_long.csv"

# Границы пика в долях ПШПВ — из lsrm.cnf прибора (см. docstring).
PEAK_BOUND = 2.5

# Соседи внутри окна ±2,5 ПШПВ и потому НЕПРИГОДНОСТЬ линии для одиночного
# фита. Список выводится не из общих соображений, а из ширины самого окна:
# на 238,632 полуокно 58 кэВ накрывает 240,99 (Ra-224), на 583,187 полуокно
# 105 кэВ накрывает 510,77 (Tl-208) вместе с аннигиляционной 511. Одиночная
# гауссиана в таком окне собирает чужую площадь, и P/T теряет смысл: измеренная
# сторона там снималась связанной деконволюцией, расчётная здесь — нет.
NEIGHBOURS = {
    238.632: "дублет с 240;99 (Ra-224) внутри окна",
    583.187: "510;77 (Tl-208) и аннигиляционная 511 внутри окна",
    2614.511: "",
}

# ИЗМЕРЕНО оператором в окне «Параметры пиков» СпектраЛайн (сеанс 30.07.2026):
# (Площадь; Полная площадь). Числа перенесены из окна программы; отдельного
# файла-артефакта в репозитории нет, поэтому уровень проверки — «реквизиты
# верны, содержимое не перечитывалось». Столбец «Площадь» согласуется с
# hard_edge_th228.py (2030000 против 2030385 на 583,2), что служит косвенной
# сверкой переноса.
MEASURED = {238.632: (6402721, 10530686),
            583.187: (2030385, 3077752),
            2614.511: (453756, 651413)}

OBS = {
    "quantity": "P/T — отношение площади пика к полной площади в окне"
                " +-2.5 ПШПВ; величина безразмерная и от уровня"
                " эффективности не зависит",
    "area": "P — площадь гауссианы фита (ступенька и подложка в неё не"
            " входят); T — валовая сумма отсчётов в том же окне",
    "window": "+-2.5 ПШПВ — LeftPeakBound/RightPeakBound из lsrm.cnf прибора",
    "shelf": "подложка входит в T целиком; из P исключается фитом"
             " (линейная плюс ступенька-из-образа)",
    "blurred": "да — расчётный спектр распада размыт приборной ПШПВ по шести"
               " измеренным линиям",
    "source": "расчёт — прогон распада p5_Th228 (не моно: в окне должен быть"
              " континуум всей цепочки); измерение — запись Th-228 5 см",
    "caveat": "фон помещения в модели отсутствует; он поднимает T измерения;"
              " поэтому измеренное P/T — нижняя оценка",
}


def load(path):
    out = []
    for ln in open(path, encoding="utf-8"):
        if ln.startswith("#") or ln.startswith("E_keV") or not ln.strip():
            continue
        e, c = ln.split(",")
        out.append((float(e), float(c)))
    return out


def blur(ec, emax):
    src = np.zeros(emax)
    for e, c in ec:
        i = int(e)
        if 0 <= i < emax:
            src[i] += c
    xs = np.arange(emax, dtype=float)
    out = np.zeros(emax)
    for i in np.nonzero(src)[0]:
        s = dp.fwhm_measured(max(xs[i], 10.0)) / 2.3548
        lo, hi = max(0, int(xs[i] - 6 * s)), min(emax, int(xs[i] + 6 * s))
        g = np.exp(-0.5 * ((xs[lo:hi] - xs[i]) / s) ** 2)
        out[lo:hi] += src[i] * g / (s * math.sqrt(2 * math.pi))
    return xs, out


def peak_and_total(xs, ys, E0):
    """(P; T; ширина фита к приборной) в окне +-PEAK_BOUND ПШПВ."""
    fw = dp.fwhm_measured(E0)
    s0 = fw / 2.3548
    m = (xs >= E0 - PEAK_BOUND * fw) & (xs <= E0 + PEAK_BOUND * fw)
    x, y = xs[m], ys[m]
    total = float(y.sum())

    def model(xx, A, sh, ws, hstep, b0, b1):
        s = ws * s0
        mu = E0 + sh
        amp = A / (s * math.sqrt(2 * math.pi))
        gg = amp * np.exp(-0.5 * ((xx - mu) / s) ** 2)
        st = amp * hstep * 0.5 * erfc((xx - mu) / (s * math.sqrt(2)))
        return b0 + b1 * (xx - xx.mean()) + gg + st

    p, _ = curve_fit(
        model, x, y,
        p0=[y.sum() * 0.5, 0.0, 1.0, 1e-3, float(np.median(y)), 0.0],
        sigma=np.sqrt(np.maximum(y, 1.0)),
        bounds=([0, -0.5 * fw, 0.5, 0.0, -np.inf, -np.inf],
                [np.inf, 0.5 * fw, 2.0, 0.2, np.inf, np.inf]),
        maxfev=40000)
    return float(p[0]), total, float(p[2])


def main():
    path = os.path.join(BUILD, RUN)
    if not os.path.exists(path):
        raise SystemExit(
            "Не найден прогон распада %s в %s.\n"
            "Макрос th228_long.mac (3e6 распадов, ~сутки) — вне репозитория,"
            " в build/ рабочего каталога модели." % (RUN, BUILD))
    ec = load(path)
    emax = int(max(e for e, _ in ec)) + 400
    xs, ys = blur(ec, emax)

    print("Отношение пик / полная площадь; окно +-%.1f ПШПВ"
          " (LeftPeakBound/RightPeakBound прибора).\n" % PEAK_BOUND)
    print("%10s %10s %8s %8s %10s %9s %6s %s"
          % ("E, кэВ", "T модель", "P/T мод", "+-стат", "P/T изм",
             "разница", "сигм", "пригодность"))
    rows = []
    for E0 in sorted(MEASURED):
        P, T, wrel = peak_and_total(xs, ys, E0)
        pt_mod = P / T
        # Каждый отсчёт окна либо в пике, либо нет, поэтому доля ведёт себя
        # биномиально: sigma = sqrt(r(1-r)/T). Наивное sqrt(1/P + 1/T) для
        # ВЛОЖЕННЫХ величин завышает: P входит в T, они не независимы.
        d_pt = math.sqrt(max(pt_mod * (1 - pt_mod) / max(T, 1.0), 0.0))
        pm, tm = MEASURED[E0]
        pt_meas = pm / tm
        d = pt_mod - pt_meas
        nsig = abs(d) / d_pt if d_pt > 0 else float("inf")
        why = NEIGHBOURS.get(E0, "")
        ok = 0 if why else 1
        print("%10.3f %10.0f %8.4f %8.4f %10.4f %+8.1f%% %6.1f %s"
              % (E0, T, pt_mod, d_pt, pt_meas, 100 * d / pt_meas, nsig,
                 why or "чистая"))
        rows.append((E0, P, T, pt_mod, d_pt, pt_meas, d, nsig, wrel, ok, why))

    clean = [r for r in rows if r[9]]
    print("\nВЫВОД.")
    if not clean:
        print("  Ни одной пригодной линии — все окна содержат соседей.")
    for E0, P, T, m, dm, x, d, nsig, wrel, _, _ in clean:
        if nsig < 3.0:
            print("  %.1f кэВ: разница %+.1f %% при статистике %.1f сигмы —"
                  " НЕ РАЗРЕШЕНО." % (E0, 100 * d / x, nsig))
            print("     Нужен более длинный прогон распада: сейчас в окне"
                  " всего %.0f отсчётов." % T)
        elif d > 0:
            print("  %.1f кэВ: P/T модели ВЫШЕ измеренного на %.1f %% (%.1f"
                  " сигмы) — модель кладёт в пик то;"
                  % (E0, 100 * d / x, nsig))
            print("     что прибор рассыпает в подложку: часть расхождения"
                  " принадлежит ФОРМЕ отклика.")
        else:
            print("  %.1f кэВ: P/T модели НИЖЕ измеренного на %.1f %% (%.1f"
                  " сигмы) — модель недодаёт пику;"
                  % (E0, 100 * abs(d) / x, nsig))
            print("     то есть форма отклика не объясняет превышение"
                  " эффективности; оно принадлежит УРОВНЮ.")
    bad = [r for r in rows if not r[9]]
    if bad:
        print("  Исключены из вывода (соседи в окне ±%.1f ПШПВ; одиночный фит"
              " там собирает чужую площадь):" % PEAK_BOUND)
        for r in bad:
            print("     %.1f кэВ — %s" % (r[0], r[10]))
    print("  Фон помещения в модели отсутствует и поднимает T измерения;"
          " поэтому измеренное P/T — нижняя")
    print("  оценка; а разница модель-минус-измерение — верхняя.")

    csvio.write(
        os.path.join(OUT, "peak_to_total.csv"),
        ["E_keV", "P_model", "T_model", "pt_model", "d_pt_stat",
         "pt_measured", "diff_abs", "n_sigma", "fit_width_rel", "usable",
         "neighbours"],
        [("%.3f" % E, "%.0f" % P, "%.0f" % T, "%.4f" % m, "%.4f" % dm,
          "%.4f" % x, "%+.4f" % d, "%.1f" % n, "%.3f" % w, "%d" % ok,
          why or "нет")
         for E, P, T, m, dm, x, d, n, w, ok, why in rows],
        comments=[
            "Отношение пик/полная площадь: проверка ФОРМЫ отклика; не уровня."
            " От абсолютной эффективности не зависит.",
            "«Полная площадь» — по определению ЛСРМ: сумма площади под пиком"
            " и фона под пиком в окне границ пика.",
            "Границы +-2;5 ПШПВ — LeftPeakBound/RightPeakBound из lsrm.cnf"
            " прибора; в слепке аттестации те же.",
            "Измеренные пары (Площадь; Полная площадь) перенесены из окна"
            " «Параметры пиков»; файла-артефакта в репозитории нет.",
            "Фон помещения в модели отсутствует: измеренное P/T — нижняя"
            " оценка; разница модель-минус-измерение — верхняя.",
        ],
        stamp=stamp.lines(
            "detectors/Gamma-1S/analysis/peak_to_total.py", OBS,
            inputs=[path],
            geometry_dir=str(paths.geometry("Gamma-1S")),
            names=stamp.SRC_LISTS["Gamma-1S"], repo_dir=str(paths.REPO)))
    print("\nтаблица: %s" % os.path.join(OUT, "peak_to_total.csv"))


if __name__ == "__main__":
    main()
