        # СВЕДЕНИЕ ИДЁТ В ДВА ШАГА, И ЭТО НЕ ФОРМАЛЬНОСТЬ (замечание аудитора).
        # Первая редакция сводила ВСЕ годные линии геометрии одним взвешенным
