def chi2_dof(vals, m):
    """χ²/ν набора относительно среднего m. Мера СОГЛАСИЯ, не точности.

    Правило ЛСРМ («максимум из взвешенной оценки и разброса») уже есть
    расширение по Бирге: Δ_ср = √(Σwᵢ(Ā−Aᵢ)²/(Σwᵢ(n−1))) = Δ_св·√(χ²/ν).
    Но расширение спасает только там, где ВЕСА правильные. Если у линий
    занижены погрешности, χ²/ν растёт, а Δ_ср остаётся привязанной к самым
    «громким» линиям — набор несогласован, а печатается узкий интервал.
    Поэтому χ²/ν выводится рядом с результатом: он показывает, стоит ли
    вообще сводить набор одним числом.
    """
    pts = [(a, d) for a, d in vals if a > 0 and d and d > 0]
    if len(pts) < 2:
        return None
    return sum((m - a) ** 2 / d ** 2 for a, d in pts) / (len(pts) - 1)


def purity(tag, E, win):
    """(чистота, [(доля, энергия) засорителей]) по спектру ИСПУСКАНИЯ прогона.

    Спектр испускания — свойство РАСПАДА, а не геометрии: он пишется по
    родившимся гамма-квантам, до всякого взаимодействия с прибором. Поэтому
    для обеих точечных геометрий берётся один файл p5_<нукл>_emit.csv;
    отдельных прогонов распада на 25 см нет и не нужно.

    Ширина окна win — та же ±1 ПШПВ, которой снимается площадь; чистота
    учитывает ИНТЕНСИВНОСТЬ соседей, а не только расстояние до них.
    """
    p = os.path.join(BUILD, "p5_%s_emit.csv" % tag)
    if not os.path.exists(p):
        return None, []
    USED.add(p)
    emit, _N = load_hist(p)
    tot = sum(c for e, c in emit.items() if abs(e - E) <= win)
    if tot <= 0:
        return None, []
    own = sum(c for e, c in emit.items() if abs(e - E) <= CLEAN_HALF)
    bad = sorted(((c / tot, e) for e, c in emit.items()
                  if CLEAN_HALF < abs(e - E) <= win and c > 0.02 * tot),
                 reverse=True)
    return own / tot, bad


def load_hist(path):
    hist, N = {}, None
    for line in open(path, encoding="utf-8"):
        if line.startswith("#"):
            if "N_primaries" in line:
                N = int(line.split("=")[1])
            continue
        if line and line[0].isdigit():
            e, c = line.split(",")
            hist[float(e)] = int(c)
    return hist, N


# FWHM662 определена выше, вместе с полосой заражения вылетом: она нужна для
# вычисления ESCAPE_BAND в объявлении наблюдаемой.
_BROAD = {}


def fwhm(E):
    return FWHM662 * math.sqrt(E / 661.657)


def area_sim(hist, E, key=None, broad=True, detail=None):
    """Площадь пика в модельном спектре.

    broad=True — спектр уширяется до разрешения прибора и площадь берётся ТЕМ
    ЖЕ окном (±1 ПШПВ + полки), что и в измерении. Обязательно там, где линии
    сливаются: у Eu-152 в NaI почти всё поле — бленды, у Th-228 линия 583,2
    соседствует с 510,7. Узкое окно по модели против широкого по измерению
    завышает активность (проверено на Ac-228 911+969: ошибка 1,5 раза).
    broad=False — депозитное окно, годится только для сеток моноэнергий.

    Депозитное окно и его полка — в `common/py/peakwin.py`, ОДНОЙ реализацией на
    репозиторий: прежде правило было скопировано в четыре места, и починка окна
    полки досталась только этому файлу, а объёмный пересчёт остался на дефектном
    правиле. Параметры окна больше не принимаются аргументами: возможность
    задать их по месту и была тем, чем копии разошлись.

    Размытый путь идёт с исключением полос вылета K-рентгена (`ESCAPES`) —
    полка в долях ПШПВ заражена тем же вылетом, что депозитная, но в другом
    месте: полоса энергий 54,3…217,4 кэВ, пять линий комплекта
    (см. method-rules §1).
    """
    if broad:
        if key not in _BROAD:
            _BROAD[key] = bm.broaden(hist, FWHM662)
        a, _ = bm.area_broadened(_BROAD[key], E, fwhm(E), escapes=ESCAPES,
                                 detail=detail)
        return a
    return peakwin.area(hist, E, detail=detail)


