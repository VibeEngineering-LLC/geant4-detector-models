def eps_decay_5cm(tag, E):
    """Эффективность на распад из прогона распада на 5 см (всё внутри)."""
    p = os.path.join(BUILD, "p5_%s.csv" % tag)
    if not os.path.exists(p):
        return None, None
    USED.add(p)
    hist, N = load_hist(p)
    a = area_sim(hist, E, key="p5:" + tag)
    if a <= 0 or not N:
        return None, None
    return a / N, math.sqrt(max(abs(a), 1.0)) / N


def yield_5cm(tag, E):
    p = os.path.join(BUILD, "p5_%s_emit.csv" % tag)
    if not os.path.exists(p):
        return None
    USED.add(p)
    em, N = load_hist(p)
    tot = sum(c for e, c in em.items() if abs(e - E) <= 2.0)
    return tot / N if (N and tot > 50) else None


def solid_angle_frac(spectrum_path, gtag):
    """Доля телесного угла розыгрыша: сперва шапка спектра, потом файл-сателлит.

    Порядок именно такой. Шапку пишет exe, разыгравший события, — это ответ на
    «из чего получено». Файл-сателлит писал драйвер по своей таблице углов, и
    совпадение с фактическим розыгрышем ничем не обеспечивалось. Откат нужен
    только для прогонов, сделанных до внедрения шапки; при откате файл идёт в
    USED, и вердикт по входам честно становится непрослеженным.
    """
    for ln in open(spectrum_path, encoding="utf-8", errors="replace"):
        if not ln.startswith("#"):
            break
        if "solid_angle_frac" in ln:
            return float(ln.split("=")[1])
    saf = os.path.join(BUILD, "grid", "%s_solidangle.txt" % gtag)
    if os.path.exists(saf):
        USED.add(saf)
        return float(open(saf).read().strip())
    # Ни шапки, ни файла-сателлита: прогон сделан старым exe и БЕЗ конуса —
    # сателлит писался ровно для конусных сеток (POINTS в run_all_grids.py), а
    # объёмные разыгрывались в полный 4pi. Возвращаем 1,0, но это ДОПУЩЕНИЕ о
    # чужом прогоне, поэтому:
    #  * оно верно для существующих данных по построению драйвера;
    #  * после регенерации становится ненужным — шапку пишет сам exe;
    #  * молчать о нём нельзя, иначе конусный прогон старого exe без сателлита
    #    получил бы 1,0 и завысил eps в четыре раза.
    NO_FRAC.add(gtag)
    return 1.0


def eps_mono_point(gtag, E):
    """Сетка с конусом: делим на долю телесного угла, записанную рядом."""
    # Доля телесного угла — ИЗ ШАПКИ СПЕКТРА, её пишет сам exe, разыгравший
    # события (`# solid_angle_frac =`). Прежде она бралась из отдельного файла
    # `<метка>_solidangle.txt`, который писал драйвер по своей таблице углов:
    # ПРЯМОЙ множитель на каждую точечную eps лежал вне цепочки провенанса, и
    # прогон с другим углом никакая сверка бы не заметила (найдено аудитом).
    # Файл-сателлит остаётся откатом для прогонов, сделанных до этой правки, и
    # тогда попадает в USED — чтобы «непрослеженность» была видна вердиктом.
    best = None
    for p in glob.glob(os.path.join(BUILD, "grid", gtag + "_E*.csv")):
        m = re.search(r"_E(\d+\.\d)\.csv$", p)
        if m and abs(float(m.group(1)) - E) < 1.0:
            best = p
    if not best:
        return None
    USED.add(best)
    frac = solid_angle_frac(best, gtag)
    if frac is None:
        return None
    hist, N = load_hist(best)
    # сетка моноэнергий: блендов нет по построению, узкое окно корректно
    a = area_sim(hist, E, broad=False)
    return (a / N) * frac if (N and a > 0) else None


def decay_factor(nuc, d0, d1):
    if not d0 or not d1:
        return 1.0
    y0, m0, dd0 = (int(x) for x in d0.split("-"))
    y1, m1, dd1 = (int(x) for x in d1.split("-"))
    dt = (date(y1, m1, dd1) - date(y0, m0, dd0)).days / 365.25
    return 0.5 ** (dt / T12[nuc])


def record(geom, nuc):
    """Найти XML записи по геометрии и нуклиду.

    Раскладка комплекта — reference_spectra/reference_kits_becqmoni/
    <геометрия>/<нуклид>/sample_*.xml. Стоял плоский glob по
    <корень эталонов>/<геометрия>/, который не находил ничего, и пересчёт
    молча печатал пустую таблицу. Тот же дефект был в kit_recalc.py.
    """
    kd = paths.kit_dir(geom)
    if kd is None:
        return None
    hits = sorted(str(p) for p in kd.rglob("*%s*" % nuc) if p.suffix == ".xml")
    return hits[0] if hits else None


if __name__ == "__main__":
    print("Пересчёт точечных записей комплекта. Отношение телесных углов "
          "25/5 см = %.4f\n" % OMEGA_RATIO)
    print("%-11s %-8s %9s %9s %11s %6s %9s %8s" %
          ("геометрия", "нуклид", "E, кэВ", "имп/с", "eps/распад", "C",
           "A, Бк", "A/пасп"))
    ratios, rows = [], []
    for geom in ("Point_5cm", "Point_25cm"):
        for nuc, (tag, lines) in NUC.items():
            key = (geom, nuc)
            if key not in PASSPORT:
                continue
            p = record(geom, nuc)
            if not p:
                continue
            s, b = bm.read_checked(p)[:2]
            txt = open(p, encoding="utf-8", errors="replace").read()
            md = re.search(r"<StartTime>(\d{4}-\d{2}-\d{2})", txt)
            md = md.group(1) if md else None
            bgref = re.search(r"<BackgroundSpectrumFile>([^<]*)</", txt)
            bgref = os.path.basename(bgref.group(1)) if bgref else "?"
            want = "point5cm" if geom == "Point_5cm" else "point25cm"
            if want not in bgref:
                print("   !! %s %s: фон «%s» не соответствует геометрии"
                      % (geom, nuc, bgref))
            A0raw, dpct, d0 = PASSPORT[key]
            A0 = A0raw * decay_factor(nuc, d0, md)
            R = float(s.n.sum()) / s.live
            pile = math.exp(2 * TAU_SHAPE * R)
            for E in lines:
                # ПШПВ по единому закону, а не по своему пику: окна модели и
                # измерения должны совпадать в точности, а у слабых линий пик
                # не находится
                fw = fwhm(E)
                # Чистота линии — ДО расчёта: она решает, пойдёт ли линия в
                # активность. Считается и на 5, и на 25 см по одному спектру
                # испускания (см. purity), поэтому набор годных линий у обеих
                # геометрий один и тот же — расходиться могут только причины
                # исключения по полкам, они геометрии не безразличны.
                frac, dirt = purity(tag, E, fw)
                usable = frac is not None and frac >= CLEAN_FRAC
                # escapes — на ИЗМЕРЕННОЙ стороне тем же кодом, что на
                # расчётной: полагаться на сокращение смещения в отношении
                # нельзя, оно держится на том, что модель верно воспроизводит
                # вылет, а это и есть проверяемое.
                r = bm.net_rate(s, b, E, fw, roi=1.0, side=1.0,
                                escapes=ESCAPES)
                if r is None or r[0] <= 0:
                    continue
                rate = r[0] * pile
                if geom == "Point_5cm":
                    # площадь модели снимается ТЕМ ЖЕ окном по уширенному
                    # спектру распада -> загрязнение полок сокращается
                    ed, _ = eps_decay_5cm(tag, E)
                    Cshow = "прям."
                else:
                    # на 25 см модельная сторона — сетка МОНОЭНЕРГИЙ, у неё
                    # полки чистые, а у измерения нет: сокращения не будет
                    bad = dirty_shelves(nuc, E, fw)
                    if bad:
                        print("%-11s %-8s %9.1f  полка загрязнена (%s) — "
                              "исключено"
                              % (geom, nuc, E,
                                 ", ".join("%.1f" % x for x in bad)))
                        continue
                    em = eps_mono_point("p25cm", E)
                    pg = yield_5cm(tag, E)
                    ed5, _ = eps_decay_5cm(tag, E)
                    em5 = eps_mono_point("p5cm", E)
                    C5 = (em5 / (ed5 / pg)) if (ed5 and em5 and pg) else None
                    C25 = 1 + (C5 - 1) * OMEGA_RATIO if C5 else 1.0
                    ed = (em * pg / C25) if (em and pg) else None
                    Cshow = "%.3f" % C25 if C5 else "1.000"
                if not ed:
                    continue
                A = rate / ed
                # Погрешность активности ПО ЛИНИИ — только от счёта. Паспортная
                # доля входит одинаково всем линиям ОДНОГО нуклида, на их
                # взаимный вес не влияет и добавляется на следующем шаге, когда
                # ряды сводятся между собой (см. сведение ниже). Держать её
                # здесь нельзя: внутри нуклида она сокращается, а снаружи она
                # независима у каждого источника и там главная.
                dA = A * (r[1] / r[0])
                if usable:
                    ratios.append((geom, nuc, E, A / A0, dA / A0, dpct))
                rows.append((geom, nuc, E, rate, ed, Cshow, A, A0, A / A0,
                             frac, usable))
                tag_txt = "  чистота %.2f" % (frac if frac is not None else 0.0)
                if not usable:
                    tag_txt += " — В АКТИВНОСТЬ НЕ ИДЁТ: " + (
                        ", ".join("%.0f кэВ %.0f%%" % (e, 100 * f)
                                  for f, e in dirt[:3]) or "группа")
                print("%-11s %-8s %9.1f %9.3f %11.4e %6s %9.3e %8.3f%s"
                      % (geom, nuc, E, rate, ed, Cshow, A, A / A0, tag_txt))
