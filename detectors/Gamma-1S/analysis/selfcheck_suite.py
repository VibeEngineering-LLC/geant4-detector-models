# --------------------------------------------------------------------------
def read_spectrum(path):
    hist, N = {}, None
    for ln in open(path, encoding="utf-8"):
        if ln.startswith("#"):
            if "N_primaries" in ln:
                N = int(ln.split("=")[1])
            continue
        if ln and ln[0].isdigit():
            e, c = ln.split(",")
            hist[float(e)] = float(c)
    return hist, N


def band(hist, lo, hi):
    """Сумма отсчётов в полосе [lo; hi) — для линий; которые не разрешены."""
    return sum(c for e, c in hist.items() if lo <= e < hi)


def verdict(name, ok, value, thr, detail, why):
    return {"name": name, "verdict": ok, "value": value, "threshold": thr,
            "detail": detail, "why": why}


