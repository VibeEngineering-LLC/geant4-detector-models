# -*- coding: utf-8 -*-
"""Две правки окна площади, измеренные ПО ОТДЕЛЬНОСТИ (задачи 129, 132).

ЗАЧЕМ ПО ОТДЕЛЬНОСТИ. В `area_sim` изменились две независимые вещи:
  (а) окно полки `[E−30, E−10]` -> `[E−25, E−10]` — чтобы плоская подложка не
      вычиталась поверх пика вылета K-рентгена иода (`E−28,6`);
  (б) ширина окна пика: множитель `2*win+1` = 13 каналов -> `nchan()` = 12,
      потому что каналы стоят в серединах `(i+0.5)*bin` и правило,
      записанное в кэВ, применялось к каналам.
Считать их вместе нельзя: тогда неизвестно, что именно сдвинуло кривую, а
контрольный признак починки обязан отличаться от починяемого правила ровно на
одну вещь (method-rules §5). Обе правки трогают ТОЛЬКО вычитаемую полку,
поэтому обе поднимают `eps` и обе сильнее на мягком крае.

ЧТО СЧИТАЕТСЯ. Одна и та же сетка моноэнергий, один и тот же файл, четыре
правила съёма площади. Прогонов не делается вовсе — это чистая сверка
конвенций, самая дешёвая из возможных: различие не может быть отнесено ни к
геометрии, ни к статистике, ни к версии exe.

ОГОВОРКА О ВХОДАХ. Штамп провенанса печатается вместе с числами. Если вердикт
не `ok`, отношения ниже всё равно осмысленны (числитель и знаменатель считаны
с ОДНОГО файла), а вот абсолютные `eps` — нет.
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402
import paths  # noqa: E402
import peakwin  # noqa: E402
import stamp  # noqa: E402

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "drivers"))
import grid_energies  # noqa: E402
import point_recalc as pr  # noqa: E402

WIN = 6.0
BG1 = 10.0

# ПЯТЬ правил, а не четыре. Прежние четыре смешивали в варианте «каналы» ДВЕ
# вещи: число каналов (13 -> 12) и ПРИВЯЗКУ окна (peakwin центрирует его на
# ближайшем канале и задаёт полку индексами, а не фильтром по кэВ). Пока они
# шли вместе, выведенный перекрёстный член a*(1-12/13) к этой паре не
# относился, и собственная проверка честно не сошлась: 1,24 против 0,81 п.п.
#   множ12 — меняется ТОЛЬКО множитель, фильтры по кэВ прежние (счёт каналов);
#   привяз — peakwin при прежнем крае полки (привязка окна к сетке);
#   оба    — то, что стоит в конвейере.
RULES = (("старое", 30.0, "kev"),
         ("окно25", 25.0, "kev"),
         ("множ12", 30.0, "kev12"),
         ("привяз", 30.0, "chan"),
         ("пара", 25.0, "kev12"),
         ("оба", 25.0, "chan"))


def area(hist, E, bg0, mode):
    """Площадь по одному из четырёх правил.

    `mode="kev"` воспроизводит ПРЕЖНЕЕ правило дословно (фильтр по кэВ и
    множитель `2*win+1`) — иначе сверять было бы нечего. `mode="chan"` идёт
    через `peakwin`, то есть через ту самую реализацию, что стоит в конвейере:
    сверка с собственной копией нового правила была бы сверкой копии с копией.
    """
    if mode == "chan":
        return peakwin.area(hist, E, win_keV=WIN, bg0_keV=bg0, bg1_keV=BG1)
    gross = sum(c for e, c in hist.items() if abs(e - E) <= WIN)
    side = sum(c for e, c in hist.items() if E - bg0 <= e <= E - BG1)
    n_peak = 12.0 if mode == "kev12" else 2 * WIN + 1
    return gross - side / (bg0 - BG1) * n_peak


def true_energy(label):
    """Истинная энергия линии по метке файла — БЛИЖАЙШАЯ из списка сетки.

    Метка в имени файла округлена до 0,1 кэВ, а конвейер (`eps_mono_point`)
    передаёт в съём площади ИСТИННУЮ энергию линии. Для 1764,491 и 2614,511
    округление меняет число каналов в окне, то есть сверка «изменено ровно одно
    правило» шла бы на РАЗНЫХ окнах — причём на 2614,5, одном из опорных узлов
    таблицы поправок. Найдено независимым аудитом.
    """
    return min(grid_energies.LINES, key=lambda x: abs(x - float(label)))


def main():
    rows, skipped = [], 0
    for gtag in ("p5cm", "p25cm"):
        paths_g = sorted(glob.glob(os.path.join(pr.BUILD, "grid",
                                                gtag + "_E*.csv")))
        if not paths_g:
            print("нет сетки %s — пропуск" % gtag)
            continue
        for p in paths_g:
            m = re.search(r"_E(\d+\.\d)\.csv$", p)
            if not m:
                continue
            E = true_energy(m.group(1))
            hist, N = pr.load_hist(p)
            frac = pr.solid_angle_frac(p, gtag)
            if not N or frac is None:
                skipped += 1
                continue
            pr.USED.add(p)
            eps = {}
            for label, bg0, mode in RULES:
                a = area(hist, E, bg0, mode)
                eps[label] = (a / N) * frac if a > 0 else None
            if None in eps.values():
                skipped += 1
                continue
            rows.append((gtag, E, eps))

    if not rows:
        raise SystemExit("Нет сеток моноэнергий — нечего сверять.")
    if skipped:
        # Молчаливый пропуск делает таблицу короче сетки без всякого признака.
        print("пропущено энергий: %d (нет статистики либо площадь <= 0)\n"
              % skipped)

    DELTAS = ("окно25", "множ12", "привяз", "оба")
    # «пара» в таблицу не печатается: она нужна только контрольной проверке.
    print("Влияние правок окна на eps сетки, ПО ОТДЕЛЬНОСТИ.")
    print("окно25 — только край полки 30 -> 25 кэВ; множ12 — только множитель"
          " 13 -> 12;")
    print("привяз — окно задано в КАНАЛАХ вместо кэВ; оба — правило конвейера."
          "\n")
    print("%-7s %9s %12s %9s %9s %9s %9s"
          % (("сетка", "E, кэВ", "eps старое") + DELTAS))
    out = []
    for gtag, E, eps in rows:
        d = {k: 100.0 * (eps[k] / eps["старое"] - 1.0) for k in DELTAS}
        print("%-7s %9.1f %12.5e %+8.2f%% %+8.2f%% %+8.2f%% %+8.2f%%"
              % ((gtag, E, eps["старое"]) + tuple(d[k] for k in DELTAS)))
        out.append((gtag, "%.3f" % E, "%.6e" % eps["старое"],
                    "%.6e" % eps["оба"])
                   + tuple("%+.3f" % d[k] for k in DELTAS))

    # ПЕРЕКРЁСТНЫЙ ЧЛЕН ВЫВЕДЕН, А НЕ УГАДАН — и проверяется на той паре, к
    # которой вывод относится: «окно25» и «множ12», обе на прежних фильтрах по
    # кэВ. Пусть
    #   net = G − S/n_s · n_p,  X = S30/20·13 (прежнее вычитание),
    #   u = S25/15·13 (только окно),  v = S30/20·12 (только множитель).
    # Тогда a = (X−u)/net, b = (X−v)/net, совместное = (X − u·12/13)/net, и
    #   a + b − совместное = (X − v − u/13)/net = a·(1 − 12/13),
    # поскольку X − v = S30/20 = X/13.
    #
    # Первая версия проверки ждала произведения a·b (так было бы при
    # МУЛЬТИПЛИКАТИВНОМ действии правок) и подняла ложную тревогу на верных
    # числах: 0,836 против ожидаемых 0,095. Вторая версия сравнивала с этим
    # выводом пару «окно25 + привяз», где меняется ещё и привязка окна, — и
    # честно не сошлась. Оба раза числа были верны, неверно было сравнение.
    # «Репродукция ≠ верификация» работает и в обратную сторону: контрольная
    # формула тоже требует вывода, а не переноса по аналогии.
    N_OLD, N_NEW = 2 * WIN + 1, 12.0
    print("\nПерекрёстный член пары «окно25 + множ12» (обе на фильтрах по кэВ):")
    worst = (0.0, 0.0, None, 0.0, 0.0)
    for gtag, E, eps in rows:
        a = 100.0 * (eps["окно25"] / eps["старое"] - 1.0)
        b = 100.0 * (eps["множ12"] / eps["старое"] - 1.0)
        joint = 100.0 * (eps["пара"] / eps["старое"] - 1.0)
        got = a + b - joint
        want = a * (1.0 - N_NEW / N_OLD)
        if abs(got - want) > abs(worst[0] - worst[3]):
            worst = (got, E, gtag, want, a)
    print("  на %s %.1f кэВ: наблюдено %.3f п.п., вывод даёт %.3f п.п."
          " (поправка окна %.2f %%)"
          % (worst[2], worst[1], worst[0], worst[3], worst[4]))
    ok = abs(worst[0] - worst[3]) < 0.02 + 0.02 * abs(worst[3])
    print("  сошлось -> пара трогает только полку, лишнего нет." if ok else
          "  !! НЕ сошлось — разобрать: правки задевают не только полку.")
    print("  привязка окна к каналам («привяз») — ОТДЕЛЬНАЯ правка,"
          " к этому выводу не относится.")

    verdict, detail = stamp.check_inputs(
        sorted(pr.USED), str(paths.geometry("Gamma-1S")),
        stamp.SRC_LISTS["Gamma-1S"])
    print("\nПРОВЕНАНС входов: %s (%s)" % (verdict, detail))
    if verdict != "ok":
        print("  Отношения выше осмысленны (числитель и знаменатель с одного"
              " файла); абсолютные eps — нет.")

    csvio.write(
        os.path.join(str(paths.results("Gamma-1S")), "shelf_window_effect.csv"),
        ["grid", "E_keV", "eps_old", "eps_new", "d_window25_pct",
         "d_mult12_pct", "d_chanbind_pct", "d_both_pct"],
        out,
        comments=[
            "Влияние двух правок окна съёма площади на eps сеток моноэнергий;"
            " прогоны НЕ переделывались.",
            "d_window25_pct — только край полки 30 -> 25 кэВ (пик вылета"
            " K-рентгена иода уходит из окна полки).",
            "d_mult12_pct — только множитель окна пика: 13 -> 12 каналов при"
            " прежних фильтрах по кэВ.",
            "d_chanbind_pct — только привязка окна к СЕТКЕ вместо кэВ; убирает"
            " скачок ширины на 8 % у энергий",
            "  с дробной частью 0;5 (среди узлов такие есть: 59;5 и 3552;5 —"
            " оба края паспортного диапазона).",
            "Обе правки только УМЕНЬШАЮТ вычитаемую полку; отсюда знак плюс и"
            " рост эффекта к мягкому краю.",
        ],
        stamp=stamp.lines(
            "detectors/Gamma-1S/analysis/shelf_window_effect.py",
            {"quantity": "eps сетки моноэнергий при четырёх правилах съёма"
                         " площади; отношения к прежнему правилу",
             "area": "пик полного поглощения в депозит-спектре",
             "window": "±6;0 кэВ",
             "shelf": "сравниваются [E-30; E-10] и [E-25; E-10]"
                      " односторонние",
             "blurred": "нет (депозит как есть)",
             "cone": "приведено делением на долю телесного угла из"
                     " <сетка>_solidangle.txt"},
            inputs=sorted(pr.USED),
            geometry_dir=str(paths.geometry("Gamma-1S")),
            names=stamp.SRC_LISTS["Gamma-1S"], repo_dir=str(paths.REPO)))
    print("таблица: %s"
          % os.path.join(str(paths.results("Gamma-1S")),
                         "shelf_window_effect.csv"))


if __name__ == "__main__":
    main()
