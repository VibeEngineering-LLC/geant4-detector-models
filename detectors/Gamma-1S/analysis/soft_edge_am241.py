"""Мягкий край: Am-241 59,5 кэВ, точечная 5 см — парная клетка (Трек 2).

Чистая монолиния ниже 100 кэВ: ни бленда, ни каскада, ни цепочки, ни
самопоглощения — из всех наших данных это самое чистое место, где можно
спросить «сколько поглотителя перед кристаллом».

ПАРНАЯ КЛЕТКА СНЯТА (сеанс 30.07.2026). Прежние прогоны шли на штатном
полиноме зон в обоих случаях — экспортёр подменял только таблицу точек
.efa, а активность программа считает по полиному (установлено на Th-228,
см. hard_edge_th228.py). После пересчёта полинома (efa_zones.py) и
применения калибровки по эффективности кривая переключается по-настоящему.

СЧИТАТЬ ПО УЗЛАМ БЫЛО НЕВЕРНО. На краю зоны полином отходит от своего же
узла: штатный на +3,44 % (4,1135E-02 против 3,9768E-02), наш на +0,64 %
(3,9030E-02 против 3,8782E-02). Оба отклонения независимо подтвердились
столбцом «Deviation» окна редактора эффективности. Поэтому расхождение
кривых на этой линии не 2,5 % (по узлам), а 5,1 % — и оно ВЫШЕ разрешения
вывода, тогда как 2,5 % туда не пролезали.

ПРЕДСКАЗАНИЕ БЫЛО ЗАФИКСИРОВАНО ДО ПРОГОНА (задача 120): 104600 Бк по
нашей кривой против 99000 по штатной. Получено 105000 базовым методом и
104000 зональным.

ГЛАВНОЕ. Знак расхождения на мягком крае ОБРАТЕН тому, что на жёстком:
здесь наша кривая ниже штатной и потому завышает активность на 6 %, на
2614,5 кэВ выше и занижает на 22 %. Полиномы пересекаются на 81,0 кэВ.
Это исключает объяснение единым множителем (нормировкой) и указывает на
энергетический ход — задача 93.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402

RESULTS = os.path.abspath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "results"))

# Паспорт источника: 103100 Бк, неопределённость 3 % при k = 2, дата
# 30.03.2021 — из файла паспортов эталонов прибора (формат «значение,неопр. %»,
# Sigma=2 в шапке) и из поля «Заметки» свойств спектра. Дата 02.2019, стоявшая
# здесь прежде, была взята из моего же старого комментария и неверна.
A_PASS, D_PASS = 103100.0, 3.0       # Бк, %
T12_A = 432.6                         # лет
DT_YEARS = 1301.0 / 365.25            # 30.03.2021 -> 21.10.2024
I_GAMMA = 0.359                       # выход 35,9 % — из библиотеки прибора
T_LIVE = 1811.475                     # с живого времени
FWHM_FIT_PCT = 16.707                 # ПШПВ фита, % (58,52 кэВ)

# Значения полиномов на 59,541 кэВ и отклонения от узлов (столбец Deviation)
EPS_POLY = {"штатная": 4.1135e-2, "наша": 3.9030e-2}
EPS_NODE = {"штатная": 3.976771e-2, "наша": 3.877473e-2}

# Сеанс 30.07.2026, параметры слепка, калибровка по эффективности ПРИМЕНЕНА
# в обоих прогонах (указание оператора: годны только такие прогоны; ранние,
# без применения калибровки, в свод не входят).
# метод -> (площадь, A Бк, неопр. %)
RUNS = {
    "штатная": {"Base": (2654000, 99000, 13),
                "ZoneByZone_Plus": (2650000, 99000, 17)},
    "наша": {"Base": (2655000, 105000, 16),
             "ZoneByZone_Plus": (2650000, 104000, 19)},
}
PRED = 104600.0                       # предсказано до прогона, задача 120


if __name__ == "__main__":
    a_pass = A_PASS * 0.5 ** (DT_YEARS / T12_A)
    print("Am-241 59,5 кэВ, точечная 5 см, поверка 2024; сеанс 30.07.2026"
          " на параметрах слепка, ПШПВ фита %.2f %%." % FWHM_FIT_PCT)
    print("паспорт %.0f Бк +-%.0f %% -> на дату измерения %.0f Бк\n"
          % (A_PASS, D_PASS, a_pass))

    print("Кривые на 59,541 кэВ: полином против узла")
    for k in ("штатная", "наша"):
        print("  %-8s узел %.4e   полином %.4e   отклонение %+.2f %%"
              % (k, EPS_NODE[k], EPS_POLY[k],
                 100 * (EPS_POLY[k] / EPS_NODE[k] - 1)))
    print("  расхождение кривых: по узлам %.1f %%, по полиномам %.1f %%"
          % (100 * (EPS_NODE["наша"] / EPS_NODE["штатная"] - 1),
             100 * (EPS_POLY["наша"] / EPS_POLY["штатная"] - 1)))

    rows = []
    print("\n%-8s %-16s %9s %9s %8s %11s"
          % ("кривая", "метод", "площадь", "A, Бк", "A/пасп", "eps по A"))
    for k in ("штатная", "наша"):
        for meth, (S, A, u) in sorted(RUNS[k].items()):
            eps = (S / T_LIVE) / (A * I_GAMMA)
            print("%-8s %-16s %9d %9d %8.3f %11.4e"
                  % (k, meth, S, A, A / a_pass, eps))
            rows.append((k, meth, S, A, u, A / a_pass, eps))

    print("\nОтношение наша/штатная по методам:")
    for meth in ("Base", "ZoneByZone_Plus"):
        r = RUNS["наша"][meth][1] / RUNS["штатная"][meth][1]
        print("  %-16s %.3f" % (meth, r))
    print("  предсказано по полиномам %.3f"
          % (EPS_POLY["штатная"] / EPS_POLY["наша"]))
    S, A, _u = RUNS["наша"]["Base"]
    print("  предсказанная активность %.0f Бк -> получено %d"
          % (PRED, A))

    print("\nЗнак расхождения меняется с энергией (одна геометрия,"
          " один прибор):")
    print("    59,5 кэВ  наша/штатная по активности 1,061 — завышает на 6 %")
    print("  2614,5 кэВ  наша/штатная по активности 0,784 — занижает на 22 %")
    print("  пересечение полиномов 81,0 кэВ; единым множителем не"
          " объясняется")

    csvio.write(
        os.path.join(RESULTS, "soft_edge_am241.csv"),
        ["curve", "method", "peak_area", "A_Bq", "unc_pct",
         "ratio_to_passport", "eps_from_activity"],
        [(k, m, "%d" % s, "%d" % a, "%d" % u, "%.4f" % r, "%.6e" % e)
         for k, m, s, a, u, r, e in rows],
        comments=[
            "Am-241 59;5 кэВ (чистая монолиния); точечная 5 см; поверка"
            " 2024. Паспорт 103100 Бк +-3 % (k=2; 30.03.2021)"
            " -> 102513 Бк на дату измерения 21.10.2024.",
            "Сеанс 30.07.2026 на параметрах резервного слепка; калибровка"
            " по эффективности применена в обоих прогонах;",
            "  полином зон нашей кривой пересчитан (efa_zones.py).",
            "На краю зоны полином отходит от узла: штатный +3;44 %;"
            " наш +0;64 % (подтверждено столбцом Deviation редактора);",
            "  поэтому расхождение кривых здесь 5;1 % по полиномам; а не"
            " 2;5 % по узлам — и оно выше разрешения вывода.",
            "Предсказание 104600 Бк было зафиксировано до прогона;"
            " получено 105000 (Base) и 104000 (ZoneByZone_Plus).",
            "Знак обратен жёсткому краю: здесь наша кривая завышает"
            " активность на 6 %; на 2614;5 кэВ занижает на 22 %;",
            "  полиномы пересекаются на 81;0 кэВ — единым множителем"
            " расхождение не объясняется.",
        ])
    print("\nтаблица: %s" % os.path.join(RESULTS, "soft_edge_am241.csv"))
