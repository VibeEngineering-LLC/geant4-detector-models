"""Мягкий край: Am-241 59,5 кэВ, точечная 5 см (Трек 2).

Чистая монолиния ниже 100 кэВ: ни бленда, ни каскада, ни цепочки, ни
самопоглощения — из всех наших данных это самое чистое место, где можно
спросить «сколько поглотителя перед кристаллом».

ДАННЫЕ: сеанс СпектраЛайн 29.07.2026, метод «Последовательно по зонам +»,
ПОСЛЕ калибровки по ПШПВ (до неё хи-квадрат фита 1995, после 1137).
Кривая в момент расчёта — НАША (в свойствах спектра детектор «geant4»:
редактор эффективности регистрирует построенную кривую как отдельный
детектор, отсюда и видно, какая кривая работала).

ПАРНЫЙ ПРОГОН СО ШТАТНОЙ КРИВОЙ НЕВОЗМОЖЕН — установлено экспериментом
оператора: при переключении кривой (и файлом полинома, и привязкой в
свойствах) активность не меняется НИ НА ЕДИНИЦУ. Вместе с прежней
находкой на маринелли (подмена узлов .efa тоже ничего не меняла) это
означает: программа держит эффективность в своей базе, а не перечитывает
её из выбираемых файлов. Поэтому клетка «штатная кривая × СпектраЛайн»
для точечной 5 см недостижима, и сравнение кривых делается ТОЛЬКО по
узлам, своим алгоритмом.

ЧТО СЧИТАЕТСЯ ЗДЕСЬ: одна измеренная площадь, три способа получить из неё
активность — полином программы, наш узел, узел штатной кривой. Паспорт
приведён на дату измерения.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402

RESULTS = os.path.abspath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "results"))

A_PASS, D_PASS = 103100.0, 3.0       # Бк, % — паспорт источника, 02.2019
T12_A = 432.6                         # лет
DT_YEARS = (2024 + 9.7 / 12) - (2019 + 1.5 / 12)
S_PEAK, T_LIVE, I_GAMMA = 2847995.0, 1811.475, 0.359
A_PROG, D_PROG = 106000.0, 14.0       # то, что показала программа
EPS_LSRM = 3.976771e-2                # узел штатной кривой, 59,541 кэВ
FWHM_FIT_PCT = 20.750                 # ПШПВ фита, % (58,38 кэВ)


def our_eps(E=59.5):
    with open(os.path.join(RESULTS, "eff_p5cm.csv"), encoding="utf-8") as fh:
        for ln in fh:
            if ln.startswith(("#", "E_keV")):
                continue
            f = ln.split(",")
            if abs(float(f[0]) - E) < 0.2:
                return float(f[1])
    raise SystemExit("нет узла %g в eff_p5cm.csv" % E)


if __name__ == "__main__":
    a_pass = A_PASS * 0.5 ** (DT_YEARS / T12_A)
    rate = S_PEAK / T_LIVE
    ours = our_eps()
    rows = [("полином программы (наша кривая)", None, A_PROG),
            ("узел нашей кривой", ours, rate / (ours * I_GAMMA)),
            ("узел штатной кривой", EPS_LSRM, rate / (EPS_LSRM * I_GAMMA))]

    print("Am-241 59,5 кэВ, точечная 5 см, поверка 2024.")
    print("паспорт %.0f Бк ±%.0f %% -> на дату измерения %.0f Бк"
          % (A_PASS, D_PASS, a_pass))
    print("площадь %.0f за %.1f с живого -> %.1f имп/с\n"
          % (S_PEAK, T_LIVE, rate))
    print("%-34s %12s %10s %8s" % ("способ", "eps", "A, Бк", "A/пасп"))
    for name, eps, a in rows:
        print("%-34s %12s %10.0f %8.3f"
              % (name, "—" if eps is None else "%.4e" % eps, a, a / a_pass))

    eps_poly = rate / (A_PROG * I_GAMMA)
    print("\nполином на 59,5 против нашего узла: %.4e против %.4e"
          " -> выше на %.1f %%" % (eps_poly, ours, 100 * (eps_poly / ours - 1)))
    print("наша кривая против штатной по узлам: %.3f" % (ours / EPS_LSRM))
    print("ПШПВ фита %.2f %% (%.1f кэВ) против измеренной точки Calibr.cfw"
          " 20,6 %% и полинома того же файла 16,4 %%"
          % (FWHM_FIT_PCT, FWHM_FIT_PCT / 100 * 58.38))

    csvio.write(
        os.path.join(RESULTS, "soft_edge_am241.csv"),
        ["method", "eps", "A_Bq", "ratio_to_passport"],
        [(n, "" if e is None else "%.6e" % e, "%.0f" % a,
          "%.4f" % (a / a_pass)) for n, e, a in rows],
        comments=[
            "Am-241 59,5 кэВ (чистая монолиния), точечная 5 см, поверка"
            " 2024. Паспорт 103100 Бк ±3 % приведён на дату измерения.",
            "Площадь снята после калибровки по ПШПВ; кривая в момент"
            " расчёта — наша (детектор «geant4» в свойствах спектра).",
            "Клетка «штатная кривая × СпектраЛайн» недостижима:"
            " переключение кривой не меняет результат — программа держит",
            "  эффективность в своей базе. Сравнение кривых — по узлам,"
            " своим алгоритмом.",
            "Вклад выбора кривой на этой линии (2,5 % по узлам) МЕНЬШЕ"
            " вариативности разметки между сеансами (3,9 % по площади).",
        ])
    print("таблица: %s" % os.path.join(RESULTS, "soft_edge_am241.csv"))
