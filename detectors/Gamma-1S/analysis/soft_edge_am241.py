"""Трек 2: мягкий край по чистой монолинии Am-241 59,5 кэВ (точечная 5 см).

Зачем именно Am-241. Это единственная в поверочном наборе линия ниже
100 кэВ, стоящая одиноко: ни бленда, ни каскада, ни цепочки. Всё, что
мешало сравнению на маринелли (разделение групп, выбор метода, поправка
на суммирование), здесь отсутствует, и остаётся чистый вопрос: сколько
поглотителя перед кристаллом.

Данные. Спектр поверки 2024, точечная 5 см; площадь и активность — из
сеанса СпектраЛайн оператора 29.07.2026 ПОСЛЕ калибровки по ПШПВ
(до неё хи-квадрат фита был 1995, после — 151; площадь при этом сдвинулась
на 3,8 %, что само по себе цена калибровки ширины на мягком крае).
Паспорт: Am-241 (номер источника в сертификате) = 103100 Бк ±3 % (сертификат ОСГИ), приведён
на дату измерения по T1/2 = 432,6 года.

Что сравнивается: активность, полученная из ОДНОЙ измеренной площади
четырьмя способами — полиномом СпектраЛайн, узлом штатной кривой .efr и
двумя нашими конвенциями площади (eps_net с вычетом полки, eps_gross без).
Разброс между конвенциями показывает, сколько в «дефиците мягкого края»
принадлежит способу взятия площади, а не поглотителю.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402

RESULTS = os.path.abspath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "results"))

A_PASS, D_PASS = 103100.0, 3.0      # Бк, % — паспорт 02.2019
T12_A = 432.6                        # лет
DT_YEARS = (2024 + 10.6 / 12) - (2019 + 2 / 12)
S_PEAK, T_LIVE, I_GAMMA = 2800000.0, 1811.475, 0.359
A_SL, D_SL = 105000.0, 13.0          # сеанс СпектраЛайн, штатная кривая
EPS_LSRM = 3.976771e-2               # узел .efr, точечная 5 см, 59,541


def our_eps(E=59.5):
    for ln in open(os.path.join(RESULTS, "eff_p5cm.csv"), encoding="utf-8"):
        if ln.startswith(("#", "E_keV")):
            continue
        f = ln.split(",")
        if abs(float(f[0]) - E) < 0.2:
            return float(f[1]), float(f[3])     # net, gross
    raise SystemExit("нет узла %g в eff_p5cm.csv" % E)


if __name__ == "__main__":
    a_pass = A_PASS * 0.5 ** (DT_YEARS / T12_A)
    rate = S_PEAK / T_LIVE
    net, gross = our_eps()
    rows = [("СпектраЛайн — полином штатной кривой", None, A_SL),
            ("узел штатной кривой .efr", EPS_LSRM, rate / (EPS_LSRM * I_GAMMA)),
            ("наша eps_net — с вычетом полки", net, rate / (net * I_GAMMA)),
            ("наша eps_gross — без вычета", gross, rate / (gross * I_GAMMA))]

    print("Am-241 59,5 кэВ, точечная 5 см, поверка 2024.")
    print("паспорт %.0f Бк ±%.0f %% (02.2019) -> на дату измерения %.0f Бк"
          % (A_PASS, D_PASS, a_pass))
    print("площадь %.0f имп за %.0f с живого -> %.1f имп/с в пике\n"
          % (S_PEAK, T_LIVE, rate))
    print("%-38s %12s %10s %8s" % ("способ", "eps", "A, Бк", "A/пасп"))
    for name, eps, a in rows:
        print("%-38s %12s %10.0f %8.3f"
              % (name, "—" if eps is None else "%.4e" % eps, a, a / a_pass))
    print("\nконвенция площади (gross/net) двигает результат на %.1f %%"
          % (100 * (net / gross - 1) * -1))
    print("полином против собственного узла: %.1f %%"
          % (100 * (A_SL / rows[1][2] - 1)))

    csvio.write(
        os.path.join(RESULTS, "soft_edge_am241.csv"),
        ["method", "eps", "A_Bq", "ratio_to_passport"],
        [(n, "" if e is None else "%.6e" % e, "%.0f" % a, "%.4f" % (a / a_pass))
         for n, e, a in rows],
        comments=[
            "Am-241 59,5 кэВ (чистая монолиния), точечная 5 см, поверка"
            " 2024; паспорт 103100 Бк ±3 % на 02.2019, приведён на дату"
            " измерения.",
            "Одна измеренная площадь, четыре способа получить активность:"
            " полином СпектраЛайн, узел .efr, наши eps_net и eps_gross.",
            "Площадь снята после калибровки по ПШПВ (хи-квадрат фита"
            " 1995 -> 151; площадь при этом сдвинулась на 3,8 %).",
        ])
    print("таблица: %s" % os.path.join(RESULTS, "soft_edge_am241.csv"))
