"""Мягкий край: Am-241 59,5 кэВ, точечная 5 см (Трек 2).

Чистая монолиния ниже 100 кэВ: ни бленда, ни каскада, ни цепочки, ни
самопоглощения — из всех наших данных это самое чистое место, где можно
спросить «сколько поглотителя перед кристаллом».

ПАРНЫЙ ПРОГОН ВЫПОЛНЕН (сеанс 30.07.2026). Прежнее утверждение — что
клетка «штатная кривая x СпектраЛайн» недостижима, поскольку переключение
кривой не меняет активность, — ОТМЕНЕНО: причиной была битая ссылка
EffFile в lsrm.cnf (файл лежал в Data\\Архив, путь указывал в Data). После
восстановления конфигурации из резервного слепка и укладки пары
.efa+.efr для геометрии «Точечная-5см» кривая выбирается штатным
образом: в свойствах спектра наша кривая видна отдельным детектором с
псевдонимом GEANT (редактор эффективности регистрирует построенную кривую
как отдельный прибор).

ЧТО ПОКАЗАЛ ПАРНЫЙ ПРОГОН. Обе кривые дают ОДНО И ТО ЖЕ отображаемое
значение 100000 Бк при неопределённости 18 %: программа округляет
результат по неопределённости, и различие узлов на этой линии (2,5 %)
лежит НИЖЕ РАЗРЕШЕНИЯ ВЫВОДА. Клетка формально закрыта, но
разделительной способности на 59,5 кэВ не имеет — сравнение кривых
средствами программы требует линии, где кривые расходятся сильнее
(на 2614,5 кэВ отношение узлов 1,28).

Оба прогона сеанса 30.07.2026 идут на параметрах обработки резервного
слепка (эпоха аттестации): ПШПВ фита 16,71 % против 20,75 % в сеансе
29.07.2026, площадь 2666669 против 2847995 (−6,4 %). Числа прежнего
сеанса приведены для сопоставления, но клеткой 2x2 не являются:
параметры обработки у них другие (см. config_drift.py).
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402

RESULTS = os.path.abspath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "results"))

A_PASS, D_PASS = 103100.0, 3.0       # Бк, % — паспорт источника, 02.2019
T12_A = 432.6                         # лет
DT_YEARS = (2024 + 10.0 / 12) - (2019 + 1.5 / 12)   # измерение 21.10.2024
I_GAMMA = 0.359

# Сеанс 30.07.2026, параметры обработки слепка, метод «Последовательно
# по зонам +». Площадь и скорость счёта — из окна «Параметры пиков».
S_PEAK, S_GROSS, T_LIVE = 2666669.0, 2988370.0, 1811.475
FWHM_FIT_PCT = 16.707                 # ПШПВ фита, % (58,52 кэВ)
A_SHOWN, D_SHOWN = 100000.0, 18.0     # обе кривые: одно и то же значение
# Сеанс 29.07.2026 — прежние (дрейфовавшие) параметры обработки
S_OLD, A_OLD, D_OLD, FWHM_OLD = 2847995.0, 106000.0, 14.0, 20.750

EPS_LSRM = 3.976771e-2                # узел штатной кривой, 59,541 кэВ


def our_eps(E=59.5):
    with open(os.path.join(RESULTS, "eff_p5cm.csv"), encoding="utf-8") as fh:
        for ln in fh:
            if ln.startswith(("#", "E_keV")):
                continue
            f = ln.split(",")
            if abs(float(f[0]) - E) < 0.2:
                return float(f[1])
    raise SystemExit("нет узла %g в eff_p5cm.csv" % E)


if __name__ == "__main__":
    a_pass = A_PASS * 0.5 ** (DT_YEARS / T12_A)
    rate = S_PEAK / T_LIVE
    ours = our_eps()
    rows = [
        ("программа (штатная кривая)", None, A_SHOWN),
        ("программа (наша кривая)", None, A_SHOWN),
        ("узел нашей кривой", ours, rate / (ours * I_GAMMA)),
        ("узел штатной кривой", EPS_LSRM, rate / (EPS_LSRM * I_GAMMA)),
    ]

    print("Am-241 59,5 кэВ, точечная 5 см, поверка 2024;"
          " сеанс 30.07.2026 на параметрах слепка.")
    print("паспорт %.0f Бк +-%.0f %% -> на дату измерения %.0f Бк"
          % (A_PASS, D_PASS, a_pass))
    print("площадь %.0f (полная %.0f) за %.1f с живого -> %.1f имп/с,"
          " ПШПВ фита %.2f %%\n"
          % (S_PEAK, S_GROSS, T_LIVE, rate, FWHM_FIT_PCT))
    print("%-30s %12s %10s %8s" % ("способ", "eps", "A, Бк", "A/пасп"))
    for name, eps, a in rows:
        print("%-30s %12s %10.0f %8.3f"
              % (name, "-" if eps is None else "%.4e" % eps, a, a / a_pass))

    print("\nРазрешение вывода. Отображаемые %.0f Бк при неопределённости"
          " %.0f %% округлены до двух значащих:" % (A_SHOWN, D_SHOWN))
    lo, hi = 95000.0, 105000.0
    print("  истинное значение в [%.0f, %.0f] Бк, то есть применённый eps"
          " в [%.4e, %.4e]" % (lo, hi, rate / (hi * I_GAMMA),
                               rate / (lo * I_GAMMA)))
    print("  оба узла (%.4e и %.4e) попадают внутрь -> различие кривых"
          " %.1f %% НЕ РАЗРЕШАЕТСЯ"
          % (ours, EPS_LSRM, 100 * abs(ours / EPS_LSRM - 1)))
    print("  для разделения нужна линия с большим расхождением узлов:"
          " на 2614,5 кэВ отношение 1,28")

    print("\nПрежний сеанс 29.07.2026 (другие параметры обработки):")
    print("  площадь %.0f (%+.1f %% к нынешней), ПШПВ фита %.2f %%,"
          " программа показывала %.0f Бк +-%.0f %%"
          % (S_OLD, 100 * (S_OLD / S_PEAK - 1), FWHM_OLD, A_OLD, D_OLD))
    print("  клеткой 2x2 не является: сопоставимы только прогоны на"
          " одних параметрах обработки")

    csvio.write(
        os.path.join(RESULTS, "soft_edge_am241.csv"),
        ["method", "eps", "A_Bq", "ratio_to_passport"],
        [(n, "" if e is None else "%.6e" % e, "%.0f" % a,
          "%.4f" % (a / a_pass)) for n, e, a in rows],
        comments=[
            "Am-241 59;5 кэВ (чистая монолиния); точечная 5 см; поверка"
            " 2024. Паспорт 103100 Бк +-3 % приведён на дату измерения.",
            "Сеанс 30.07.2026 на параметрах обработки резервного слепка"
            " (эпоха аттестации); площадь 2666669 за 1811;475 с живого.",
            "Парный прогон выполнен: кривая переключается штатно после"
            " починки ссылки EffFile и укладки пары .efa+.efr для",
            "  геометрии Точечная-5см; наша кривая видна отдельным"
            " детектором с псевдонимом GEANT.",
            "Обе кривые дают одно отображаемое значение 100000 Бк: при"
            " неопределённости 18 % различие узлов 2;5 % лежит ниже",
            "  разрешения вывода. Разделение требует линии 2614;5 кэВ"
            " (отношение узлов 1;28).",
        ])
    print("\nтаблица: %s" % os.path.join(RESULTS, "soft_edge_am241.csv"))
