"""Каскадное суммирование, измеренное моделью на самой себе.

ЗАЧЕМ. Величина поправки на истинное совпадение до сих пор бралась из
прогонов распада, но НЕ проверялась независимо: сходится ли она с тем, что
даёт та же геометрия без каскада. Проверка не обращается ни к ЛСРМ, ни к
паспорту — сравниваются два прогона одной модели, различающиеся только тем,
разыгран ли полный распад или единичный квант.

ФОРМУЛА И ЕДИНИЦЫ (здесь легко ошибиться на выход линии):

    TCC(E) = eps_decay(E) / ( p_g(E) * eps_mono(E) )

`eps_decay` — площадь пика на РАСПАД РОДИТЕЛЯ: в неё уже входит вероятность
испустить этот квант. `eps_mono` — эффективность на ИСПУЩЕННЫЙ КВАНТ: моно-
прогон испускает ровно тот квант, что и меряется, выхода линии там нет по
построению. Прямое отношение дало бы не TCC, а TCC*p_g, и для Cs-137
(p_g = 85 %) контроль показал бы 0,85 при полном отсутствии суммирования.
Выход берётся из emit-файла ТОГО ЖЕ прогона распада — фактический, разыгранный
Geant4, а не табличный: делится ровно то, что было домножено.

ДВЕ ЛИНИИ, И ОБЕ НУЖНЫ. Cs-137 661,657 кэВ — распад без каскада, суммирования
нет, ожидание TCC = 1,00. Это контроль МЕТОДА: отклонение здесь означает
ошибку не в физике, а в нормировке или в окнах площади. Co-60 1173,23 и
1332,49 кэВ — рабочая точка, где каскад из двух квантов даёт выбивание из
пика. Согласие на одной линии без другой не доказывает ничего: только Cs-137 —
не проверено, ловит ли метод суммирование вообще; только Co-60 — не отделить
суммирование от ошибки нормировки.

Моно-прогоны — свой тег `tcc5cm` (drivers/run_tcc_mono.py), геометрия та же,
что у `p5cm`. Совпадение двух тегов на 661,7 кэВ печатается как контроль.
"""
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import csvio  # noqa: E402

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from point_recalc import (
    BUILD, area_sim, eps_mono_point, load_hist,
)  # noqa: E402

MONO_TAG = "tcc5cm"

# (нуклид, метка прогона, линии, ожидание TCC, чем обосновано ожидание)
CASES = [
    ("Cs-137", "Cs137", [661.657], 1.00,
     "распад без каскада: суммироваться нечему"),
    ("Co-60", "Co60", [1173.23, 1332.49], 0.97,
     "каскад двух квантов, оценка по Хуртадо"),
]


def mono_with_err(tag, E):
    """Эффективность на квант и её статистическая погрешность.

    Площадь берётся УЗКИМ окном по неуширенному спектру (`broad=False`) — тем
    же способом, что и в `decay_area` ниже. См. пояснение там: уширение с
    полками здесь неприменимо.
    """
    import glob
    import re
    saf = os.path.join(BUILD, "grid", "%s_solidangle.txt" % tag)
    if not os.path.exists(saf):
        return None, None
    frac = float(open(saf).read().strip())
    best = None
    for p in glob.glob(os.path.join(BUILD, "grid", tag + "_E*.csv")):
        m = re.search(r"_E(\d+\.\d)\.csv$", p)
        if m and abs(float(m.group(1)) - E) < 1.0:
            best = p
    if not best:
        return None, None
    hist, N = load_hist(best)
    a = area_sim(hist, E, broad=False)
    if not N or a <= 0:
        return None, None
    return (a / N) * frac, (math.sqrt(a) / N) * frac


def decay_area(tag, E):
    """Эффективность на распад из прогона распада — узким окном.

    ПОЧЕМУ НЕ `eps_decay_5cm`. Штатная функция меряет площадь через
    `area_sim(broad=True)`: спектр уширяется до разрешения прибора, площадь
    берётся окном ±1 ПШПВ, фон — по полкам на ±1…2 ПШПВ. В `point_recalc` это
    правильно и намеренно: измеренный спектр разбирается теми же окнами, и
    систематика окна сокращается в отношении «счёт/эффективность».

    Здесь сокращать нечему, и способ становится неприменим. У Co-60 линии 1173
    и 1332 кэВ разнесены на 159 кэВ при ПШПВ около 70 кэВ, поэтому правая полка
    пика 1173 приходится на левый склон пика 1332, а левая полка пика 1332 — на
    правый склон пика 1173. Подложка завышается, площадь занижается. В моно-
    прогоне соседней линии нет по построению, его полки чистые — и дефект,
    вместо того чтобы сократиться, входит в отношение целиком. Первый прогон
    этой проверки дал так TCC = 0,70 при физически ожидаемых 0,97, то есть
    приписал каскаду тридцатипроцентную потерю, созданную полками. Это тот же
    механизм, что был разобран для измеренных спектров: полка фона встаёт на
    чужой пик.

    В модельном спектре уширение не нужно вовсе: пик полного поглощения стоит
    узкой линией, окно ±6 кэВ забирает его целиком, а полки на 10…30 кэВ ниже
    попадают на комптоновский континуум, свободный от соседних пиков.
    """
    p = os.path.join(BUILD, "p5_%s.csv" % tag)
    if not os.path.exists(p):
        return None, None
    hist, N = load_hist(p)
    a = area_sim(hist, E, broad=False)
    if not N or a <= 0:
        return None, None
    return a / N, math.sqrt(a) / N


def yield_with_err(tag, E):
    """Выход линии из emit-файла прогона распада и его погрешность."""
    p = os.path.join(BUILD, "p5_%s_emit.csv" % tag)
    if not os.path.exists(p):
        return None, None
    em, N = load_hist(p)
    tot = sum(c for e, c in em.items() if abs(e - E) <= 2.0)
    if not N or tot <= 50:
        return None, None
    return tot / N, math.sqrt(tot) / N


def main():
    print("Каскадное суммирование: прогон распада против моноэнергий,")
    print("та же геометрия, ЛСРМ и паспорт не участвуют.\n")
    print("%-8s %9s %11s %8s %11s %9s %7s"
          % ("нуклид", "E, кэВ", "eps_распад", "выход", "eps_моно",
             "TCC", "ожид."))

    rows, verdicts = [], []
    for nuc, tag, lines, expect, why in CASES:
        got = []
        for E in lines:
            ed, d_ed = decay_area(tag, E)
            pg, d_pg = yield_with_err(tag, E)
            em, d_em = mono_with_err(MONO_TAG, E)
            if not ed or not pg or not em:
                print("%-8s %9.3f   нет данных (прогон не посчитан)"
                      % (nuc, E))
                continue
            tcc = ed / (pg * em)
            # относительные погрешности складываются квадратично
            rel = math.sqrt((d_ed / ed) ** 2 + (d_pg / pg) ** 2
                            + (d_em / em) ** 2)
            d_tcc = tcc * rel
            print("%-8s %9.3f %11.4e %8.4f %11.4e %6.3f±%.3f %7.2f"
                  % (nuc, E, ed, pg, em, tcc, d_tcc, expect))
            got.append((tcc, d_tcc))
            rows.append((nuc, "%.3f" % E, "%.5e" % ed, "%.5f" % pg,
                         "%.5e" % em, "%.4f" % tcc, "%.4f" % d_tcc,
                         "%.2f" % expect))
        if got:
            # среднее по линиям нуклида, взвешенное обратно дисперсии
            w = [1.0 / (d * d) for _, d in got]
            avg = sum(t * wi for (t, _), wi in zip(got, w)) / sum(w)
            d_avg = math.sqrt(1.0 / sum(w))
            dev = (avg - expect) / d_avg if d_avg > 0 else 0.0
            verdicts.append((nuc, avg, d_avg, expect, dev, why))

    print("\n=== СВОДКА ===")
    print("%-8s %14s %8s %9s  %s"
          % ("нуклид", "TCC", "ожид.", "откл., σ", "чем обосновано ожидание"))
    for nuc, avg, d_avg, expect, dev, why in verdicts:
        print("%-8s %8.3f±%.3f %8.2f %+9.1f  %s"
              % (nuc, avg, d_avg, expect, dev, why))

    # Контроль воспроизводимости: та же энергия в двух независимых тегах.
    a, _ = mono_with_err(MONO_TAG, 661.657)
    b = eps_mono_point("p5cm", 661.657)
    if a and b:
        print("\nконтроль тегов на 661,657 кэВ: %s %.4e против p5cm %.4e,"
              " расхождение %+.2f %%" % (MONO_TAG, a, b, 100.0 * (a - b) / b))

    if rows:
        op = os.path.abspath(os.path.join(
            os.path.dirname(os.path.abspath(__file__)), "..", "results",
            "tcc_selfcheck.csv"))
        csvio.write(
            op,
            ["nuclide", "E_keV", "eps_decay", "yield", "eps_mono", "tcc",
             "d_tcc", "expected"],
            rows,
            comments=[
                "Поправка на истинное совпадение, измеренная моделью на самой"
                " себе: прогон полного распада против моноэнергий.",
                "TCC = eps_decay / (yield * eps_mono). Деление на выход"
                " обязательно: eps_decay считается НА РАСПАД и уже содержит"
                " выход,",
                "  а eps_mono — на испущенный квант. Без деления Cs-137 дал бы"
                " 0,85 вместо 1,00 при полном отсутствии суммирования.",
                "Выход берётся из emit-файла того же прогона распада —"
                " фактический, а не табличный.",
                "Cs-137 — контроль метода (каскада нет), Co-60 — рабочая"
                " точка.",
            ])
        print("\nсводка: %s" % op)


if __name__ == "__main__":
    main()
