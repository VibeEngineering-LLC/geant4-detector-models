"""Каскадное суммирование, измеренное моделью на самой себе.

ЗАЧЕМ. Величина поправки на истинное совпадение до сих пор бралась из
прогонов распада, но НЕ проверялась независимо: сходится ли она с тем, что
даёт та же геометрия без каскада. Проверка не обращается ни к ЛСРМ, ни к
паспорту — сравниваются два прогона одной модели, различающиеся только тем,
разыгран ли полный распад или единичный квант.

ФОРМУЛА И ЕДИНИЦЫ (здесь легко ошибиться на выход линии):

    TCC(E) = eps_decay(E) / ( p_g(E) * eps_mono(E) )

`eps_decay` — площадь пика на РАСПАД РОДИТЕЛЯ: в неё уже входит вероятность
испустить этот квант. `eps_mono` — эффективность на ИСПУЩЕННЫЙ КВАНТ: моно-
прогон испускает ровно тот квант, что и меряется, выхода линии там нет по
построению. Прямое отношение дало бы не TCC, а TCC*p_g, и для Cs-137
(p_g = 85 %) контроль показал бы 0,85 при полном отсутствии суммирования.
Выход берётся из emit-файла ТОГО ЖЕ прогона распада — фактический, разыгранный
Geant4, а не табличный: делится ровно то, что было домножено.

ДВЕ ЛИНИИ, И ОБЕ НУЖНЫ. Cs-137 661,657 кэВ — распад без каскада, суммирования
нет, ожидание TCC = 1,00. Это контроль МЕТОДА: отклонение здесь означает
ошибку не в физике, а в нормировке или в окнах площади. Co-60 1173,23 и
1332,49 кэВ — рабочая точка, где каскад из двух квантов даёт выбивание из
пика. Согласие на одной линии без другой не доказывает ничего: только Cs-137 —
не проверено, ловит ли метод суммирование вообще; только Co-60 — не отделить
суммирование от ошибки нормировки.

Моно-прогоны — свой тег `tcc5cm` (drivers/run_tcc_mono.py), геометрия та же,
что у `p5cm`. Совпадение двух тегов на 661,7 кэВ печатается как контроль.
"""
