// Спектрометр ГАММА-1С (ЗАО НПЦ «АСПЕКТ», Дубна, ДЦКИ.412131.001):
// устройство детектирования УДС-ГЦ-63х63-USB в свинцовом экране-защите
// «Экран-1СГ» ДЦКИ.305179.038.
//
// МИРОВАЯ СИСТЕМА КООРДИНАТ: начало — в ЦЕНТРЕ КРИСТАЛЛА NaI.
// Ось Z — ось детектора, +Z ВВЕРХ, в сторону входного торца (крышки) и пробы;
// хвост с ФЭУ уходит в -Z. Так же стоит прибор в установке: головка смотрит
// вверх, сосуд Маринелли надевается на неё сверху.
//
// Происхождение каждого числа помечено в G1SDetector.cc.
#pragma once
#include "G4VUserDetectorConstruction.hh"
#include "globals.hh"

class G4LogicalVolume;
class G4Material;

// --- Устройство детектирования УДС-ГЦ-63х63 ---------------------------------
// Все размеры в мм, ЧЕРТЁЖ = «Чертеж 63х63.pdf» (БДС-Г, УДС-Г-63х63).
struct HeadGeom {
  double cryDia = 63.00;   // ЧЕРТЁЖ: NaI(Tl) 63x63 мм
  double cryLen = 63.00;

  // Отражатель MgO: по чертежу радиально 3,65 мм, по входному торцу 6 мм.
  double mgoRad  = 3.65;   // ЧЕРТЁЖ
  double mgoFace = 6.00;   // ЧЕРТЁЖ
  double mgoBack = 3.00;   // ДОПУЩЕНИЕ: со стороны световода отражателя нет,
                           //   но торец банки не вплотную к кристаллу

  double alCan   = 0.50;   // ЧЕРТЁЖ: «Al» — герметичная банка кристалла
  double rubber2 = 2.00;   // ЧЕРТЁЖ: резина 2 мм — амортизатор, ТОЛЬКО по боку
  double alCase  = 1.50;   // ЧЕРТЁЖ: наружный корпус Al по боку

  // СТЕК ВХОДНОГО ТОРЦА — уточнён оператором по чертежу (28.07.2026),
  // снаружи внутрь: Al 2,0 / воздух 1,0 / банка Al 0,5 / MgO 6,0 / кристалл.
  // РЕЗИНЫ НА ТОРЦЕ НЕТ ВОВСЕ (прежнее чтение ставило туда протектор 1 мм и
  // амортизатор 2 мм — это была ошибка чтения подписей 0,5/1/2). Наружная
  // плоскость торца, на которую садится дно колодца маринелли и от которой
  // меряются 5/25 см, — крышка Al: z = 31,5+6+0,5+1+2 = 41,0.
  double alCaseFace = 2.00;  // ЧЕРТЁЖ: крышка Al входного торца
  double faceAir    = 1.00;  // ЧЕРТЁЖ+ОПЕРАТОР: воздух банка<->крышка, торец

  // ОПЕРАТОР (29.07.2026), правка чтения чертежа: «резина 1 мм» — НЕ
  // наружная обёртка по боку (прежнее чтение), а КОЛЬЦЕВАЯ ПРОКЛАДКА С
  // ТОРЦА: стоит в воздушном зазоре банка<->крышка по периферии и фиксирует
  // банку от осевого смещения. «Резина 2 мм» — боковой уплотнитель-фиксатор
  // (радиально, как и было в модели). Наружная поверхность корпуса — голый
  // Al Ø78,3, никакой обёртки; это снимает конфликт посадки маринелли #103.
  double faceSeal  = 1.00;  // толщина кольца = зазор faceAir
  double faceSealW = 5.50;  // ОПЕРАТОР: разница радиусов кольца 5-6 мм

  // САМОПРОВЕРКА: радиально 63 + 2*(3,65+0,5+2+1,5) = 78,3 против Ø78 —
  // сходится ИМЕННО без наружной обёртки; по оси торцевая колонна
  // 6+0,5+1+2 = 9,5 мм.

  // Насыпная плотность отражателя MgO. Величина управляет мягким краем
  // кривой: 6 мм MgO (толщина — ЧЕРТЁЖ, не трогается) на 59,5 кэВ
  // пропускают 71 % при ρ=2,0, 91 % при ρ=0,8.
  //
  // 28.07.2026, РЕШЕНИЕ ОПЕРАТОРА (через аудитора). Первая сверка (ρ=2,0,
  // взятое по Mendes et al., Braz. J. Rad. Sci. 07-03A (2019), Table 1) не
  // закрывала мягкий дефицит. Аудитор нашёл, что для НАСЫПНОГО ПРЕССОВАННОГО
  // порошкового отражателя NaI(Tl) физический диапазон — 0,5–1,2 г/см³,
  // типично 0,7–1,0 (диффузное отражение 95–99 % на 400–450 нм работает
  // ИМЕННО за счёт пористости порошка; 3,58 — плотность сплошного/
  // спечённого MgO, к отражателю не относится). Источники: Mostafa et al.,
  // Appl. Radiat. Isot. (2022) S0969806X22003681; аналогично
  // S0969806X21002310, S0969804317307479 — там же описана и практика
  // КАЛИБРОВКИ плотности отражателя по отношению двух мягких линий.
  //
  // Эта практика ОТКЛОНЕНА оператором намеренно: подогнанная по мягким
  // линиям плотность впитает в себя всё прочее неверное в торце (толщину
  // Al, воздух, чего нет в чертеже) и станет эффективной массовой толщиной
  // под чужим именем — согласие на тех же линиях перестанет быть проверкой.
  // Берём физическое значение из середины диапазона, ρ=0,8, и проверяем
  // РЕЗУЛЬТАТ, а не подгоняем его.
  //
  // Прежний диапазон скана «1,5–2,4» (см. историю правок) был подобран без
  // источника и целиком лежал ВЫШЕ физической области порошка — поэтому
  // тогдашний вывод «плотность не объясняет мягкий дефицит» был неверен:
  // скан не заходил туда, где находится ответ.
  double mgoDensity = 0.80;

  double pmtDia   = 71.00;  // ЧЕРТЁЖ: Ø71 — баллон ФЭУ
  double pmtGlass = 1.50;   // ДОПУЩЕНИЕ: стенка баллона
  double pmtLen   = 120.00; // ДОПУЩЕНИЕ: длина баллона до делителя
  // ОПЕРАТОР (28.07.2026): между кристаллом и ФЭУ НЕТ ни зазора, ни толстого
  // световода — тонкий слой ОПТИЧЕСКОГО ГЕЛЯ. Толщина слоя — допущение
  // (типичные 0,3–1 мм); стояло 5 мм стекла из прежнего допущения.
  double window   = 0.50;   // оптический гель кристалл->ФЭУ (толщина — допущ.)
  double unitLen  = 315.00; // ЧЕРТЁЖ: полная длина устройства
};

// --- Экран-защита «Экран-1СГ» -----------------------------------------------
// Материалы и толщина свинца — ЗАДАНИЕ ОПЕРАТОРА: сталь 3 мм, свинец 50 мм,
// кадмий, медь. Толщины Cd и Cu оператором не заданы; приняты по 1 мм
// (Будыка: Cd 0,5–1 мм, Cu 1–2 мм). Размер полости подобран так, чтобы масса
// свинца сошлась с паспортной (см. G1SDetector.cc, ПРОВЕРКА ПО МАССАМ).
struct ShieldGeom {
  double cavityDia = 200.00;  // ПОДБОР по массе свинца
  double cavityH   = 190.00;  // ПОДБОР по массе свинца
  double cu = 1.00;           // ДОПУЩЕНИЕ (паспорт: медь >= 1,6 кг на прибор)
  double cd = 1.00;           // ДОПУЩЕНИЕ (паспорт: кадмий >= 1,2 кг)
  double pb = 50.00;          // ЗАДАНИЕ ОПЕРАТОРА
  double steel = 3.00;        // ЗАДАНИЕ ОПЕРАТОРА
  double boreDia = 82.00;     // проход под головку Ø78,3 с зазором
  // Днище полости лежит на уровне z = cavityFloorZ относительно центра
  // кристалла: головка входит в полость снизу.
  double floorFromCryCentre = -45.00;  // ДОПУЩЕНИЕ: торец крышки на 31,5+11,5
                                       //   = 43 мм выше центра кристалла,
                                       //   днище полости — на 45 мм ниже него
  bool lidClosed = true;      // крышка экрана: для точечной 25 см она открыта
};

// --- Сосуд Маринелли 1 л ------------------------------------------------------
// Габариты — ЛСРМ «Прецизионные измерения», с. 11, таблица измерительных кювет:
// Маринелли 1,0 л — внешние габариты Ø150, H = 110, d_эфф табличное 26(2) мм.
// (.efa ЭТОГО экземпляра детектора даёт Thick = 31(2) — сверяем с обоими.)
// Сосуд выше номинального объёма: проба 1000 мл его НЕ заполняет доверху,
// уровень засыпки вычисляется в BuildVessel из целевого объёма.
struct VesselGeom {
  G4String name   = "marinelli";
  double wall     = 2.00;    // ДОПУЩЕНИЕ: полипропилен, стандартная стенка
  // Конфликт посадки #103 СНЯТ правкой чтения чертежа (29.07.2026):
  // наружной резиновой обёртки не существует («резина 1 мм» — торцевое
  // кольцо, см. HeadGeom::faceSeal), корпус голый Al Ø78,3, и колодец Ø80
  // надевается с зазором 0,85 мм. Оператор подтвердил: реальный сосуд
  // садится до упора, дно колодца на торце.
  double wellInR  = 40.00;   // колодец Ø80: корпус Ø78,3 + зазор посадки.
                             //   wellInR <= 0 — колодца нет (Дента, Петри)
  double wellDepth = 74.00;  // ДОПУЩЕНИЕ: колодец садится на всю головку
  double outerR   = 75.00;   // ЛСРМ табл.: внешний Ø150
  double height   = 110.00;  // ЛСРМ табл.: H = 110
  double sampleCm3 = 1000.0; // целевой объём пробы, задаёт уровень засыпки
  double sampleDensity = 1.60;        // .efa: ОИСН-16
  G4String sampleMatrix = "OISN16";   // .efa: состав по массе, см. MakeMatrix

  // marinelli | denta | petri. Габариты — таблица измерительных кювет ЛСРМ
  // («Прецизионные измерения», с. 11), объёмы и матрица — .efa комплекта.
  static VesselGeom Preset(const G4String& n);
};

class G1SDetector : public G4VUserDetectorConstruction {
public:
  G1SDetector() = default;
  G4VPhysicalVolume* Construct() override;

  HeadGeom   fHead;
  ShieldGeom fShield;
  VesselGeom fVessel;
  bool fWithShield = true;
  bool fWithVessel = false;

  double fSampleVolumeCm3 = 0.0;   // считается по построенному телу
  bool fSampleFits = true;         // уровень засыпки не выше крышки
  G4LogicalVolume* fSampleLV = nullptr;

  G4LogicalVolume* fCrystalLV = nullptr;

  // Матрица пробы. Отдельный статический метод — чтобы mucalc считал
  // коэффициент ослабления по ТОЙ ЖЕ смеси, что идёт в транспорт.
  static G4Material* MakeMatrix(const G4String& matrix, double rho,
                                const G4String& g4name = "OISN16");

  // Печатает массы построенных тел — свинец, кадмий, медь, алюминий, NaI.
  // Служит проверкой геометрии против таблицы 2.2 паспорта.
  void ReportMasses() const;

private:
  void DefineMaterials();
  void BuildHead(G4LogicalVolume* world);
  void BuildShield(G4LogicalVolume* world);
  void BuildVessel(G4LogicalVolume* world);   // Маринелли, с колодцем
  void BuildCup(G4LogicalVolume* world);      // Дента и Петри, плоские

  G4LogicalVolume* fPbLV = nullptr;
  G4LogicalVolume* fCdLV = nullptr;
  G4LogicalVolume* fCuLV = nullptr;
  G4LogicalVolume* fSteelLV = nullptr;
};
