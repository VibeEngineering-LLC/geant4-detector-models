// «Экран-1СГ» ДЦКИ.305179.038.
//
// МИРОВАЯ СИСТЕМА КООРДИНАТ: начало — в ЦЕНТРЕ КРИСТАЛЛА NaI.
// Ось Z — ось детектора, +Z ВВЕРХ, в сторону входного торца (крышки) и пробы;
// хвост с ФЭУ уходит в -Z. Так же стоит прибор в установке: головка смотрит
// вверх, сосуд Маринелли надевается на неё сверху.
//
// Происхождение каждого числа помечено в G1SDetector.cc.
