// --- Устройство детектирования УДС-ГЦ-63х63 ---------------------------------
// Все размеры в мм, ЧЕРТЁЖ = «Чертеж 63х63.pdf» (БДС-Г, УДС-Г-63х63).
struct HeadGeom {
  double cryDia = 63.00;   // ЧЕРТЁЖ: NaI(Tl) 63x63 мм
  double cryLen = 63.00;

  // Отражатель MgO: по чертежу радиально 3,65 мм, по входному торцу 6 мм.
  double mgoRad  = 3.65;   // ЧЕРТЁЖ
  double mgoFace = 6.00;   // ЧЕРТЁЖ
  double mgoBack = 3.00;   // ДОПУЩЕНИЕ: со стороны световода отражателя нет,
                           //   но торец банки не вплотную к кристаллу

  double alCan   = 0.50;   // ЧЕРТЁЖ: «Al» — герметичная банка кристалла
  double rubber2 = 2.00;   // ЧЕРТЁЖ: резина 2 мм — амортизатор, ТОЛЬКО по боку
  double alCase  = 1.50;   // ЧЕРТЁЖ: наружный корпус Al по боку

  // СТЕК ВХОДНОГО ТОРЦА — уточнён оператором по чертежу (28.07.2026),
  // снаружи внутрь: Al 2,0 / воздух 1,0 / банка Al 0,5 / MgO 6,0 / кристалл.
  // РЕЗИНЫ НА ТОРЦЕ НЕТ ВОВСЕ (прежнее чтение ставило туда протектор 1 мм и
  // амортизатор 2 мм — это была ошибка чтения подписей 0,5/1/2). Наружная
  // плоскость торца, на которую садится дно колодца маринелли и от которой
  // меряются 5/25 см, — крышка Al: z = 31,5+6+0,5+1+2 = 41,0.
  double alCaseFace = 2.00;  // ЧЕРТЁЖ: крышка Al входного торца
  double faceAir    = 1.00;  // ЧЕРТЁЖ+ОПЕРАТОР: воздух банка<->крышка, торец

  // ОПЕРАТОР (29.07.2026), правка чтения чертежа: «резина 1 мм» — НЕ
  // наружная обёртка по боку (прежнее чтение), а КОЛЬЦЕВАЯ ПРОКЛАДКА С
  // ТОРЦА: стоит в воздушном зазоре банка<->крышка по периферии и фиксирует
  // банку от осевого смещения. «Резина 2 мм» — боковой уплотнитель-фиксатор
  // (радиально, как и было в модели). Наружная поверхность корпуса — голый
  // Al Ø78,3, никакой обёртки; это снимает конфликт посадки маринелли задача 103.
  double faceSeal  = 1.00;  // толщина кольца = зазор faceAir
  double faceSealW = 5.50;  // ОПЕРАТОР: разница радиусов кольца 5-6 мм

  // САМОПРОВЕРКА: радиально 63 + 2*(3,65+0,5+2+1,5) = 78,3 против Ø78 —
  // сходится ИМЕННО без наружной обёртки; по оси торцевая колонна
  // 6+0,5+1+2 = 9,5 мм.

  // Насыпная плотность отражателя MgO. Величина управляет мягким краем
  // кривой: 6 мм MgO (толщина — ЧЕРТЁЖ, не трогается) на 59,5 кэВ
  // пропускают 71 % при ρ=2,0, 91 % при ρ=0,8.
  //
  // 28.07.2026, РЕШЕНИЕ ОПЕРАТОРА (через аудитора). Первая сверка (ρ=2,0,
  // взятое по Mendes et al., Braz. J. Rad. Sci. 07-03A (2019), Table 1) не
  // закрывала мягкий дефицит. Аудитор нашёл, что для НАСЫПНОГО ПРЕССОВАННОГО
  // порошкового отражателя NaI(Tl) физический диапазон — 0,5–1,2 г/см³,
  // типично 0,7–1,0 (диффузное отражение 95–99 % на 400–450 нм работает
  // ИМЕННО за счёт пористости порошка; 3,58 — плотность сплошного/
  // спечённого MgO, к отражателю не относится). Источники: Mostafa et al.,
  // Appl. Radiat. Isot. (2022) S0969806X22003681; аналогично
  // S0969806X21002310, S0969804317307479 — там же описана и практика
  // КАЛИБРОВКИ плотности отражателя по отношению двух мягких линий.
  //
  // Эта практика ОТКЛОНЕНА оператором намеренно: подогнанная по мягким
  // линиям плотность впитает в себя всё прочее неверное в торце (толщину
  // Al, воздух, чего нет в чертеже) и станет эффективной массовой толщиной
  // под чужим именем — согласие на тех же линиях перестанет быть проверкой.
  // Берём физическое значение из середины диапазона, ρ=0,8, и проверяем
  // РЕЗУЛЬТАТ, а не подгоняем его.
  //
  // Прежний диапазон скана «1,5–2,4» (см. историю правок) был подобран без
  // источника и целиком лежал ВЫШЕ физической области порошка — поэтому
  // тогдашний вывод «плотность не объясняет мягкий дефицит» был неверен:
  // скан не заходил туда, где находится ответ.
  double mgoDensity = 0.80;

  double pmtDia   = 71.00;  // ЧЕРТЁЖ: Ø71 — баллон ФЭУ
  double pmtGlass = 1.50;   // ДОПУЩЕНИЕ: стенка баллона
  double pmtLen   = 120.00; // ДОПУЩЕНИЕ: длина баллона до делителя
  // ОПЕРАТОР (28.07.2026): между кристаллом и ФЭУ НЕТ ни зазора, ни толстого
  // световода — тонкий слой ОПТИЧЕСКОГО ГЕЛЯ. Толщина слоя — допущение
  // (типичные 0,3–1 мм); стояло 5 мм стекла из прежнего допущения.
  double window   = 0.50;   // оптический гель кристалл->ФЭУ (толщина — допущ.)
  double unitLen  = 315.00; // ЧЕРТЁЖ: полная длина устройства
};

// --- Экран-защита «Экран-1СГ» -----------------------------------------------
// ФОРМА — рисунок 1.1 «Общий вид спектрометра» руководства по эксплуатации
// (стр. 7, продольный разрез установки на тележке). Рисунок размеров НЕ несёт,
// поэтому снят промером: контурные линии найдены суммированием черноты по
// полосам строк и столбцов растра 2480x3507 (скан 300 dpi), координаты границ
// переведены в мм единым масштабом. Метод — скилл photo-metrology.
//
// МАСШТАБ задан ДЛИНОЙ ДЕТЕКТОРА 315 мм (директива оператора «отталкивайся от
// размеров детектора»): устройство на разрезе занимает 383,9 px по оси, отсюда
// 1,2187 px/мм. Ноль оси z — центр кристалла, привязка — наружная плоскость
// торца головки z = +41 (y = 568,1 px).
//
// ПОЧЕМУ ИМЕННО ДЛИНА, А НЕ ДИАМЕТР. Диаметр устройства на рисунке НЕ
// РАЗРЕШАЕТСЯ: там, где детектор стоит в канале, его контур и стенка канала
// слиты в одну линию толщиной 14-18 px, а внутри контура идёт точечная заливка
// без чёткого края. Кандидаты на «диаметр» разбросаны от 77 до 112 px, то есть
// от Ø63 до Ø92 при любом разумном масштабе, — величина такой ширины масштаб
// не задаёт. Длина же меряется между двумя чёткими торцами и даёт базу втрое
// больше. (Прежняя редакция этого комментария утверждала, что рисунок
// «нарисован на 14 % тоньше»; это был вывод из ОДНОГО произвольно выбранного
// кандидата и снят.)
//
// НЕЗАВИСИМАЯ ПРОВЕРКА — паспортные массы, и они же ограничивают масштаб с
// двух сторон, потому что масса идёт как s^-3:
//   свинца «не менее 165 кг» (табл. 2.2 паспорта)   ->  s <= 1,2508;
//   экран-защита «не более 231 кг» (РЭ, п. 1.2.14)  ->  s >= 1,1927.
// Масштаб по длине детектора, 1,2187, лежит внутри этого окна почти посередине.
// Модель на нём даёт свинец 178,4 кг и экран-защиту 216,5 кг без тележки.
//
// ОТСЮДА ЖЕ ТОЧНОСТЬ ВСЕЙ ГЕОМЕТРИИ: окно 1,1927...1,2508 — это +-2,4 % по
// любому линейному размеру. Толщина свинца 45 мм означает 45 +- 1 мм.
// Задававшиеся ранее «50 мм» потребовали бы s = 1,171: экран-защита вышла бы
// 244 кг против паспортных «не более 231», поэтому 50 мм с паспортом не
// сходятся и в модель не берутся.
//
// ЧТО ЭТО МЕНЯЕТ ПРОТИВ ПРЕЖНЕЙ МОДЕЛИ. Прежде защита была ОДНИМ цилиндром
// с полостью Ø200 x 190 и ровным слоем свинца 50 мм, а сама полость
// подбиралась под паспортную массу — то есть подгонялись ОБА параметра сразу.
// На разрезе защита ступенчатая: широкий блок с полостью под сосуд сверху,
// узкая свинцовая шейка с каналом под головку снизу, стальной кожух по всей
// высоте. Подгоночными остались только толщины вкладышей Cu и Cd.
//
// САМОПРОВЕРКА ФОРМЫ (не закладывалась, получилась сама): в полость высотой
// 127,6 мм сосуд Маринелли 1 л высотой 112 мм, надетый на головку, входит с
// зазором 10 мм снизу и 5 мм сверху. Полость под этот сосуд и сделана.
struct ShieldGeom {
  // Уровни по оси z (мм от центра кристалла), сверху вниз
  double zLidTop   =  163.7;   // верх крышки
  double zLidBot   =  105.7;   // низ диска крышки
  double zBlockTop =  100.7;   // верх свинцового блока
  double zCeil     =   95.2;   // потолок полости (низ пробки крышки)
  double zFloor    =  -32.4;   // полка полости, на неё выходит шейка
  double zLedge1   =  -68.1;   // низ широкого блока
  double zLedge2   = -163.2;   // ступень шейки
  double zBottom   = -414.2;   // низ свинца (палуба тележки)

  // Радиусы (мм)
  double rPbOut = 139.2;       // свинец блока и крышки снаружи
  double rCav   =  91.1;       // полость (по вкладышу, см. cu/cd)
  double rNeck1 =  89.9;       // шейка выше второй ступени
  double rNeck2 =  79.6;       // шейка ниже второй ступени
  double rBore  =  45.3;       // канал под головку Ø78,3 — зазор 6,2 на сторону
  double steel  =   7.5;       // стальной кожух

  // Свинцовая пробка: закрывает канал снизу, экранирует детектор с хвоста.
  // На разрезе — заштрихованный блок в канале, y 1071,9...1135,1 px, отсюда
  // верх на z = -372,4 и толщина 51,9 мм. Привязка идёт по ВЕРХУ: это рабочая
  // поверхность, а низ пробки попадает в толстую линию палубы (y 1123...1141),
  // где разрешение растра уже не даёт различить пробку, палубу и низ шейки.
  // Диаметр принят по каналу. Фланец (буртик, видный на фотографии пробки)
  // НЕ моделируется: он лежит вне канала и на пути от пробы к кристаллу не
  // стоит. Между хвостом устройства (z = -274) и верхом пробки остаётся 98 мм
  // канала — там разъём и кабель, они тоже не моделируются.
  double zPlugTop  = -372.4;
  double plugThick =   51.9;

  // Вкладыши. На разрезе не показаны — единственные подгоночные величины,
  // берутся из паспорта (таблица 2.2, «не менее»): медь 1,6 кг, кадмий 1,2 кг.
  // При площади полости 1,19e5 мм² 1 мм меди весит 1,06 кг, 1 мм кадмия
  // 1,03 кг, отсюда 1,5 и 1,2 мм. Обе величины лежат в обычном диапазоне
  // (Будыка: Cd 0,5–1 мм, Cu 1–2 мм). Порядок от полости наружу: Cu -> Cd -> Pb.
  double cu = 1.50;
  double cd = 1.20;

  bool lidClosed = true;       // крышка экрана: для точечной 25 см она открыта

  // ЧЕГО В МОДЕЛИ НЕТ: тележка с колёсами и её стальная палуба (ниже zBottom,
  // экранирована свинцом шейки), петля и подъёмный механизм крышки слева,
  // кабельный ввод, столик под сосуд. Ввод и петля — сквозные нарушения
  // сплошности свинца, их влияние не оценено.
};

// --- Сосуд Маринелли 1 л ------------------------------------------------------
// Габариты — ЧЕРТЁЖ ИЗГОТОВИТЕЛЯ источников (лист «Сосуд Маринелли 1л»,
// каталог ОМАСН, прислан оператором 08.08.2026): наружный Ø154 (Ø155,5 по
// буртику), высота 112, колодец Ø97 глубиной 65, над колодцем 24 мм до
// внутренней крышки. Толщина стенки на чертеже не проставлена — принято 2 мм
// по штриховке, ДОПУЩЕНИЕ.
//
// ЧТО БЫЛО ДО ЭТОГО И ПОЧЕМУ ЗАМЕНЕНО. Прежде габариты брались из таблицы
// ЛСРМ («Прецизионные измерения», с. 11; она же «Алгоритмические основы»,
// табл. 8-2): «Сосуд типа Маринелли, 1.0 л, внешние габариты Ø150 H=110».
// Диаметра колодца в той таблице НЕТ ВОВСЕ — Ø80 был нашим допущением
// «колодец по головке Ø78,3». Чертёж даёт Ø97, то есть допущение промахнулось
// на 17 мм по диаметру и на 9 мм по глубине.
//
// ОТДЕЛЬНО — про d_эфф, на которое опиралась прежняя сверка. Это НЕ размер
// сосуда, а подгоночный параметр модели самопоглощения ЛСРМ: «любой объёмный
// источник гамма-излучения можно представить в виде точечного источника за
// поглощающей пластинкой», d_эфф — толщина этой пластинки (§8.5.2). ЛСРМ
// прямо пишет, что её «подбирают так, чтобы кривые эффективности при
// пересчёте на материал совпали». Решающее доказательство — их же таблицы:
// для ОДНОГО сосуда Маринелли 1 л при одних внешних габаритах Ø150 H=110
// табл. 8-1 («старый» способ, до SpectraLine 1.4) даёт d_эфф = 17(2) мм,
// табл. 8-2 («новый» способ) — 26(2) мм. Размер от смены формулы не
// меняется, подгоночный параметр — меняется. У .efa этого экземпляра
// Thick = 31(2) мм, то есть своя подгонка под конкретный прибор.
// Прежний комментарий трактовал Thick как геометрическую толщину кольца
// пробы и объявлял совпадение 31,00 против 31,2 подтверждением геометрии.
// Это было сравнение нашей модели с чужой моделью, а не с чертежом.
//
// Сосуд выше номинального объёма: проба 1000 мл его НЕ заполняет доверху,
// уровень засыпки вычисляется в BuildVessel из целевого объёма.
struct VesselGeom {
  G4String name   = "marinelli";
  double wall     = 2.00;    // ДОПУЩЕНИЕ: полипропилен, на чертеже не задана
  // Посадка. Наружной резиновой обёртки на головке нет («резина 1 мм» —
  // торцевое кольцо, см. HeadGeom::faceSeal), корпус голый Al Ø78,3.
  // Колодец Ø97 головку НЕ обхватывает: зазор 9,35 мм на сторону. Оператор
  // подтверждал, что сосуд садится до упора и дно колодца лежит на торце, —
  // это условие сохранено, но РАДИАЛЬНОЕ положение сосуда чертежом не
  // задаётся и здесь принято соосным. ДОПУЩЕНИЕ, влияет на телесный угол.
  double wellInR  = 48.50;   // чертёж: колодец Ø97 (полость).
                             //   wellInR <= 0 — колодца нет (Дента, Петри)
  double wellDepth = 65.00;  // чертёж: глубина колодца 65
  double outerR   = 77.00;   // чертёж: наружный Ø154
  double height   = 112.00;  // чертёж: H = 112
  double sampleCm3 = 1000.0; // целевой объём пробы, задаёт уровень засыпки
  double sampleDensity = 1.60;        // .efa: ОИСН-16
  G4String sampleMatrix = "OISN16";   // .efa: состав по массе, см. MakeMatrix

  // marinelli | denta | petri. Габариты — таблица измерительных кювет ЛСРМ
  // («Прецизионные измерения», с. 11), объёмы и матрица — .efa комплекта.
  static VesselGeom Preset(const G4String& n);
};

class G1SDetector : public G4VUserDetectorConstruction {
public:
  G1SDetector() = default;
  G4VPhysicalVolume* Construct() override;

  HeadGeom   fHead;
  ShieldGeom fShield;
  VesselGeom fVessel;
  bool fWithShield = true;
  bool fWithVessel = false;

  double fSampleVolumeCm3 = 0.0;   // считается по построенному телу
  bool fSampleFits = true;         // уровень засыпки не выше крышки
  G4LogicalVolume* fSampleLV = nullptr;

  G4LogicalVolume* fCrystalLV = nullptr;

  // Матрица пробы. Отдельный статический метод — чтобы mucalc считал
  // коэффициент ослабления по ТОЙ ЖЕ смеси, что идёт в транспорт.
  static G4Material* MakeMatrix(const G4String& matrix, double rho,
                                const G4String& g4name = "OISN16");

  // Печатает массы построенных тел — свинец, кадмий, медь, алюминий, NaI.
  // Служит проверкой геометрии против таблицы 2.2 паспорта.
  void ReportMasses() const;

private:
  void DefineMaterials();
  void BuildHead(G4LogicalVolume* world);
  void BuildShield(G4LogicalVolume* world);
  void BuildVessel(G4LogicalVolume* world);   // Маринелли, с колодцем
  void BuildCup(G4LogicalVolume* world);      // Дента и Петри, плоские

  G4LogicalVolume* fPbLV = nullptr;
  G4LogicalVolume* fCdLV = nullptr;
  G4LogicalVolume* fCuLV = nullptr;
  G4LogicalVolume* fSteelLV = nullptr;
};
