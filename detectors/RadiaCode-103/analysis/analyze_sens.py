# -*- coding: utf-8 -*-
"""Сверка модели с паспортной чувствительностью: 30 cps на 1 мкЗв/ч по Cs-137.

Пучок 662 кэВ, диск радиусом 40 мм (площадь 50.265 см²). Скорость счёта
    N = (счёт/первичных) * Ф * A,
где Ф — плотность потока, дающая H*(10) = 1 мкЗв/ч. По ICRP 74 на 662 кэВ
h*(10) выводится из кермы и отношения ICRP 74 (см. ниже) и равен
3,73 пЗв·см², откуда Ф = 1e6/3600/3,73 = 74,5 см⁻²·с⁻¹.
"""
import os

import numpy as np

import sys

# Корни путей — из переменных окружения (common/py/paths.py).
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "..", "common", "py"))
import paths  # noqa: E402
# Модули прибора лежат в двух каталогах: разбор в analysis/, запуск прогонов
# в drivers/. Импорт через каталог-сосед иначе не находится: python кладёт
# в sys.path только каталог запускаемого файла.
for _d in ("analysis", "drivers"):
    _p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", _d)
    if _p not in sys.path:
        sys.path.insert(0, _p)

import rcspec

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = str(paths.build("RadiaCode-103"))

if not os.path.isdir(BUILD):
    raise SystemExit(
        "Нет каталога расчётных спектров %s.\n"
        "Они не коммитятся (сотни файлов), а воспроизводятся драйверами:\n"
        "    python detectors/RadiaCode-103/drivers/run_grid.py\n"
        "Либо укажите G4MODELS_BUILD_RADIACODE_103 на готовый каталог."
        % BUILD)

AREA = np.pi * 4.0 ** 2          # см², диск радиусом 40 мм

# Коэффициент перехода от плотности потока к H*(10) на 662 кэВ.
#
# НЕ КОНСТАНТА ИЗ ПАМЯТИ, А ВЫВОД. Стоявшее здесь 4,13 пЗв·см² было подписано
# «ICRP 74 с интерполяцией», но проверить подпись было нечем, а вывод о
# паспортной чувствительности зависит от числа прямо. Замена интерполяции на
# соседние узлы, взятые по памяти, ничего не исправляет — память и оказалась
# источником ошибки.
#
# Величина раскладывается на две, каждая из которых известна независимо:
#
#     h*(10)/Ф = [E · (mu_en/rho)_воздух] · [h*(10)/K_возд]
#
# Первый множитель — керма в воздухе на единицу флюенса, чистая физика с
# табличным коэффициентом поглощения NIST. Второй — отношение, которое и
# публикует ICRP 74; для поля Cs-137 оно равно 1,20 Зв/Гр и меняется по
# энергии медленно. Из справочника берётся ТОЛЬКО оно.
#
# Метод проверен на узле, где табличное значение общеизвестно: на 1 МэВ
# расчёт даёт 5,23 пЗв·см² против печатаемых ICRP 74 5,24 — сходится до
# двух десятых процента. На 662 кэВ выходит 3,73.
MEV_J = 1.602176634e-13          # Дж на МэВ
E_CS_MEV = 0.661657
MUEN_AIR_662 = 0.02932           # см²/г, NIST: 0,02955 на 0,6 и 0,02882 на 0,8
H10_OVER_KAIR = 1.20             # Зв/Гр, ICRP 74 для поля Cs-137

KERMA_PER_FLUENCE = E_CS_MEV * MEV_J * MUEN_AIR_662 * 1000.0 * 1e12  # пГр·см²
H10_662 = KERMA_PER_FLUENCE * H10_OVER_KAIR                          # пЗв·см²
H10_OLD = 4.13                   # прежнее значение, для оговорки в выводе
PHI_1USVH = 1e6 / 3600.0 / H10_662

DIRS = [("sens_cs137_front.csv", "фронт (дисплей, кристалл ближе)"),
        ("sens_cs137_back.csv", "тыл (задняя крышка)"),
        ("sens_cs137_nose.csv", "торец (нос)")]


def main():
    print("плотность потока для 1 мкЗв/ч на 662 кэВ: %.1f см⁻²·с⁻¹" % PHI_1USVH)
    print("h*(10) = %.3f пЗв·см²: керма на флюенс %.3f пГр·см² (E·mu_en/rho)"
          "\n   на отношение h*(10)/K = %.2f Зв/Гр (ICRP 74, поле Cs-137)."
          % (H10_662, KERMA_PER_FLUENCE, H10_OVER_KAIR))
    print("   прежнее значение %.2f завышало коэффициент в %.3f раза,"
          " то есть занижало счёт" % (H10_OLD, H10_OLD / H10_662))
    print("площадь пучка: %.2f см²\n" % AREA)
    print("%-34s %10s %12s %10s" % ("направление", "порог 0", "порог 20 кэВ",
                                    "порог 50"))
    for fn, title in DIRS:
        p = os.path.join(BUILD, fn)
        if not os.path.exists(p):
            print("%-34s нет файла" % title)
            continue
        meta, hist = rcspec.read_spec(p)
        n = float(meta["N_primaries"])
        row = []
        for thr in (0, 20, 50):
            cps = hist[thr:].sum() / n * PHI_1USVH * AREA
            row.append(cps)
        print("%-34s %10.1f %12.1f %10.1f" % (title, *row))
    print("\nпаспорт RadiaCode: 30 cps на 1 мкЗв/ч (Cs-137)")


if __name__ == "__main__":
    main()
