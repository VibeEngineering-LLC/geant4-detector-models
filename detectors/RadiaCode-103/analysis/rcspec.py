VESSELS = ("m200", "m500")

NBINS = 3201          # каналы по 1 кэВ, как пишет rc_curves


def vessel():
    """Сосуд берётся из аргументов командной строки, по умолчанию m200."""
    for a in sys.argv[1:]:
        if a in VESSELS:
            return a
    return "m200"


def rdir(*parts, v=None):
    """Путь внутри results для выбранного сосуда."""
    return os.path.join(RESULTS, v or vessel(), *parts)
# Паспортное разрешение на 662 кэВ: RC-102 9.5 %, RC-103 8.4 %.
# Ход по энергии принят статистическим, FWHM ~ sqrt(E); у CsI(Tl) на низких
# энергиях реальное разрешение хуже из-за непропорциональности отклика.
R662 = {"102": 0.095, "103": 0.084, "101": 0.095}


def read_spec(path):
    """-> (метаданные, массив каналов 1 кэВ длиной NBINS)."""
    meta = {}
    hist = np.zeros(NBINS)
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                if "=" in line:
                    k, v = line[1:].split("=", 1)
                    meta[k.strip()] = v.strip()
            elif line and line[0].isdigit():
                a, b = line.split(",")
                i = int(float(a))
                if 0 <= i < NBINS:
                    hist[i] += float(b)
    return meta, hist


# Разрешение RC-103, измеренное по спектрам оператора (правило контура: «всегда
# калибруйся и измеряй fwhm»). Форма (FWHM/E)^2 = a2/E + b^2: первый член —
# статистика фотоэлектронов, второй — ПОЗИЦИОННАЯ НЕОДНОРОДНОСТЬ светосбора
# (окно SiPM ~5 мм при грани кристалла 10 мм, фото drawings/rc_teardown_crystal_window.jpg).
# Та же форма стоит в профиле RC-103 у SpectraVibe: FWHM=k*sqrt(E+alpha*E^2).
# Ниже 350 кэВ форма НЕ проверена — линий в наших спектрах там нет, это экстраполяция.
# ПЕРЕКАЛИБРОВАНО 18.08 (W-012). Прежние значения (2,26 / 5,74 %) получены негодным
# методом: моменты пика с ЛИНЕЙНОЙ подложкой, тогда как под пиком стоит комптоновский
# континуум ОТ ЭТОЙ ЖЕ ЛИНИИ. Три способа на одной линии 662 давали 53,4 / 58,2 / 62,9 кэВ —
# разброс 25 %, то есть метод определял ответ. Нынешние значения получены подгонкой ПОЛНОЙ
# формы спектра: модельный спектр (МК, 96 млн историй, континуум посчитан физикой)
# сворачивается с разной шириной и сравнивается с измерением на калиброванной шкале в
# окне 350-800 кэВ; минимум chi2/dof = 6,0 при FWHM(662) = 65,1 кэВ = 9,83 %.
# Сходится с профилем RC-103 у SpectraVibe (ожидаемое R(662) для CsI(Tl) handheld 8-10 %).
# ТРЁХЧЛЕННАЯ форма: FWHM^2 = C + A2*E + (B*E)^2.
#   C  — постоянный (шумовой/непропорциональный) член, кэВ^2. Доминирует НИЖЕ ~200 кэВ:
#        у CsI(Tl) световыход на электрон непропорционален энергии (см. arXiv:2302.05641,
#        профиль RC-103 у SpectraVibe: «non-prop заметна на низких E < 200 keV»), плюс
#        электронный шум тракта. Без него модель даёт в мягкой части ВЫРАЖЕННЫЕ пики,
#        которых у реального RC-103 нет — замечание оператора 18.08: «RC не даёт такие
#        выраженные пики в фоне, у него всё смазано в средней и низкой части».
#   A2 — статистика фотоэлектронов;  B — позиционная неоднородность светосбора.
# ПЕРЕКАЛИБРОВАНО 20.08 (P-019) — ПРЯМЫМ измерением ширин одиночных пиков
# (гауссиана + линейная база, единый метод по всем линиям):
#   661,7 (черника, 29k отсч., пик/база 18:1)  -> 54,2 кэВ = 8,07 %
#   911,2 (открытый фон 7 сут)                  -> 68,0 кэВ
#   1460,8 (открытый фон 7 сут)                 -> 73,3 кэВ
#   2614,5 (мало статистики, ориентир)          -> ~59 кэВ
# Прежние значения (FWHM(662)=65,1=9,83 %, B=6,888 %) — артефакт full-shape
# фита 350-800 при модельном континууме, в котором не хватало ~18 % счёта
# (ахроматическая утечка, GEANT4/references/rethink-2026-08-20.md): фит
# раздувал гауссиану, заполняя недостающий континуум (chi2/dof=6). Класс
# W-012 — метод определил ответ. Член (B*E)^2 прямыми ширинами ИСКЛЮЧЁН:
# на 1461 он один давал бы 100 кэВ при измеренных 73. Форма A2*E одна
# ложится в +-10 % на все три надёжные точки: 662->54,2; 911->63,6
# (изм. 68); 1461->80,5 (изм. 73).
# ⚠ Ниже ~300 кэВ прямых одиночных линий нет (46,5 у порога, 76,7 —
# мультиплет XRF) — форма там ЭКСТРАПОЛЯЦИЯ, как и прежде.
# ⚠ После смены констант устарели ВСЕ свёртки: b_room_prior, бюджет фона,
# черника (ROI зависит от FWHM), fit_lines. Пересчёт — одной волной с
# пост-ESR прогонами Pb-210 (#SHIELD-27).
# ═══ ПЕРЕПРИВЯЗКА 21.08 (P-020). Прежнее A2 = 4,440 ОТОЗВАНО ═══
# Прежнее значение не воспроизводилось НИ ОДНИМ скриптом репозитория, скрипта-
# производителя не существовало (W-023), и оно лежало ниже ВСЕХ независимых
# измерений. Похоже, 54,2 кэВ = 21 канал x шаг шкалы: из приложения взято
# округлённое ЧИСЛО КАНАЛОВ вместо готового значения в кэВ рядом с ним.
#
# ИСТОЧНИК: ОБЩИЙ измеритель контура SpectraVibe (своего у нас больше нет,
# убран в analysis/_attic_20260821/):
#   gamma/calibration/fwhm_measure.py -> measure_fwhm(window_factor=1.25)
# Принят по протоколу 8/8, включая мутационную проверку: analysis/accept_fwhm_measure.py
#
# ВОСПРОИЗВЕДЕНИЕ (правило W-023 — константа принимается только с командой):
#   G4MODELS_MEASURED=C:\g4work\measured\RadiaCode-103 python analysis/fwhm_curve.py
#
# ТОЧКА ПРИВЯЗКИ: Cs-137 661,657 в чернике -> 57,455 кэВ = 8,684 %.
# Сошлись ЧЕТЫРЕ независимых источника: приложение оператора №1 — 56,87 (8,64 %),
# приложение №2 — 58,068 (8,777 %), независимое измерение SpectraVibe — 8,73 %,
# общий измеритель — 57,455. Коридор 8,64-8,78 %; прежние 8,19 % вне него.
#   A2 = 57,455^2 / 661,657 = 4,989
#
# ПОГРЕШНОСТЬ: ±2,0 кэВ (3,4 %), НЕ ±0,425, которые отдаёт сам модуль. Бюджет на
# 90 % методический, не статистический: пик набран на ~147 сигма, статистика не
# ограничитель. Поправка от SpectraVibe после стерильного аудита их же модуля.
# Читать как 8,68 ± 0,30 %. Их же оговорка: избыток справа от пика (~4 % площади)
# вероятно от дрейфа усиления за 31,7 ч набора — тогда это разрешение ДАННОГО
# НАБОРА, то есть ВЕРХНЯЯ оценка мгновенного разрешения детектора.
FWHM_C = 0.0        # кэВ^2, постоянный член отвергнут точкой 32 кэВ (см. ниже)
FWHM_A2 = 4.989     # кэВ: 57,455^2/661,657, общий измеритель SpectraVibe, 21.08
FWHM_B = 0.0        # (B*E)^2: alpha при подгонке отрицательна -> член отвергнут
# ⚠ ФОРМА КРИВОЙ ДАННЫМИ НЕ ОПРЕДЕЛЕНА. Записываю честно, а не маскирую согласием.
#   Надёжных якорей ДВА: 662 -> 57,455 и 1460,8 -> 74,193. Они НЕСОВМЕСТИМЫ:
#   A2 по ним 4,989 против 3,768 — расхождение 32 %. Обе двухпараметрические
#   формы отвергнуты физикой, а не вкусом: k*sqrt(E+alpha*E^2) даёт alpha < 0
#   (кривая изгибается ВНИЗ, для сцинтиллятора невозможно), а FWHM^2 = C + A2*E
#   при C > 0 даёт на 32 кэВ 39,6 кэВ против измеренных приложением ~10.
#   Поэтому форма оставлена ОДНОПАРАМЕТРИЧЕСКОЙ, а константа перепривязана
#   к самому надёжному якорю.
#   СЛЕДСТВИЕ, которое надо помнить при чтении любых свёрток: на 1460,8 модель
#   даёт 85,4 кэВ против измеренных 74,2 (+15 %). Это известное РАСХОЖДЕНИЕ.
#   Негодные якоря и почему именно: 583,19 и 609,31 разнесены на 26,1 кэВ при
#   ПШПВ ~53 — полностью слиты, измеритель дважды померил один горб (52,7/52,2);
#   911,20 — значимость 1,4 сигма; 2614,51 — методы расходятся на 57 %;
#   1120,29 дал 135 кэВ при подогнанных 92,8, отбракован гейтом по немонотонности.
# ═══ ОБЛАСТЬ ПРИМЕНИМОСТИ — читать до любого использования fwhm() ═══
# (внесено 21.08 по возражению SpectraVibe; их разбор проверен и принят)
# Моя формулировка «привязка к одной точке — значит риск равен риску этой точки»
# НЕВЕРНА, отзываю. Однопараметрическая a*sqrt(E) даёт предсказание на ЛЮБОЙ
# энергии, в том числе на второй измеренной точке, и там она промахивается:
#   привязка 56,87 -> на 1460,8 модель 84,50 против измеренных 74,19 (+13,9 %)
#   привязка 57,455 -> 85,37 (+15,1 %);  привязка 58,068 -> 86,28 (+16,3 %)
# Промах есть при ЛЮБОЙ из четырёх привязок => это свойство ФОРМЫ, а не точки.
# Эффективный показатель между двумя точками n = 0,31...0,34 вместо стат. 0,50.
# Списать на погрешность НЕЛЬЗЯ: разброс по окну на 1461 всего ±1,25 кэВ (1,7 %),
# проверено прогоном window_factor 1,0...1,5 -> 74,01...76,50 кэВ.
# Непропорциональностью CsI тоже НЕЛЬЗЯ: она не превышает 3-4 % и проявляется
# ниже 300 кэВ («Введение в физику сцинтилляторов», ч. 2), обе точки выше 300.
# ОСТАЮТСЯ ДВЕ ВОЗМОЖНОСТИ, двумя точками НЕ различимые:
#   (а) точка 1461 смещена вниз: линия слабая и стоит на структурированном фоне,
#       то есть в условиях известного дефекта измерителя. На сыром спектре метод
#       давал там 60,0 кэВ, и только снятие наклона подложки подняло до 74-77 —
#       точка, зависящая от обработки подложки на 20 %, «надёжной» не является;
#   (б) форма для этого прибора не sqrt(E) и по двум точкам не определяется.
# ПРАКТИЧЕСКИ:
#   • в ОКРЕСТНОСТИ 662 константа обоснована — четыре независимых источника;
#   • ВЫШЕ ~1000 кэВ модель ЗАВЫШАЕТ ширину примерно на 15 % в известную сторону.
#     Любой вывод, чувствительный к ширине выше 1 МэВ (пик 2614 в бюджете домика,
#     мюонное окно, МДА на верхних линиях), обязан это учитывать;
#   • НИЖЕ ~300 кэВ якорей нет вообще — чистая экстраполяция.
# Закрыть вопрос может только ТРЕТЬЯ точка, независимая от обеих: кандидаты
# Pb-212 238,63 и Ac-228 338,32 — они ниже 662 и дают плечо в другую сторону.
# ⚠ Geant4-модель ответить на это НЕ МОЖЕТ: в МК фотопик — дельта-функция,
# разрешение вносится свёрткой ИЗВНЕ, а физика, задающая показатель степени
# (статистика фотоэлектронов, светосбор, шум тракта), в модели отсутствует.
# Считать n из своей МК — значит получить обратно то, что в неё заложено этим
# же файлом.
# ⚠ СТАТУС ИЗМЕРИТЕЛЯ: 21.08 SpectraVibe ОТОЗВАЛ у fwhm_measure.py статус «готов»
# (их стерильный аудит нашёл 3 критичных дефекта). Почему константа ВСЁ РАВНО
# действует — проверено мной на своих данных, а не принято на веру:
#   1) отозванные дефекты — про ложные числа на бесструктурном завале (запрос
#      150 кэВ даёт 82,5 кэВ там, где линии нет) и про молчаливое измерение
#      дублетов (583,19 даёт центроид 596,84 — это центр дублета 583/609).
#      Оба воспроизвёл у себя; оба бьют по якорям, которые я и так исключил.
#   2) точка 662 к этим классам не относится и устояла: их стерильный замер
#      57,7 ± 2,0, приложения оператора 56,87 и 58,068.
#   3) формальный отказ «блендирована с 609,31 и 665,45» при полном списке линий
#      для ЧЕРНИКИ не действует: домик подавляет эти линии до 4,2 % и 1,1 %
#      счёта в их областях, и удаление фона ВМЕСТЕ С НИМИ меняет ширину на
#      0,18 %. Проверено прямым сравнением сырого и фоновычтенного спектра.
#   4) прежние 8,19 % противоречили ЧЕТЫРЁМ независимым источникам, два из
#      которых — приложения оператора, с этим модулем вообще не связанные.
#      Возврат к ним был бы не осторожностью, а ухудшением.


def fwhm(E, model="103"):
    """Полная ширина на полувысоте, кэВ."""
    Ec = np.maximum(E, 1.0)
    if model == "103":
        return np.sqrt(FWHM_C + FWHM_A2 * Ec + (FWHM_B * Ec) ** 2)
    # 101/102 не измерялись — остаётся паспортная статистическая форма
    r = R662[model] if isinstance(model, str) else float(model)
    return r * 662.0 * np.sqrt(Ec / 662.0)


# ═══ ШИРИНА ДЛЯ ОКОН ОТБОРА ЛИНИЙ — ИЗ ИЗМЕРЕНИЯ, не из модели (21.08) ═══
# Повод (оператор: «ширину для окон из измерения»). Окна нетто строятся как
# ±2,5σ от ширины. Модельная кривая выше 1 МэВ ЗАВЫШАЕТ (см. провенанс выше),
# и на 2614 окно ±121 кэВ растягивалось на 2493…2736: боковые полосы ложились
# на сам пик и за край шкалы, нетто выходило ОТРИЦАТЕЛЬНЫМ, линия
# отбраковывалась как «шаблон не даёт пика в окне» — при том что пик в шаблоне
# ЕСТЬ (263 отсчёта в 2590–2640, и только у Tl-208). Та же беда на 1461: окно
# ±91 кэВ затягивало Ac-228 1377 и Bi-214 1509, и в окне K-40 «доминировал»
# Ra-226 на 80 %.
#
# ИЗМЕРЕННЫЕ ТОЧКИ (общий измеритель SpectraVibe, принят по протоколу 8/8,
# window_factor=1.25). Воспроизведение — analysis/measure_lines_fwhm.py:
#   661,657 Cs-137 (черника)  -> 57,48 кэВ  ← эталон, сошёлся с 4 источниками
#   1460,82 K-40 (откр. фон)  -> 74,19 кэВ
# Честные ОТКАЗЫ измерителя: 911 и 1764 — значимость 1,4-1,5σ; 1120 — не
# сошлось; 2614 — методы разошлись (2,7σ). 583/609 измерились (52,7/52,3), но
# это ДУБЛЕТ с разносом 26 кэВ при ширине ~53 — один горб, померенный дважды;
# в опору не берутся.
#
# ФОРМА: степенная a·E^n по двум надёжным точкам, n = 0,322. Это ЭМПИРИКА ДЛЯ
# ОКОН, а НЕ физическая модель разрешения (физическая форма данными не
# определена, см. выше). Окну нужна не физика, а совпадение с реальным краем
# линии.
_FWIN_E1, _FWIN_W1 = 661.657, 57.48
_FWIN_E2, _FWIN_W2 = 1460.82, 74.19
FWIN_N = float(np.log(_FWIN_W2 / _FWIN_W1) / np.log(_FWIN_E2 / _FWIN_E1))
FWIN_A = _FWIN_W1 / (_FWIN_E1 ** FWIN_N)


def fwhm_win(E):
    """Ширина ДЛЯ ОКОН отбора линий — по ИЗМЕРЕННЫМ точкам (провенанс ниже).

    ⚠ Выше 1461 кэВ — ЭКСТРАПОЛЯЦИЯ (на 2614 даёт ~89 кэВ против 114 у
    модельной кривой). Для СВЁРТКИ модели по-прежнему fwhm(): это разные
    задачи, подменять одну другой нельзя.
    """
    return FWIN_A * np.power(np.maximum(E, 1.0), FWIN_N)


def fold(hist, model="103"):
    """Свёртка с разрешением прибора. Ширина зависит от энергии, поэтому
    раскладываем каждый канал в свою гауссиану."""
    E = np.arange(len(hist)) + 0.5
    out = np.zeros_like(hist)
    sig = fwhm(E, model) / 2.35482
    nz = np.nonzero(hist)[0]
    for i in nz:
        s = sig[i]
        lo = max(0, int(i - 5 * s))
        hi = min(len(hist), int(i + 5 * s) + 1)
        x = E[lo:hi]
        g = np.exp(-0.5 * ((x - E[i]) / s) ** 2)
        gs = g.sum()
        if gs > 0:
            out[lo:hi] += hist[i] * g / gs
    return out


def roi(hist, E0, model="103", nsig=1.2):
    """Площадь в окне +-nsig*sigma вокруг линии (около 80 % площади пика при
    nsig=1.2) и границы окна."""
    s = fwhm(E0, model) / 2.35482
    lo, hi = int(E0 - nsig * s), int(E0 + nsig * s) + 1
    lo, hi = max(0, lo), min(len(hist), hi)
    return hist[lo:hi].sum(), lo, hi


def peak_fraction(model="103", nsig=1.2):
    """Доля площади гауссианы, попадающая в окно +-nsig*sigma."""
    from math import erf, sqrt
    return erf(nsig / sqrt(2.0))
