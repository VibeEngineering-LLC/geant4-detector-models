# -*- coding: utf-8 -*-
"""Достоверность взвешенного МК-спектра по областям энергии.

ЗАЧЕМ. Под importance-биасингом «сумма весов» ничего не говорит о качестве
статистики: 0,73 может быть и ОДНОЙ историей с весом 0,73, и тысячей историй
по 0,0007. Задача №13 проверяла достоверность только в окне 662 кэВ; в
остальном спектре проверки не было, и 13.08.2026 выяснилось, что
низкоэнергетическая часть (45-120 кэВ, где живёт ХРИ свинца) при pb=30
держится на 0,18 суммы весов в 28 каналах — площадь группы K-линий Pb за
вычетом подложки выходила ОТРИЦАТЕЛЬНОЙ.

МЕТРИКА. Для взвешенной гистограммы эффективное число выборок
    N_eff = (Σw)² / Σw²
и относительная погрешность области
    σ/значение = sqrt(Σw²) / Σw = 1 / sqrt(N_eff).
Σw² пишет сам `shieldrun` в файл `<out>.sumw2.csv` (введено 13.08.2026).

⚠️ Для старых файлов БЕЗ него подставляется w²→w, тогда N_eff = Σw. Это
НЕ верхняя оценка (первая редакция этого файла утверждала обратно —
исправлено 13.08.2026): при importance splitting веса МЕНЬШЕ единицы, тогда
Σw² < Σw, а значит истинный N_eff = (Σw)²/Σw² БОЛЬШЕ показанного. То есть
для биасированных прогонов это НИЖНЯЯ граница, и «НЕ ГОДНО» по ней само по
себе ничего не доказывает. Пример из задачи №13: pb=100 дал 1461
независимую взвешенную выборку при сумме весов всего 0,0203 — подстановка
показала бы N_eff=0,02 вместо истинных ~1461.

Вывод: по файлам без `.sumw2.csv` судить о достоверности НЕЛЬЗЯ, нужен
перепрогон уже собранным `shieldrun`. Знак смещения оценки зависит от
весов: w<1 — занижение, w>1 — завышение, w=1 — точно.

ПОРОГ. N_eff >= 100 (отн. погрешность 10 %) — область пригодна для
количественных выводов; 25..100 (10..20 %) — только для порядка величины;
< 25 — не использовать. Пороги эвристические, не норматив; выбраны так же,
как N_MIN=20 в mda_shield.py, и помечены здесь как эвристика.

Запуск:
    python spec_quality.py <spectrum.csv> [ещё файлы...]
    python spec_quality.py test
"""
import os
import sys

import numpy as np

GOOD, FAIR = 100.0, 25.0      # эвристические пороги N_eff, не норматив

# Области, по которым имеет смысл судить отдельно (границы — по физике
# задачи, не произвольные): ХРИ свинца, окно Cs-137, линия K-40, жёсткий
# хвост, где живёт проникающая компонента.
BANDS = [
    (20.0, 45.0, "мягкий край"),
    (45.0, 68.0, "подложка под ХРИ"),
    (68.0, 94.0, "ХРИ Pb (K-линии)"),
    (94.0, 300.0, "низкий континуум"),
    (300.0, 632.2, "средний континуум"),
    (632.2, 691.2, "ОКНО Cs-137 662"),
    (691.2, 1400.0, "верхний континуум"),
    (1400.0, 1550.0, "линия K-40 1460,8"),
    (1550.0, 2700.0, "жёсткий хвост"),
]


def read_two_col(path):
    e, v = [], []
    if not os.path.exists(path):
        return np.array([]), np.array([])
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or not line[:1].isdigit():
            continue
        a, b = line.split(",")
        e.append(float(a))
        v.append(float(b))
    return np.array(e), np.array(v)


def load(path):
    """-> (e, w, w2, has_w2). w2 = Σw² поканально; при отсутствии файла
    .sumw2.csv подставляется w (эквивалент допущения w=1)."""
    e, w = read_two_col(path)
    e2, w2 = read_two_col(path + ".sumw2.csv")
    if len(e2) == 0:
        return e, w, w.copy(), False
    # выравниваем по энергиям основного файла
    m = {round(x, 1): y for x, y in zip(e2, w2)}
    w2a = np.array([m.get(round(x, 1), 0.0) for x in e])
    return e, w, w2a, True


def band_stats(e, w, w2, lo, hi):
    m = (e >= lo) & (e < hi)
    sw, sw2 = float(w[m].sum()), float(w2[m].sum())
    if sw <= 0 or sw2 <= 0:
        return sw, 0.0, float("inf")
    n_eff = sw * sw / sw2
    return sw, n_eff, 1.0 / np.sqrt(n_eff)


def verdict(n_eff):
    if n_eff >= GOOD:
        return "годно"
    if n_eff >= FAIR:
        return "только порядок"
    return "НЕ ГОДНО"


def report(path):
    e, w, w2, has = load(path)
    if len(e) == 0:
        print("%s — пусто или не найден" % path)
        return
    print("=" * 78)
    print(os.path.basename(path), "" if has else
          "\n  [!] нет .sumw2.csv — подставлено w²→w. Для биасированных прогонов"
          "\n      (веса < 1) это НИЖНЯЯ граница N_eff: истинная достоверность"
          "\n      ВЫШЕ показанной. Судить по этим числам нельзя — перепрогнать.")
    print("%-22s %12s %10s %9s  %s" % ("область, кэВ", "Σw", "N_eff", "σ/знач", "вердикт"))
    print("-" * 78)
    for lo, hi, name in BANDS:
        sw, n_eff, rel = band_stats(e, w, w2, lo, hi)
        rel_s = "—" if not np.isfinite(rel) else "%8.1f%%" % (100 * rel)
        print("%-22s %12.4g %10.1f %9s  %s"
              % ("%.0f-%.0f %s" % (lo, hi, name), sw, n_eff, rel_s, verdict(n_eff)))


def self_test():
    ok = True
    rng = np.random.default_rng(20260813)
    e = np.arange(0.5, 3200.5, 1.0)

    # случай 1: невзвешенный (w=1) — N_eff обязан равняться числу отсчётов
    counts = rng.poisson(np.full_like(e, 0.5)).astype(float)
    sw, n_eff, rel = band_stats(e, counts, counts, 632.2, 691.2)
    if abs(n_eff - sw) > 1e-9:
        print("ПРОВАЛ: при w=1 N_eff (%.3f) != Σw (%.3f)" % (n_eff, sw)); ok = False
    else:
        print("ok: при w=1 N_eff совпадает с числом отсчётов (%.0f)" % sw)

    # случай 2: та же сумма весов, но РАЗНАЯ раздробленность — N_eff обязан
    # различаться на порядки. Ровно та ошибка, из-за которой метрика введена.
    w_one = np.zeros_like(e); w_one[660] = 0.73
    w2_one = w_one ** 2
    w_many = np.zeros_like(e); w2_many = np.zeros_like(e)
    w_many[650:700] = 0.73 / 50.0
    w2_many[650:700] = (0.73 / 1000.0) ** 2 * 20     # 1000 историй по 0,00073
    _, n1, _ = band_stats(e, w_one, w2_one, 632.2, 691.2)
    _, n2, _ = band_stats(e, w_many, w2_many, 632.2, 691.2)
    print("ok: одна история весом 0,73 -> N_eff=%.1f; раздробленная та же сумма -> N_eff=%.1f"
          % (n1, n2))
    if not (n1 < 2.0 < n2):
        print("ПРОВАЛ: метрика не различает раздробленность"); ok = False

    print("ИТОГ:", "ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ" if ok else "ЕСТЬ ПРОВАЛЫ")
    return ok


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "test":
        sys.exit(0 if self_test() else 1)
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    for p in sys.argv[1:]:
        report(p)
