// Розыгрыш энергии космического мюона по спектру Гайссера, вертикальное
// приближение (PDG RPP2020 §30.3.1):
//
//   dN/dE dOmega = 0.14 * E^(-2.7) *
//                  [ 1/(1 + 1.1*E/115) + 0.054/(1 + 1.1*E/850) ]     E в ГэВ
//
// ⚠ ОГОВОРКА ПЕРВОИСТОЧНИКА (повторяется здесь по требованию спеки):
// формула строго применима при E > 100/cosT ГэВ, а нас интересуют сотни МэВ —
// единицы ГэВ, то есть используемое ниже — ЭКСТРАПОЛЯЦИЯ. Годится для ФОРМЫ
// континуума, но НЕ для абсолютного числа с точностью до процентов.
//
// Реализация: логарифмическая сетка узлов в [E_LO, E_HI], кумулятивное
// распределение по трапециям, розыгрыш двоичным поиском + линейная
// интерполяция внутри интервала.
#pragma once

#include <vector>

class Rc103MuonSpectrum {
 public:
  static constexpr double kELoGeV = 0.3;
  static constexpr double kEHiGeV = 100.0;
  // Спека требует "не менее 400 узлов"; берём 1000 — стоимость нулевая,
  // дискретизация края спектра заметно мягче.
  static constexpr int kNNodes = 1000;

  Rc103MuonSpectrum();

  // Возвращает энергию в ГэВ.
  double SampleEnergyGeV() const;

  // Дифференциальная интенсивность (произвольная нормировка), E в ГэВ.
  static double Gaisser(double eGeV);

 private:
  std::vector<double> fE;    // узлы сетки, ГэВ
  std::vector<double> fCdf;  // кумулятив, нормирован на 1 в последнем узле
};
