// ПРЯМОУГОЛЬНАЯ свинцовая защита («домик») для RadiaCode 101/102/103 с сосудом
// Маринелли 200 мл. Размеры в мм.
//
// ФОРМА. До 15.08.2026 защита моделировалась ЦИЛИНДРОМ. Это была проектная
// идеализация, а не обмер: реальный домик оператора сложен из кирпичей и в
// плане КВАДРАТНЫЙ. Разница не косметическая — полость выросла в 6,1 раза
// (1414 -> 8663 см³), а вместе с ней телесный угол, под которым кристалл
// видит стенки, и длина пути через воздух до них.
//
// ЗАДАЧА, ПОД КОТОРУЮ СДЕЛАНО. Проектный расчёт: как МДА по Cs-137 в пробе
// зависит от толщины свинца, и с какой толщины свинец перестаёт окупаться.
// Поэтому толщина здесь — свободный параметр, а полость ФИКСИРОВАНА: наружный
// габарит растёт вместе с толщиной, как у настоящей сборки из кирпичей.
//
// ПОЧЕМУ СЛОЙ СОБРАН ИЗ ТРЁХ ПРОСТЫХ ТЕЛ, А НЕ ВЫРЕЗАН БУЛЕВОЙ ОПЕРАЦИЕЙ.
// Три причины, все существенные:
//   1) скорость: пустотелая оболочка через G4SubtractionSolid считает
//      DistanceToIn/Out по двум телам на каждом шаге, а прогон стадии 1 —
//      самая дорогая часть работы;
//   2) координаты: прибор и сосуд остаются дочерними объёмами МИРА, чья
//      система отсчёта — центр кристалла (см. RCDetector.hh). Если бы полость
//      была физическим объёмом, прибор пришлось бы класть внутрь неё со
//      сдвигом, то есть править проверенный код размещения;
//   3) биасинг: каждый кусок — отдельная ячейка G4IStore. Важность зависит
//      только от НОМЕРА слоя, поэтому обечайка, дно и крышка одного слоя
//      получают одно значение, и переход между ними расщепления не вызывает.
//
// Слой k с внутренними полуразмерами hx, hy, hz и толщиной d даёт ШЕСТЬ тел
// (пять при открытом верхе). Стенки по X берутся во всю ширину слоя, стенки
// по Y — только по внутренней: так углы закрыты ровно один раз, без щели и
// без перекрытия.
//   стенка ±X  G4Box(d/2, hy+d, hz)      в x = ±(hx + d/2)
//   стенка ±Y  G4Box(hx,   d/2,  hz)     в y = ±(hy + d/2)
//   дно        G4Box(hx+d, hy+d, d/2)    в z = zCav - hz - d/2
//   крышка     то же                      в z = zCav + hz + d/2
// после чего hx += d, hy += d, hz += d. Сечение сходится тождественно:
//   4d(hy+d) + 4(hx)d  ==  4[(hx+d)(hy+d) - hx*hy],
// то есть самопроверка объёма ниже — не формальность, а реальная ловушка
// на арифметику стыков (та же, что была у цилиндра).
//
// ПОРЯДОК СЛОЁВ от полости наружу: Cu -> Cd -> Pb. Тот же, что у защиты
// Гамма-1С (G1SDetector.cc:570-572) и по той же причине: K-рентген свинца
// 72..88 кэВ гасится кадмием, K-рентген кадмия ~23 кэВ — медью. Значения
// K-краёв и линий проверяются по первоисточнику, а не назначаются здесь.
#pragma once
#include "RCDetector.hh"

#include <vector>

class G4VPhysicalVolume;

struct ShieldGeom {
  // --- полость -------------------------------------------------------------
  // РАЗМЕРЫ РЕАЛЬНОГО ДОМИКА ОПЕРАТОРА (сообщено 15.08.2026): внутри
  // 150 x 150 мм в плане, высота 385 мм, свинец 50 мм (стенки И дно),
  // верх ОТКРЫТ, меди и кадмия нет. До 15.08.2026 здесь стоял ЦИЛИНДР
  // rCav=50, hzCav=90 (полость 1414 см³) — проектная модель под развёртку
  // по толщине свинца, а не обмер реальной сборки. Настоящая полость
  // 8663 см³, то есть в 6,1 раза больше; сравнивать модель с измерением
  // «Фон домик 23 дня» на цилиндре было незаконно.
  //
  // Посадка по оси. Сборка (прибор + сосуд m200 с крышкой) стоит НА ДНЕ
  // полости, в пустом сосуде. Занято: r до 40.25 (юбка крышки сосуда),
  // z от -36.61 (низ диска крышки) до +111.00 (хвост прибора) — числа
  // выводятся из RCDetector.hh через AssemblyExtent(), НЕ набираются здесь
  // руками. При seatOnFloor=true zCav вычисляется так, чтобы пол полости
  // совпал с низом сборки; значение поля zCav тогда игнорируется.
  // Проверка вместимости делается в коде, а не на словах: BuildShield()
  // сверяет габариты и отказывается строить, если прибор не влезает.
  double hxCav = 75.0;    // полуширина полости по X (150 мм в плане)
  double hyCav = 75.0;    // полуширина полости по Y (150 мм в плане)
  double hzCav = 192.5;   // полувысота полости (385 мм высота)
  double zCav  = 155.89;  // центр полости в мировой системе (центр кристалла);
                          // = -36.61 + 192.5, см. seatOnFloor ниже

  // Сажать пол полости на низ сборки, пересчитывая zCav в BuildShield().
  // Так у координаты -36.61 остаётся ОДИН источник истины — геометрия
  // сосуда в RCDetector.hh; иначе литерал в zCav разойдётся с ней при
  // любой правке сосуда, и разойдётся молча (тот же класс ошибки, что
  // Sc-44 4,04 ч против 3,97 ч в линии Гамма-1С).
  // false — zCav берётся как задан (проектные расчёты, ключ zcav=).
  bool seatOnFloor = true;

  // --- слои от полости наружу ----------------------------------------------
  double cu = 0.0;       // медный вкладыш, 0 = вкладыша нет
  double cd = 0.0;       // кадмиевый вкладыш, 0 = вкладыша нет
  double pb = 50.0;      // свинец

  // На сколько вложенных слоёв резать свинец. Нужно ТОЛЬКО для расщепления по
  // важности: карта важностей одномерна по глубине, и слои — её ячейки.
  // На физику не влияет (материал один), на скорость влияет слабо.
  // Проверка (iv) требует, чтобы результат не зависел от этого числа.
  int nShellPb = 8;
};

class RCShieldDetector : public RCDetector {
public:
  // withDevice=false — ДЛЯ СТАДИИ 1 конвейера снижения дисперсии: полость
  // остаётся пустым воздухом (без прибора, без сосуда), и проверка
  // вместимости в BuildShield() тогда пропускается — проверять нечего.
  // Комбинация withDevice=false, withVessel=true запрещена логикой: сосуд без
  // прибора внутри него не строился и не имеет смысла (см. Construct()).
  explicit RCShieldDetector(bool withVessel = true, bool withShield = true,
                            bool withDevice = true);
  G4VPhysicalVolume* Construct() override;

  // Центр полости, КОТОРЫЙ БУДЕТ ПОСЛЕ посадки на дно, и наружные полугабариты,
  // КОТОРЫЕ БУДУТ после сборки слоёв. Нужны вызывающему коду ДО Construct():
  // мюонный блок shieldrun.cc ставит диск-источник по zCav и наружному
  // габариту, а при seatOnFloor настоящий zCav появляется только внутри
  // Construct(). Читать fSh.zCav там напрямую нельзя — получишь значение ДО
  // посадки, и диск уедет на сотни миллиметров (полость поднимается со старых
  // 35 мм до ~156 мм). Construct() зовёт эти же методы, поэтому формула
  // посадки существует ровно в одном месте.
  double PlannedZCav() const;
  double PlannedOuterHx() const { return fSh.hxCav + fSh.cu + fSh.cd + fSh.pb; }
  double PlannedOuterHy() const { return fSh.hyCav + fSh.cu + fSh.cd + fSh.pb; }
  // ⚠ По оси наружный габарит НЕ симметричен центру полости, когда верх открыт:
  // вниз он уходит на толщину дна, вверх не уходит вовсе (стенки кончаются
  // вровень с полостью). Поэтому полувысота и центр — отдельные величины, и
  // брать zCav за центр габарита нельзя.
  double PlannedOuterZLo() const {
    return PlannedZCav() - fSh.hzCav - (fSh.cu + fSh.cd + fSh.pb);
  }
  double PlannedOuterZHi() const {
    return PlannedZCav() + fSh.hzCav
         + (fWithLid ? (fSh.cu + fSh.cd + fSh.pb) : 0.0);
  }
  double PlannedOuterHz() const {
    return 0.5 * (PlannedOuterZHi() - PlannedOuterZLo());
  }
  double PlannedOuterZc() const {
    return 0.5 * (PlannedOuterZHi() + PlannedOuterZLo());
  }
  // Радиус окружности, ОПИСАННОЙ вокруг наружного габарита. Именно он, а не
  // полуширина, задаёт мюонный диск и полуразмер мира: углы короба выходят за
  // полуширину в sqrt(2) раз (для 250x250 это 176.8 мм против 125 мм).
  double PlannedOuterR() const;

  ShieldGeom fSh;

  // Физические объёмы слоёв ОТ ПОЛОСТИ НАРУЖУ вместе с глубиной каждого:
  // fLayerDepth[i] — номер слоя (0 = ближайший к полости), одинаковый у
  // обечайки, дна и крышки. Отсюда строится G4IStore.
  std::vector<G4VPhysicalVolume*> fLayerPV;
  std::vector<int>                fLayerDepth;
  int fNDepth = 0;                 // сколько слоёв всего

  // Наружный габарит собранной защиты. Полуразмеры короба + радиус ОПИСАННОЙ
  // вокруг него окружности. fOuterR держится не для красоты: по нему ставится
  // мюонный диск-источник и полуразмер мира, и для короба это обязана быть
  // полудиагональ, а не полуширина — иначе углы защиты систематически не
  // накрываются источником (для 250x250 наружного габарита полудиагональ
  // 176.8 мм против полуширины 125 мм, то есть промах в 1,4 раза).
  double fOuterHx = 0., fOuterHy = 0., fOuterHz = 0.;
  double fOuterZc = 0.;   // центр наружного габарита по оси (≠ zCav при nolid)
  double fOuterR  = 0.;   // = sqrt(fOuterHx² + fOuterHy²), описанная окружность
  double fMassPb = 0., fMassCd = 0., fMassCu = 0.;   // кг

  // Нижняя граница полуразмера мира по XY, мм. 0 = не задана (мир считается
  // только по габариту защиты, прежнее поведение — побитово). Нужна режиму
  // mode=muon: диск-источник мюонов может быть ШИРЕ защиты, и если мир по
  // нему не расширить, часть диска окажется снаружи мира. Найдено 13.08.2026
  // на развёртке по радиусу диска: при pb=50 мир имеет полуразмер XY 130 мм,
  // а диски 140..600 мм торчали наружу — «выход на полку» в той развёртке
  // был артефактом обрезания диска гранью мира, а не физикой.
  double fWorldMinHalfXY = 0.0;

  // Строить ли ВЕРХНЮЮ крышку защиты. true — закрытый короб (проектные
  // расчёты по толщине свинца). false — открытая сверху защита: именно так
  // собран реальный домик оператора (13.08.2026, подтверждено 15.08.2026
  // вместе с размерами), и только для такой геометрии законно сравнивать
  // модель с его измерением «Фон домик 23 дня». Без крышки поле помещения
  // входит в полость сверху не ослабленным, а мюоны (cos²θ, идут
  // преимущественно сверху) попадают в кристалл вообще без свинца.
  //
  // ⚠ Дефолт остаётся true СОЗНАТЕЛЬНО: сменить его молча — значит изменить
  // результат всех прежних проектных прогонов задним числом. Для реального
  // домика верх открывается явным ключом `nolid` (shieldrun.cc).
  // ⚠ ЗНАЙ ПРО #SHIELD-2: этот флаг влияет на ПОСТРОЕНИЕ геометрии, но в
  // источниках GPS режимов resp/trans он до сих пор НЕ учитывается —
  // источник разыгрывается по замкнутой поверхности, включая верх, которого
  // при nolid нет. Пока это не исправлено, открытый верх даёт систематику
  // и в розыгрыше, и в площади S для тождества Ф=4N/S.
  bool fWithLid = true;

  // Именованная "полость" — ТОЛЬКО когда fWithDevice=false (стадия 1/beam):
  // отдельный физический объём воздуха (совпадает по размеру с полостью),
  // сосед "world", а не сам "world". Нужен для importance-биасинга (задача
  // №2): G4IStore ключует по G4VPhysicalVolume*, а "world" в этой геометрии
  // до сих пор одновременно и внешнее пространство (снаружи защиты, где
  // рождается источник), и полость — одному указателю нельзя присвоить две
  // разные важности сразу (найдено 12.08.2026 на практике: GeomBias1001,
  // ipre_over_ipost=1/128 — источник в "world" с важностью полости получал
  // обвальный roulette на первом же шаге). С отдельной "cavity" источник
  // остаётся в "world" (важность 1, естественная), а полость — в "cavity"
  // (важность слоя depth=0, без разрыва на входе).
  G4VPhysicalVolume* fCavityPV = nullptr;

  bool fWithShield = true;
  bool fWithDevice = true;

private:
  void BuildShield(G4LogicalVolume* world);
};
