// Цилиндрическая свинцовая защита для RadiaCode 101/102/103 с сосудом
// Маринелли 200 мл. Размеры в мм.
//
// ЗАДАЧА, ПОД КОТОРУЮ СДЕЛАНО. Проектный расчёт: как МДА по Cs-137 в пробе
// зависит от толщины свинца, и с какой толщины свинец перестаёт окупаться.
// Поэтому толщина здесь — свободный параметр, а полость ФИКСИРОВАНА: наружный
// габарит растёт вместе с толщиной, как у настоящей сборки из кирпичей.
//
// ПОЧЕМУ СЛОЙ СОБРАН ИЗ ТРЁХ ПРОСТЫХ ТЕЛ, А НЕ ВЫРЕЗАН БУЛЕВОЙ ОПЕРАЦИЕЙ.
// Три причины, все существенные:
//   1) скорость: пустотелая оболочка через G4SubtractionSolid считает
//      DistanceToIn/Out по двум телам на каждом шаге, а прогон стадии 1 —
//      самая дорогая часть работы;
//   2) координаты: прибор и сосуд остаются дочерними объёмами МИРА, чья
//      система отсчёта — центр кристалла (см. RCDetector.hh). Если бы полость
//      была физическим объёмом, прибор пришлось бы класть внутрь неё со
//      сдвигом, то есть править проверенный код размещения;
//   3) биасинг: каждый кусок — отдельная ячейка G4IStore. Важность зависит
//      только от НОМЕРА слоя, поэтому обечайка, дно и крышка одного слоя
//      получают одно значение, и переход между ними расщепления не вызывает.
//
// Слой k с внутренним радиусом r и полувысотой h и толщиной d даёт:
//   обечайка  G4Tubs(rmin=r, rmax=r+d, halfz=h)        в z = zCav
//   дно       G4Tubs(0, r+d, halfz=d/2)                в z = zCav - h - d/2
//   крышка    то же                                     в z = zCav + h + d/2
// после чего r += d, h += d. Стык точный, пересечений нет по построению,
// толщина стенки, дна и крышки одинакова — как и требует постановка.
//
// ПОРЯДОК СЛОЁВ от полости наружу: Cu -> Cd -> Pb. Тот же, что у защиты
// Гамма-1С (G1SDetector.cc:570-572) и по той же причине: K-рентген свинца
// 72..88 кэВ гасится кадмием, K-рентген кадмия ~23 кэВ — медью. Значения
// K-краёв и линий проверяются по первоисточнику, а не назначаются здесь.
#pragma once
#include "RCDetector.hh"

#include <vector>

class G4VPhysicalVolume;

struct ShieldGeom {
  // --- полость -------------------------------------------------------------
  // ФИКСИРОВАНА. Подобрана под сосуд m200 с прибором:
  //   радиально  юбка крышки сосуда 40.25 -> зазор 9.75 мм;
  //   по оси     низ крышки сосуда z = -36.61, хвост прибора z = +111.00
  //              (RCDetector: nose = -crystalZ0 = -12, caseZ = 123),
  //              то есть занято -36.61..+111.00; полость -55..+125 даёт
  //              18.4 мм снизу и 14.0 мм сверху на кабель и посадку.
  // Проверка вместимости делается в коде, а не на словах: BuildShield()
  // сверяет габариты и отказывается строить, если прибор не влезает.
  double rCav  = 50.0;
  double hzCav = 90.0;
  double zCav  = 35.0;   // центр полости в мировой системе (центр кристалла)

  // --- слои от полости наружу ----------------------------------------------
  double cu = 0.0;       // медный вкладыш, 0 = вкладыша нет
  double cd = 0.0;       // кадмиевый вкладыш, 0 = вкладыша нет
  double pb = 50.0;      // свинец

  // На сколько вложенных слоёв резать свинец. Нужно ТОЛЬКО для расщепления по
  // важности: карта важностей одномерна по глубине, и слои — её ячейки.
  // На физику не влияет (материал один), на скорость влияет слабо.
  // Проверка (iv) требует, чтобы результат не зависел от этого числа.
  int nShellPb = 8;
};

class RCShieldDetector : public RCDetector {
public:
  // withDevice=false — ДЛЯ СТАДИИ 1 конвейера снижения дисперсии: полость
  // остаётся пустым воздухом (без прибора, без сосуда), и проверка
  // вместимости в BuildShield() тогда пропускается — проверять нечего.
  // Комбинация withDevice=false, withVessel=true запрещена логикой: сосуд без
  // прибора внутри него не строился и не имеет смысла (см. Construct()).
  explicit RCShieldDetector(bool withVessel = true, bool withShield = true,
                            bool withDevice = true);
  G4VPhysicalVolume* Construct() override;

  ShieldGeom fSh;

  // Физические объёмы слоёв ОТ ПОЛОСТИ НАРУЖУ вместе с глубиной каждого:
  // fLayerDepth[i] — номер слоя (0 = ближайший к полости), одинаковый у
  // обечайки, дна и крышки. Отсюда строится G4IStore.
  std::vector<G4VPhysicalVolume*> fLayerPV;
  std::vector<int>                fLayerDepth;
  int fNDepth = 0;                 // сколько слоёв всего

  double fOuterR = 0., fOuterHz = 0.;   // наружный габарит собранной защиты
  double fMassPb = 0., fMassCd = 0., fMassCu = 0.;   // кг

  // Нижняя граница полуразмера мира по XY, мм. 0 = не задана (мир считается
  // только по габариту защиты, прежнее поведение — побитово). Нужна режиму
  // mode=muon: диск-источник мюонов может быть ШИРЕ защиты, и если мир по
  // нему не расширить, часть диска окажется снаружи мира. Найдено 13.08.2026
  // на развёртке по радиусу диска: при pb=50 мир имеет полуразмер XY 130 мм,
  // а диски 140..600 мм торчали наружу — «выход на полку» в той развёртке
  // был артефактом обрезания диска гранью мира, а не физикой.
  double fWorldMinHalfXY = 0.0;

  // Строить ли ВЕРХНЮЮ крышку защиты. true — прежнее поведение (закрытый
  // цилиндр, все проектные расчёты). false — открытая сверху защита: именно
  // так собран реальный домик оператора (сообщено 13.08.2026), и только для
  // такой геометрии законно сравнивать модель с его измерением
  // «Фон домик 23 дня». Без крышки поле помещения входит в полость сверху
  // не ослабленным, а мюоны (cos²θ, идут преимущественно сверху) попадают в
  // кристалл вообще без свинца.
  bool fWithLid = true;

  // Именованная "полость" — ТОЛЬКО когда fWithDevice=false (стадия 1/beam):
  // отдельный физический объём воздуха (совпадает по размеру с полостью),
  // сосед "world", а не сам "world". Нужен для importance-биасинга (задача
  // №2): G4IStore ключует по G4VPhysicalVolume*, а "world" в этой геометрии
  // до сих пор одновременно и внешнее пространство (снаружи защиты, где
  // рождается источник), и полость — одному указателю нельзя присвоить две
  // разные важности сразу (найдено 12.08.2026 на практике: GeomBias1001,
  // ipre_over_ipost=1/128 — источник в "world" с важностью полости получал
  // обвальный roulette на первом же шаге). С отдельной "cavity" источник
  // остаётся в "world" (важность 1, естественная), а полость — в "cavity"
  // (важность слоя depth=0, без разрыва на входе).
  G4VPhysicalVolume* fCavityPV = nullptr;

  bool fWithShield = true;
  bool fWithDevice = true;

private:
  void BuildShield(G4LogicalVolume* world);
};
