// Геометрия RadiaCode 101/102/103 и авторского сосуда Маринелли 200 мл.
// Размеры в мм. Происхождение каждого числа помечено в RCDetector.cc.
//
// МИРОВАЯ СИСТЕМА КООРДИНАТ: начало — в ЦЕНТРЕ КРИСТАЛЛА; ось Z вдоль длинной
// оси прибора, +Z к хвосту прибора (вверх при измерении), нос смотрит в -Z.
// Поэтому нос прибора всегда в z = -crystalZ0 = -12.00.
// Ось Y — толщина прибора; -Y — та большая грань, к которой кристалл ближе
// (8.20 мм): там дисплей, основная плата и фотоприёмник.
#pragma once
#include "G4VUserDetectorConstruction.hh"
#include "globals.hh"

#include <vector>

class G4LogicalVolume;
class G4Material;
class G4VSolid;

// --- Прибор -----------------------------------------------------------------
struct DeviceGeom {
  double caseX = 34.00, caseY = 17.50, caseZ = 123.00;  // ЧЕРТЁЖ
  double caseEdgeR = 5.00;  // ДОПУЩЕНИЕ: радиус продольных рёбер корпуса
  double wallSide = 2.70;   // ЧЕРТЁЖ (промер пикселей): стенка по бокам (±X)
  double wallFace = 1.50;   // ЧЕРТЁЖ (промер): стенка по большим граням (±Y)
  double wallNose = 2.00;   // ДОПУЩЕНИЕ: пластик носа до полости
  double wallTail = 2.00;   // ДОПУЩЕНИЕ: то же у хвоста
  double airEdgeR = 3.00;   // ДОПУЩЕНИЕ: радиус рёбер внутренней полости

  double crystal       = 10.00;  // ПАСПОРТ+ЧЕРТЁЖ: CsI(Tl), куб 1 см³
  double crystalZ0     = 12.00;  // ЧЕРТЁЖ: торец носа -> ЦЕНТР кристалла
  double crystalToFace =  8.20;  // ЧЕРТЁЖ: большая грань -> ЦЕНТР кристалла

  // ФОТО разборки: кристалл сидит в белой отражающей чашке с окном под SiPM,
  // чашка — в отдельном чёрном модуле у носа, связанном с платой шлейфом.
  double reflector = 1.25;   // ФОТО: толщина белой чашки (окно со стороны SiPM)
  double sipm      = 0.40;   // ДОПУЩЕНИЕ: кремний фотоприёмника
  double sipmSide  = 6.00;   // ФОТО: кристалл SiPM ~6x6 мм
  double subT = 0.60, subDia = 10.00;  // ФОТО: круглая платка SiPM

  double pcbT = 1.00, pcbX = 26.00;    // ФОТО: основная плата, весь корпус
  double pcbZ0 = 8.00, pcbZ1 = 106.00; //   от модуля детектора к разъёму

  // ФОТО: на элементе читается маркировка 602560 3.7V 1000mAh => 6.0 x 25 x 60
  double battT = 6.00, battX = 25.00;
  double battZ0 = 47.00, battZ1 = 107.00;

  double dispT = 1.00, dispX = 22.00;  // ДОПУЩЕНИЕ: дисплей со стороны -Y
  double dispZ0 = 20.00, dispZ1 = 70.00;
};

// --- Сосуд Маринелли, авторский ---------------------------------------------
// Оба сосуда — печатные модели автора dnpro, лицензия CC BY:
//   m200  «200 ml v.2 Marinelli Beaker for RadiaCode 101, 102, 103», 03.04.2024
//         https://www.thingiverse.com/thing:6562353
//         файлы v.2_-_Can_200_ml_-_RC-Mr.stl, v.2_-_Cap_200_ml_-_RC-Mr.stl
//   m500  «500 ml v.1 - Marinelli Beaker for RadiaCode 101, 102, 103», 20.11.2023
//         https://www.thingiverse.com/thing:6325102
//         файлы Marinelli_Beaker_for_RadiaCode_101.stl, ..._cap_....stl
// Все размеры — ПРОМЕР STL лучевым сканированием (analysis/measure_stl.py),
// независимо от того, что написано в описании модели.
// Координата чертежа z_can: 0 — наружная плоскость со щелью под прибор, растёт
// внутрь сосуда. Пересчёт в мир: z = zSlot - z_can.
struct VesselGeom {
  G4String name = "m200";

  // Наружный обвод. У m200 это цилиндр (outerR > 0). У m500 стенка переменной
  // толщины, от 2 мм у горловины до 12 мм в поясе, и наружная поверхность не
  // осесимметрична (рёбра); задаётся медианным по окружности радиусом —
  // проверено по полному объёму пластика, сходится на 2.7 %.
  double outerR  = 36.05;   // STL: наружный радиус стакана
  std::vector<double> profZcan, profR;   // непустой — обвод по точкам

  double innerR  = 33.24;   // STL: внутренний радиус (стенка 2.81)
  double barrelH = 69.30;   // STL: высота стакана до среза горловины
  double endWall =  2.80;   // STL: торцевая стенка со стороны щели

  // Колодец повторяет форму прибора: скруглённый прямоугольник, стенка 1.25 мм.
  double wellOutX = 18.60;  // STL: полуширина наружной поверхности гильзы
  double wellOutY = 10.35;  // STL: полутолщина наружной поверхности гильзы
  double wellOutR =  6.75;  // STL: радиус углов сечения (по угловому профилю R)
  double wellInX  = 17.35;  // STL: полуширина полости
  double wellInY  =  9.07;  // STL: полутолщина полости
  double wellInR  =  5.50;  // STL: радиус углов полости (6.75 - 1.25)
  double wellTip    = 47.81; // STL: z_can вершины полости колодца
  double wellTipOut = 49.10; // STL: z_can вершины наружной поверхности гильзы
  // Зазор посадки. Значение выбрано так, чтобы центр носового купола полости
  // совпал с центром купола корпуса (8.75 - 9.07 + 0.64): тогда полость объемлет
  // корпус при любом Z и составное тело не даёт пересечений. Физически это
  // «прибор не досажен на треть миллиметра» — на положение кристалла влияет в
  // пределах 0.1 мм.
  double seatGap    =  0.32; // ДОПУЩЕНИЕ

  double capT = 2.80;        // STL: толщина диска крышки
  double capH = 12.20;       // STL: полная высота крышки
  double capSkirtR = 40.25;  // STL: наружный радиус юбки

  double sampleDensity = 1.00;      // г/см³
  G4String sampleMatrix = "water";  // матрица пробы, см. MakeMatrix()
  // Печатный пластик: PLA | PETG, шестой аргумент rc_curves. Умолчание PLA —
  // из него напечатаны те экземпляры, на которых сделаны измерения; автор
  // моделей рекомендует Pet-G, и напечатанный по его совету сосуд надо считать
  // с PETG. На результат выбор влияет мало: линейный коэффициент ослабления
  // отличается на 0.8 % при 100 кэВ и 0.5 % при 60 кэВ, а на пути через
  // торцевую стенку 2.8 мм это 0.04 % пропускания — ниже статистики прогонов.
  // Размеры сосуда от материала не зависят.
  G4String plasticMat  = "PLA";

  static VesselGeom Preset(const G4String& name);   // "m200" | "m500"
};

class RCDetector : public G4VUserDetectorConstruction {
public:
  // withVessel=false — «голый» прибор в воздухе (проверка 30 cps/(мкЗв/ч))
  explicit RCDetector(bool withVessel = true);
  G4VPhysicalVolume* Construct() override;

  // Матрица пробы: water | soil | ash | organic | air.
  // Плотность задаётся отдельно, поэтому одна матрица покрывает диапазон проб
  // (насыпной грунт 0.8..1.6, зола 0.4..0.9, зерно 0.5..0.8 и т.д.).
  // g4name — имя создаваемого материала; отличается от "Sample" только когда
  // нужно построить несколько матриц сразу (расчёт коэффициентов ослабления).
  static G4Material* MakeMatrix(const G4String& name, double densityGcm3,
                                const G4String& g4name = "Sample");

  G4LogicalVolume* fCrystalLV = nullptr;
  G4LogicalVolume* fSampleLV  = nullptr;
  double fSampleVolumeCm3 = 0.0;   // считается по построенному телу

  DeviceGeom fDev;
  VesselGeom fVes;

  // Тело прибора/колодца: в сечении — скруглённый прямоугольник 2hx x 2hy с
  // радиусом углов r; носовой торец при -Z скруглён радиусом hy, торец при +Z
  // плоский; полная длина len.
  // ВАЖНО: начало координат готового тела не в центре габарита, а в центре
  // прямой части — на CapOriginFromTip от вершины носа.
  static G4VSolid* Capsule(const G4String& nm, double hx, double hy, double r,
                           double len);
  static double CapOriginFromTip(double hy, double len) { return 0.5 * (len + hy); }

  // Полуразмеры мира, мм. Умолчания — исторические (мир 300 x 300 x 400),
  // при них геометрия побитово та же, что до введения этих полей.
  // Свинцовая защита наружу выходит далеко за прибор, и наследнику нужен мир
  // больше; менять их надо ДО Construct().
  double fWorldHalfXY = 150.0;
  double fWorldHalfZ  = 200.0;

protected:
  // Открыты наследнику (RCShieldDetector): защита строится вокруг ТОГО ЖЕ
  // прибора и сосуда. Дублировать их размещение в другом файле нельзя — это
  // второй источник истины для геометрии.
  void DefineMaterials();
  void BuildDevice(G4LogicalVolume* world);
  void BuildVessel(G4LogicalVolume* world);

  bool fWithVessel = true;
};
