"""Проверка репозитория перед публикацией: локальные пути, имена, номера.

Запускать ПЕРЕД каждым коммитом, который уходит в публичный репозиторий.
Ловит то, что нельзя вычистить задним числом: попав в историю git, локальный
путь или фамилия остаются там навсегда.

    python tools/check_paths.py [корень]

Возврат: 0 — чисто, 1 — есть находки.

Если задана переменная ANON_MAP (карта обезличивания, лежит ВНЕ
репозитория), проверка дополнительно ищет точные подлинные фамилии и номера
из неё. Это самая надёжная часть: без догадок и без ложных срабатываний.
Без карты работают только общие шаблоны, и они заведомо слабее.

--------------------------------------------------------------------------
ЧЕТЫРЕ СЛЕПЫХ ПЯТНА ПЕРВОЙ ВЕРСИИ
--------------------------------------------------------------------------
Первая версия отчиталась «чисто», а в публикацию ушли восемь фамилий в
четырёх сотнях файлов и подлинный заводской номер. Почему:

1. ДВОИЧНЫЕ ФАЙЛЫ ПРОПУСКАЛИСЬ ЦЕЛИКОМ. Если файл не декодировался ни в
   UTF-8, ни в CP-1251, проверка молча шла дальше. Формат ЛСРМ .spe не
   декодируется никогда: за текстовым заголовком идёт двоичный блок
   отсчётов. Именно в этих заголовках и стояло «OPERATOR=Фамилия И.О.».
   Теперь у таких файлов проверяется заголовок до метки «SPECTR=».

2. ФАМИЛИЯ ИСКАЛАСЬ ТОЛЬКО ВМЕСТЕ С ИНИЦИАЛАМИ. Шаблон «Фамилия И.О.» не
   видел ни одиночной фамилии в названии пробы, ни фамилии в имени файла.

3. ИМЕНА ФАЙЛОВ ПРОВЕРЯЛИСЬ ТОЛЬКО НА ПУТИ. Номера и фамилии в именах не
   искались вовсе — а утёк заводской номер именно так, в имени каталога
   и восьми файлов кривых эффективности.

4. АРХИВЫ И БАЗЫ ЗАНОСИЛИСЬ В ИСКЛЮЧЕНИЯ. .zip, .rar, .mdb пропускались как
   «двоичные», хотя внутри лежали необезличенные копии тех же спектров.
   Проверить их содержимое эта программа не может, поэтому теперь она о них
   ЗАЯВЛЯЕТ: такой файл либо распаковывают и обезличивают, либо не публикуют.
"""
import json
import os
import re
import sys

SKIP_DIRS = {".git", "__pycache__", "build", ".venv"}
# Растры и документы: текста для проверки в них нет, а разбирать их нечем.
SKIP_EXT = (".png", ".jpg", ".jpeg", ".gif", ".pdf", ".pyc")
# Контейнеры: содержимое скрыто. Не пропускать молча — заявлять (пятно 4).
OPAQUE_EXT = (".zip", ".rar", ".7z", ".mdb", ".xlsx", ".docx")

CHECKS = [
    # Любой путь с буквой диска, а не только Users|Windows|Program. Прежний
    # шаблон пропустил каталоги личных облачных дисков в пяти provenance.json
    # и рабочий стол ещё в четырёх: облако монтируют куда угодно, и
    # перечислить все его имена заранее нельзя. Что заведомо безобидно —
    # в ALLOW_PATH ниже, по одной строке с обоснованием.
    ("абсолютный путь", re.compile(r"[A-Za-z]:\\{1,2}[^\\/:*?\"<>|\r\n]+")),
    ("домашний каталог", re.compile(r"(?:USERPROFILE|/home/|/Users/)")),
    ("фамилия/инициалы", re.compile(
        r"\b[А-ЯЁ][а-яё]{3,}\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.")),
    # Без пробела между знаком и числом: «# 511» в коде — это комментарий,
    # а не номер. Иначе половина находок — ложные.
    ("серийный номер", re.compile(
        r"(?:№|#)0?\d{2,4}(?:[.\-]\d{2,4})?(?![\d.\-])")),
    # Заводской номер прибора пишут и без знака номера — так он и утёк.
    ("номер прибора", re.compile(r"(?<![\d.])0\d{3}-\d{2}(?![\d.])")),
    ("почта", re.compile(r"[\w.\-]+@[\w.\-]+\.\w+")),
    ("токен", re.compile(r"gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}")),
]
# Псевдонимы — это НЕ находка
ALLOW = re.compile(r"S[NR]C?-\w+|SN-\d+|Опер-\d+|Проба-\d+")

# Пути, которые не говорят о владельце ничего. Каждая строка — с обоснованием,
# добавлять сюда только так.
ALLOW_PATH = re.compile(
    # C:\Lsrm (и C:\LSRM) — каталог, куда по умолчанию ставится ПО ЛСРМ. Один
    # и тот же у всех пользователей, встречается 4165 раз в 655 служебных
    # файлах самой программы внутри reference/lsrm. Вычищать его — значит
    # править чужие рабочие файлы без всякой пользы.
    r"^[Cc]:\\{1,2}[Ll][Ss][Rr][Mm](\\|$)",
    re.IGNORECASE)
CSS_COLOR = re.compile(r"#[0-9a-fA-F]{3,8}(?![0-9a-zA-Z])")
WEB_EXT = (".html", ".htm", ".css", ".svg")
MARK = b"SPECTR="
# Встроенные картинки: страница обязана открываться без внешних запросов,
# поэтому рисунки лежат в ней как base64. Случайных «045» и «309» в мегабайте
# такой каши сколько угодно, и это единственный источник ложных находок,
# который не устраняется уточнением шаблона. Вырезаем полезную нагрузку.
DATA_URI = re.compile(r"data:[\w.+-]*/?[\w.+-]*;base64,[A-Za-z0-9+/=\s]+")

# Файлы, которые сами перечисляют образцы находок, — не считать находкой.
# build_article.py проверяет собранную страницу тем же списком запрещённых
# подстрок, поэтому список в нём есть по делу.
SELF = ("check_paths.py", "anonymize.py", "build_article.py")


def load_names():
    """Фамилии, номера и каталожные обозначения из карты обезличивания.

    Третий список — исключения: обозначения наборов ОИСН, которые остаются
    в данных намеренно. Раньше они отсеивались по длине ключа, и вместе с
    ними мимо проверки проходили настоящие номера экземпляров.
    """
    mp = os.environ.get("ANON_MAP")
    if not mp or not os.path.isfile(mp):
        return [], [], set()
    with open(mp, encoding="utf-8") as fh:
        m = json.load(fh)
    return (sorted((m.get("names") or {})), sorted((m.get("serials") or {})),
            set(m.get("catalog") or []))


def text_of(path):
    """Текст файла или текстовый заголовок двоичного .spe; None — нечего смотреть."""
    raw = open(path, "rb").read()
    for enc in ("utf-8", "cp1251"):
        try:
            t = raw.decode(enc)
        except UnicodeDecodeError:
            continue
        if path.lower().endswith(WEB_EXT):
            t = DATA_URI.sub("data:BASE64", t)
        return t
    # Пятно 1: .spe целиком не декодируется, но заголовок — обычный CP-1251.
    i = raw.find(MARK, 0, 65536)
    if i >= 0:
        return raw[:i + len(MARK)].decode("cp1251", errors="replace")
    return None


def scan(root):
    names, serials, catalog = load_names()
    hits, opaque = [], []
    for r, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for fn in files + dirs:
            p = os.path.join(r, fn)
            rel = os.path.relpath(p, root)
            low = fn.lower()

            if low.endswith(OPAQUE_EXT):
                opaque.append(rel)
                continue

            # Имя файла или каталога проверяем ВСЕГДА и по всем шаблонам:
            # заводской номер утёк именно в имени (пятно 3).
            fields = [(rel, " (в имени)")]
            if os.path.isfile(p) and not low.endswith(SKIP_EXT):
                t = text_of(p)
                if t is not None:
                    fields.append((t, ""))

            for txt, where in fields:
                for name, rx in CHECKS:
                    for m in rx.finditer(txt):
                        s = m.group(0)
                        if ALLOW.search(s):
                            continue
                        if name == "абсолютный путь" and ALLOW_PATH.match(s):
                            continue
                        if low.endswith(WEB_EXT):
                            if CSS_COLOR.match(txt[m.start():m.start() + 10]):
                                continue      # цвет в стилях, а не номер
                            if name == "фамилия/инициалы":
                                # В статьях фамилии — это БИБЛИОГРАФИЯ (авторы
                                # книг и методик). Обезличивать надо спектры и
                                # паспорта, а не список литературы.
                                continue
                        if os.path.basename(p) in SELF:
                            continue
                        hits.append((rel, name + where, s.strip()[:60]))

                # Точная проверка по карте — самая надёжная (пятно 2).
                if os.path.basename(p) in SELF:
                    continue
                if not (low.endswith(WEB_EXT) or rel.startswith("docs" + os.sep)):
                    # Фамилии в статье — авторы книг в списке литературы.
                    for who in names:
                        if who in txt:
                            hits.append((rel, "ФАМИЛИЯ ПО КАРТЕ" + where, who))
                for num in serials:
                    # Короткие ключи вроде «420» или «309» — каталожные
                    # обозначения наборов ОИСН; они оставлены намеренно и
                    # встречаются внутри обычных чисел, искать их бессмысленно.
                    # Но порог «короче шести» отсекал и настоящие номера
                    # экземпляров — 4213, 5431, 045 в паспортах .src прошли
                    # мимо проверки именно так. Теперь пропускаем только то,
                    # что помечено в карте как каталожное (catalog).
                    if num in catalog:
                        continue
                    if len(num) < 3:
                        continue
                    # Запятая в границах — десятичный разделитель в русской
                    # локали: intensity="0,045" номером источника не является.
                    if re.search(r"(?<![\d.,])" + re.escape(num) + r"(?![\d.,])",
                                 txt):
                        hits.append((rel, "НОМЕР ПО КАРТЕ" + where, num))
    return hits, opaque


if __name__ == "__main__":
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(
        os.path.dirname(os.path.abspath(__file__)))
    if not os.environ.get("ANON_MAP"):
        print("ANON_MAP не задана: точная проверка по карте подлинных фамилий\n"
              "и номеров не выполняется, работают только общие шаблоны.\n")
    found, opaque = scan(root)

    if opaque:
        print("НЕПРОЗРАЧНЫЕ ФАЙЛЫ — содержимое проверить нечем:")
        for rel in sorted(set(opaque)):
            print("   ", rel)
        print("Распакуйте и обезличьте либо не публикуйте: внутри архивов уже\n"
              "находились необезличенные копии спектров.\n")

    seen = set()
    for rel, name, s in found:
        key = (rel, name, s)
        if key in seen:
            continue
        seen.add(key)
        print("%-58s %-24s %s" % (rel[:58], name, s))

    if not seen and not opaque:
        print("чисто: локальных путей, имён, серийных номеров и токенов нет")
        sys.exit(0)
    if seen:
        print("\nнаходок: %d — публиковать НЕЛЬЗЯ" % len(seen))
    sys.exit(1 if seen or opaque else 0)
